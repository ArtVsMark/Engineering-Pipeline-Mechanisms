"""Адреса каталога правил — в одном месте на всех читателей.

ЗАЧЕМ ОТДЕЛЬНЫМ МОДУЛЕМ. Выгрузку каталога читают сверка ссылок, дрейф, карта
ревью и сверка чужого разбора. Адрес у неё был написан в каждом из них заново —
четыре копии одной строки, — и переезд каталога чинился бы поиском по дереву,
а не правкой одного места
([022](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/022-one-canonical-document.md),
[090](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/090-shared-helpers-move-up-not-sideways.md)).
Пятый читатель и стал поводом поднять общее вверх, а не приписать вбок.

ЗДЕСЬ АДРЕСА И ОДИН СПОСОБ ИХ ПРОЧИТАТЬ. Что делать с прочитанным, каждый
читатель решает сам: дрейф сравнивает числа, сверка ссылок — имена, карта ревью
строит подсказку. Свести это в «общий разбор каталога» значило бы связать
разные предметы одной формой.

ИСКЛЮЧЕНИЕ ОДНО, И ОНО НЕ РАЗБОР: статус правила (`rule_status`). Это поле
договора выгрузки, а не толкование, и прочитанное двумя читателями по-разному
оно давало бы два каталога — дрейф читал ссылку `superseded_by`, значок
каталога — слово `status` (#1563). Поэтому «чем заменено» отвечается здесь,
и «действует ли» ляжет сюда же, а что с этим делать — по-прежнему решает читатель.

А вот САМО ЧТЕНИЕ у всех одно, и различает оно два состояния, которые прежде
сливались: «каталог ответил» и «каталог не ответил». Второе — отказ КАНАЛА, а не
находка о нашем дереве, и держать слияние он не вправе
([084](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/084-best-effort-channels-never-block-the-main-path.md)).
Это уже стоило красного: 16.09.2026 на голове #370 обязательная проверка
`journal` дала зелёное, красное и снова зелёное на ОДНОМ дереве — упал шаг
«чужой разбор приведён ссылкой», и упал он на чтении выгрузки. Общая ветка за те
три минуты не двигалась, то есть дерево было то же; очередь встала из-за канала.

Проект уже решил этот класс — и решил иначе. `tests/test_rule_links.py` при
недоступном каталоге ПРОПУСКАЕТСЯ, и причина записана там же: «её предмет тогда
недоступен, и падение говорило бы о канале». Два места применяли одну доктрину
по-разному; здесь она сведена к одному чтению.
"""

from typing import Any, Final

import ghrest
import report

#: Репозиторий каталога: владелец и имя, как их знает площадка.
REPO: Final = "ArtVsMark/Engineering-Incidents-Playbook"

#: Приставка семьи у ссылок `uses:` — владелец каталога. Одна на двух судей
#: версий действий: дрейф её не судит, гейт заготовки (155) судит только её, и
#: выводится она здесь, а не буквами у каждого (взгляд на #1006, 022).
FAMILY_PREFIX: Final = f"{REPO.split('/')[0]}/"

#: Корень сырых файлов каталога. Ветка называется в самом адресе: выгрузка
#: живёт на `main`, снимок «у кого чем держится» — на ветке значков.
RAW: Final = f"https://raw.githubusercontent.com/{REPO}"

#: Выгрузка правил: номера, имена файлов, разбор.
EXPORT_URL: Final = f"{RAW}/main/export/rules.json"

#: Снимок семьи: кто из соседей чем держит правило.
WHERE_URL: Final = f"{RAW}/badges/export/where.json"

#: Ответ каталога на предложения: вердикты по нашим записям.
PROPOSALS_URL: Final = f"{RAW}/main/.rules/proposals.json"

#: НАБОР ВОПРОСОВ ВИТРИНЫ — ЭТАЛОН, А НЕ НАША ПАМЯТЬ. Список один на все
#: проекты семьи, и живёт он у каталога; наш файл — копия, снятая рукой. Копия,
#: которую не с чем сверить, расходится молча
#: ([055](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/055-your-own-expectations-are-a-hypothesis.md)).
SHOWCASE_URL: Final = f"{RAW}/main/.rules/showcase.json"


def is_catalogue(repo: str) -> bool:
    """Имя `владелец/репозиторий` — сам каталог; сравнение без учёта регистра.

    ОДИН ПРЕДИКАТ НА ВСЕХ СПРАШИВАЮЩИХ (взгляд на #1646, `42106cc`): прежде
    `check_foreign_why` сравнивал через `.lower()`, а `debt.catalogue_tree` —
    через `casefold()`, и третий спрашивающий завёл бы третью. ГРАНИЦА —
    ТОЧНОЕ ИМЯ: форк или переименованный каталог каталогом не считается, и
    гейт судит его как обычно — ошибка в сторону громкости (051). Пустое имя —
    не каталог.
    """
    return bool(repo) and repo.casefold() == REPO.casefold()


class Silent(RuntimeError):
    """Каталог не ответил.

    Отдельный класс, а не общий отказ чтения: «канал молчит» и «в выгрузке нет
    предмета» дают одинаковое бездействие и значат разное. Первое — состояние
    СЕТИ, и чинить его в дереве нечем; второе — поломка договора с каталогом, и
    она обязана краснеть
    ([039](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/039-three-outcomes-not-two.md)).
    """


def read(url: str) -> dict[str, Any]:
    """Снимок каталога по адресу; молчание канала поднимается своим классом.

    Читатель ловит `Silent` отдельно и отвечает на него СВОИМ исходом — не
    зелёным. Зелёное здесь было бы молчаливым отключением гейта: снаружи оно
    неотличимо от настоящей проверки
    ([045](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/045-no-silent-fallback.md)).
    """
    try:
        return ghrest.raw_json(url)
    except ghrest.TransportError as exc:
        raise Silent(f"каталог не ответил ({url}): {report.cut(str(exc))}") from exc


def read_text(url: str) -> str:
    """Тот же канал, но для файла каталога, а не выгрузки.

    Разбор правила живёт в его собственном файле, и адрес этого файла берётся
    из выгрузки, а не пишется рукой: рукописный путь к чужому документу гниёт
    первым же переименованием
    ([005](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/005-hand-written-numbers-rot.md)).

    Молчание канала — тот же третий исход, что и у выгрузки: читатель ловит
    `Silent` и отвечает на него своим состоянием, а не красным о дереве (084).
    """
    try:
        return ghrest.raw_text(url)
    except ghrest.TransportError as exc:
        raise Silent(f"каталог не ответил ({url}): {report.cut(str(exc))}") from exc


#: Слова поля `status` правила в выгрузке 1.9: действует или заменено.
ACTIVE: Final = "active"
SUPERSEDED: Final = "superseded"


class BadExport(ValueError):
    """Выгрузка прочитана, но не той формы: списка правил в ней нет.

    Не `Silent`: канал ответил, а договор выгрузки сломан, и это краснеет у
    читателя, а не гасится как молчание сети (039).
    """


def rules_of(export: dict[str, Any]) -> list[dict[str, Any]]:
    """Записи правил выгрузки; списка нет — `BadExport`, а не «правил ноль».

    Пустой список по умолчанию отдал бы «действующих 0» и «замен нет» — ответ
    там, где ответа нет (075).
    """
    said = export.get("rules") if isinstance(export, dict) else None
    if not isinstance(said, list):
        raise BadExport("в выгрузке каталога нет списка «rules»")
    return [rule for rule in said if isinstance(rule, dict)]


def rule_status(rule: dict[str, Any]) -> str:
    """Статус правила выгрузки — ОДНО чтение на всех читателей.

    ДВА ПОЛЯ, ОДИН ОТВЕТ. С выгрузки 1.9 статус назван словом (`status`), до
    1.9 — отсутствием `superseded_by`. Слово сильнее: правило со ссылкой на
    заменяющее, но в статусе `active`, действует. Прежде дрейф читал только
    `superseded_by`, а значок каталога — слово, и разошлись бы они молча, как
    только каталог сменил бы одно поле без другого (#1563, 214).
    """
    said = rule.get("status")
    if said is not None:
        return str(said)
    return SUPERSEDED if rule.get("superseded_by") else ACTIVE


def replacements(export: dict[str, Any]) -> dict[str, str]:
    """Замены правил: номер заменённого → номер заменяющего.

    Замена — правило в статусе `superseded` С адресом заменяющего. Заменённое без
    адреса здесь не заменой: подставить на его место нечего, и дрейф судит его
    находку прежним путём, как работу (045).
    """
    return {
        str(rule.get("id")): str(rule["superseded_by"])
        for rule in rules_of(export)
        if rule_status(rule) == SUPERSEDED and rule.get("superseded_by")
    }


def active_rules(export: dict[str, Any]) -> set[str]:
    """Номера действующих правил выгрузки — тем же чтением статуса, что у замен (214).

    Знаменатель значка проекта: ответ о заменённом правиле законен, но правилом
    оно больше не является (каталог, решение владельца 17.10).
    """
    return {str(rule.get("id")) for rule in rules_of(export) if rule_status(rule) == ACTIVE}
