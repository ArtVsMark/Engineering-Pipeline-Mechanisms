def render_body(
    entries: dict[str, findings.Entry],
    swept_to: str = "",
    recorded: dict[int, int] | None = None,
) -> str:
    """Собирает тело живой задачи: заметки, а не счётчики.

    Записывается заголовок находки, а не число: «находок 2» не отвечает на
    вопрос, что делать, — за этим пришлось бы идти в слитое изменение.
    """
    lines = [
        MARKER,
        "",
        "> **Читатель:** окно, берущее работу. Это адресат находок внешнего",
        "> взгляда, переживающий слияние.",
        "",
        "Вес — из объявленной шкалы: "
        + " · ".join(f"`{name}` — {why}" for name, why in WEIGHTS.items())
        + f". `{UNWEIGHED}` значит, что ревьюер его не назвал.",
        "",
        "Запись снимается строкой `Разобрано: <отпечаток>` в теле изменения,",
        "которое её починило — снятие едет вместе с работой, а не отдельным",
        "жестом, который забудут. Задачу закрывает человек: механизм не знает,",
        "разобрана находка или просто надоела.",
        "",
        "Находку **об ОТВЕТЕ** снимает только изменение, тронувшее сам ответ",
        "(`.rules/bindings.json`): предмет у неё ровно один файл, и снятие без",
        "правки этого файла говорит о работе, которой нет. Отказ снятия",
        "называется вслух предупреждением, а запись остаётся.",
        "",
        f"Хвост «{findings.REFUTED}» ставит ВЕРИФИКАТОР — отдельный заход,",
        "входящий от ОДНОЙ находки и пытающийся её опровергнуть. Это НЕ снятие:",
        "находку снимает работа, а верификатор лишь говорит, что чинить, возможно,",
        "нечего — взгляд смотрит дифф изменения, а не нынешнюю общую ветку, и",
        "законно находит то, что уже починено. Решение за тем, кто берёт работу.",
        "",
    ]
    # ОТМЕТКА УБОРКИ — СРОК ЖИЗНИ СНЯТИЯ, СЧИТАННЫЙ ОТ ПРОЧТЕНИЯ. Без неё окно
    # было бы «последние тридцать закрытых», то есть отсчёт шёл бы от публикации
    # снятия и тем короче, чем быстрее мержатся соседи (079).
    lines += [f"Убрано до: {swept_to or NEVER_SWEPT}", ""]
    # ОТМЕТКА ЗАПИСАННЫХ ЗАХОДОВ — ПО НЕЙ ДОГОНЯЕТСЯ ВЫТЕСНЕННАЯ ЗАПИСЬ (#842).
    lines += [f"Записано: {render_recorded(recorded or {})}", ""]
    if entries:
        lines.append("## Не разобрано")
        lines.append("")
        # Порядок — по весу, а не по приходу: тяжёлое разбирают раньше, и
        # решать это должен не порядок появления (053).
        #
        # НЕНАЗВАННЫЙ ВЕС ИДЁТ ПЕРВЫМ, А НЕ ПОСЛЕДНИМ. Прежде он получал место
        # ЗА самой лёгкой категорией — то есть на практике трактовался как
        # «легче замечания», ровно в ту сторону, которую модуль обещает не
        # выбирать. Обещание и код разошлись молча, и нашёл это поздний взгляд
        # по общей ветке на #73.
        #
        # Первым — не потому, что «тяжелее», а потому, что неизвестное требует
        # взгляда, чтобы перестать быть неизвестным: очередь ведёт к разбору, а
        # не расставляет по важности. Ошибаться здесь можно только в сторону
        # «посмотреть лишний раз» (051).
        order = {name: place for place, name in enumerate(WEIGHTS)}
        # НАХОДКИ ОБ ОТВЕТЕ ИДУТ ПЕРВЫМИ, И ЭТО НЕ ВКУС. Карта, которую проект
        # выдаёт взгляду, говорит ему прямо: «это находка об ОТВЕТЕ, а не о
        # коде, и она дороже любой другой — ответ живёт годами и читается как
        # факт». Пока род не записывался, механизм объявлял их ценнее и терял
        # различие при записи: отдачу канала по ответам посчитать было нечем.
        порядок = sorted(
            entries.items(),
            key=lambda item: (
                item[1].kind != findings.ANSWER_KIND,
                order.get(item[1].weight, -1),
                item[1].pr,
            ),
        )
        об_ответе = [one for one in порядок if one[1].kind == findings.ANSWER_KIND]
        if об_ответе:
            lines.append("### Об ОТВЕТЕ каталогу — разбирать первыми")
            lines.append("")
            lines.append(
                "Ответ живёт годами и читается соседями как факт. Находка здесь говорит, "
                "что предмет правила в дереве ЕСТЬ, а ответ утверждает обратное."
            )
            lines.append("")
        for mark, entry in порядок:
            if об_ответе and entry is об_ответе[-1][1]:
                lines.append(f"- `{mark}` {entry.said()}")
                lines.append("")
                lines.append("### О коде")
                lines.append("")
                continue
            lines.append(f"- `{mark}` {entry.said()}")
    else:
        lines.append("## Не разобрано")
        lines.append("")
        lines.append("Пусто — все находки названы разобранными.")
    return "\n".join(lines) + "\n"


live_issue = findings.live_issue


#: Слова закрытой шкалы верификатора. Объявлены ОДИН раз и отсюда же собирается
#: образец: копия словаря рядом с образцом разошлась бы с ним молча
#: ([022](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/022-one-canonical-document.md)).
SAYS_YES: Final = "подтверждена"
SAYS_NO: Final = "не подтвердилась"

#: Ответ верификатора в комментарии захода. Слово из закрытой шкалы, причина —
#: необязательна у подтверждения и обязательна у опровержения: «не
#: подтвердилась» без причины не даёт разбирающему ничего (154).
#: РАЗМЕТКУ ЭТОТ ОБРАЗЕЦ ПЕРЕЖИВАЕТ ПО ПОСТРОЕНИЮ, А НЕ ПО ЗАМЕРУ, и это сказано
#: вслух. Верификатор — тот же ревьюер и тот же markdown, но за шестьдесят
#: изменений он не ответил НИ РАЗУ: строк «ПРЕМИСА:» в ленте ноль, и потерь
#: измерить не на чем. Ноль здесь — не «беды нет», а «предмета ещё не было»
#: ([075](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/075-a-guard-that-finds-nothing-must-fail.md)).
#: Форма у него общая с соседями по модулю, и чинить её порознь значило бы
#: ждать, пока та же потеря случится третий раз (206).
PREMISE_RE: Final = re.compile(
    rf"^{MARK}\s*ПРЕМИСА\s*:\s*(?P<said>{SAYS_YES}|{SAYS_NO})\s*"
    rf"(?:—\s*(?P<why>\S.*?))?\s*{MARK}\s*$",
    re.I,
)


def premise_of(comments: list[dict[str, Any]]) -> tuple[str, str] | None:
    """Последний ответ верификатора: («подтверждена»|«не подтвердилась», причина).

    Последний, а не первый: заход повторяют, и свежий ответ отменяет прежний —
    тем же правилом, что и вердикт находок.
    """
    found: tuple[str, str] | None = None
    for comment in comments:
        for line in bare_lines(comment.get("body") or ""):
            one = PREMISE_RE.match(line)
            if one is not None:
                found = (one["said"].lower(), (one["why"] or "").strip())
    return found


def verified(entry: findings.Entry, said: str, why: str, day: str) -> findings.Entry:
    """Дописывает к записи ответ верификатора, не трогая ничего другого.

    ЭТО НЕ СНЯТИЕ. Находку снимает работа строкой «Разобрано»; верификатор лишь
    говорит, что чинить, возможно, нечего: взгляд смотрит дифф изменения, а не
    нынешнюю общую ветку, и законно находит уже починенное. Замер 16.09.2026:
    находка `1fd43a4` описывала дефект, закрытый двумя днями раньше, и заметил
    это человек, а не механизм.

    Причина у опровержения переносится в запись целиком: без неё разбирающий
    узнаёт, что премиса не подтвердилась, и не узнаёт почему — то есть обязан
    проверять заново (046).
    """
    # СЛОВО СВЕРЯЕТСЯ ЦЕЛИКОМ, А НЕ ПО НАЧАЛУ. Прежде здесь стояло
    # `said.startswith("не")`: безопасно, пока шкалу держит образец выше, — но
    # связь эта невидима у самого сравнения, а функция открыта и принимает любую
    # строку. «Нейтрально», «независимо», «нельзя» прочлись бы как опровержение
    # ([141](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/141-a-marker-is-matched-whole-not-by-prefix.md)).
    head = findings.REFUTED if said.strip().lower() == SAYS_NO else findings.CONFIRMED
    tail = f"{head} {day}" + (f": {why}" if why else "")
    return replace(entry, checked=tail)


#: Докуда уборка уже дочитала слитое. Без отметки окно было бы «последние
#: тридцать закрытых» — то есть срок жизни снятия отсчитывался бы от его
#: ПУБЛИКАЦИИ и тем короче, чем быстрее мержатся соседи.
#:
#: ОТМЕТКА — ВРЕМЯ СЛИЯНИЯ, А НЕ НОМЕР ИЗМЕНЕНИЯ, И ЭТО ПОЧИНКА ПО ЗАМЕРУ.
#: Номер говорит, когда изменение ОТКРЫТО; сливаются они в другом порядке.
#: Изменение, простоявшее открытым, пока соседи с бо́льшими номерами уехали в
#: общую ветку, оказывалось НИЖЕ курсора в тот самый заход, который его впервые
#: увидел, — и его снятия не читались уже никогда.
#:
#: ЗАМЕР 17.09.2026 ПО ВСЕЙ ИСТОРИИ: из 386 слитых изменений 36 слились не в
#: порядке номера, и в них 76 отметок снятия, которых уборка не прочла ни разу.
#: Последний случай — #438: слит в 14:41, курсор к тому времени стоял на #442,
#: пять отметок остались в реестре неразобранными при сделанной работе
#: ([079](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/079-ttl-counts-from-completion.md)).
SWEPT_RE: Final = re.compile(r"^Убрано до: (\S+)\s*$", re.M)
#: Прежняя форма отметки — номер изменения. Читается на ВХОДЕ, чтобы подъём не
#: требовал ручной правки реестра; пишется всегда новая
#: ([022](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/022-one-canonical-document.md)).
LEGACY_SWEPT_RE: Final = re.compile(r"^#\d+$")
#: Что значит прежняя отметка при переводе. Времени в ней нет, и придумать его
#: нельзя: номер не говорит ни когда изменение слито, ни какие соседи уехали
#: раньше. Поэтому перевод — ПУСТО, то есть «читать всё, до чего дотянется
#: страница»: повторное чтение снятия безвредно (запись либо уже снята, либо
#: обязана быть снята), а пропуск — это те самые 76 отметок (039, 045).
LEGACY_MEANS: Final = ""
#: Чем записывается «не читала никуда». Заполнитель — ДЛЯ ЧЕЛОВЕКА, и это
#: проверено откатом: убрать его круговорот не ломает — образец требует
#: непробельного знака, поэтому пустой хвост строки и так читается как пусто.
#: Прежняя редакция комментария утверждала обратное, и откат её опроверг (014).
#:
#: А ВОТ ЧИТАТЬСЯ ОБРАТНО КАК ПУСТО ОН ОБЯЗАН, И ЭТО НЕ ОФОРМЛЕНИЕ.
#: Первая редакция писала «—» и читала его ЗНАЧЕНИЕМ курсора — а тире (U+2014)
#: больше любой даты ISO, то есть записанный однажды курсор «—» пропускал бы
#: ВСЁ и навсегда: уборка перестала бы читать снятия вообще, оставаясь зелёной.
#: Круговорот здесь — предмет проверки, а не аккуратность: тело задачи
#: единственное хранилище отметки, и что записано, то и будет прочитано
#: (нашёл внешний взгляд на #444; 049).
NEVER_SWEPT: Final = "—"


def parse_swept(body: str | None) -> str:
    """Докуда уборка дочитала — время слияния; пусто — не читала никуда.

    Прежняя отметка `#N` переводится в пусто, а не в время того изменения:
    время номера неизвестно, а догадка здесь стоила бы ровно того же пропуска,
    ради которого форма и меняется.
    """
    found = SWEPT_RE.findall(body or "")
    if not found:
        return ""
    last = found[-1].strip()
    if last == NEVER_SWEPT:
        return ""
    return LEGACY_MEANS if LEGACY_SWEPT_RE.match(last) else last


#: Какой заход взгляда записан у каждого изменения: номер и id комментария с
#: вердиктом. По ней запись и уборка догоняют заходы, чья запись вытеснена в
#: группе `findings-write` (#842). Хранится там же, где отметка уборки: тело
#: реестра — единственное место, которое обе записи читают и пишут.
RECORDED_RE: Final = re.compile(r"^Записано: (.*)$", re.M)
RECORDED_ONE_RE: Final = re.compile(r"#(\d+)@(\d+)")


def parse_recorded(body: str | None) -> dict[int, int]:
    """Отметка записанных заходов: номер изменения → id комментария с вердиктом."""
    found = RECORDED_RE.findall(body or "")
    if not found:
        return {}
    return {int(pr): int(look) for pr, look in RECORDED_ONE_RE.findall(found[-1])}


def render_recorded(recorded: dict[int, int]) -> str:
    """Отметка записанных заходов строкой; пусто пишется тем же знаком, что у уборки."""
    return " ".join(f"#{pr}@{look}" for pr, look in sorted(recorded.items())) or NEVER_SWEPT


def twins_of_resolved(
    swept: set[str],
    entries: dict[str, findings.Entry],
    *,
    strict: bool = False,
) -> dict[str, str]:
    """Открытые записи, которые — дубли снятых: отпечаток → снятый, чей он дубль.

    СВЕРКА ДУБЛЕЙ (решение владельца 25.09.2026, #807). Дубль — один дефект,
    названный дважды, и работа, снявшая одно имя, починила оба; висящий дубль
    снятого выдаёт закрытое за работу. Признак — ТОТ ЖЕ, что у реестра при
    записи (`pair_up`), целиком, а не один его порог (взгляд на #818):
    - то же изменение — беды разных изменений реестр держит раздельно;
    - `same_finding` с тем же `strict`: строгий заход (102) держит недословные
      заголовки отдельно, и уборка того же захода их не сводит;
    - тот же ФАЙЛ (`finding_chains.place_of` берёт путь без строки): совпавший
      файл тождеством сам не считается (#657), а без него сходство слов свело
      бы беды разных файлов;
    - тот же род записи: находку об ОТВЕТЕ снимает только правка ответа
      (`closable`), и дублем находки о коде она не уходит (взгляд на #818).
      Этого хватает и для записи с отвергнутым снятием: она всегда об ответе,
      а снятая запись того же изменения и рода была бы отвергнута тем же
      `closable`. Отдельное исключение для неё недостижимо (взгляд на #823).
    """
    # Импорт здесь, а не наверху: `finding_chains` сам читает этот модуль.
    import finding_chains

    found: dict[str, str] = {}
    gone = {mark: entries[mark] for mark in swept if mark in entries}
    for mark, entry in entries.items():
        if mark in gone:
            continue
        place = finding_chains.place_of(entry.title)
        for was, other in gone.items():
            if (
                place
                and entry.pr == other.pr
                and entry.kind == other.kind
                and place == finding_chains.place_of(other.title)
                and same_finding(entry.title, other.title, strict=strict)
            ):
                found[mark] = was
                break
    return found


def drop_resolved(
    entries: dict[str, findings.Entry],
    swept: set[str],
    *,
    strict: bool = False,
) -> dict[str, str]:
    """Убирает снятые записи и их дубли; отдаёт дубли, чтобы их назвать (#807)."""
    twins = twins_of_resolved(swept, entries, strict=strict)
    for mark in [*swept, *twins]:
        entries.pop(mark, None)
    return twins


#: Как отказ снятия называет снявших, не правивших ответ: одного и нескольких.
UNTOUCHED_ONE: Final = "не трогало"
UNTOUCHED_MANY: Final = "не трогали"


def resolved_marks(
    repo: str, token: str, since: str = "", limit: int = ghrest.MERGED_WINDOW
) -> tuple[dict[str, set[int]], str]:
    """Отпечатки, названные разобранными в слитом ПОСЛЕ отметки уборки, и кем.

    У отпечатка — номера СНЯВШИХ изменений: находку об ответе принимает только
    снятие изменением, тронувшим ответ, и спрашивать надо его, а не изменение,
    на котором находку нашли (взгляд на #834, `f73648a`).

    СРОК ЖИЗНИ СНЯТИЯ СЧИТАЕТСЯ ОТ ТОГО, КОГДА ЕГО ПРОЧЛИ, А НЕ КОГДА ОПУБЛИКОВАЛИ
    ([079](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/079-ttl-counts-from-completion.md)).
    Прежде окно было «последние тридцать закрытых»: снятие, опубликованное в теле
    изменения, обязано было попасть под уборку раньше, чем тридцать соседей
    сольются следом. Отсчёт шёл от ПУБЛИКАЦИИ, и жило снятие тем меньше, чем
    быстрее движется очередь, — ровно признак правила: «результат длинной
    операции исчезает раньше, чем результат короткой».

    ЗАМЕР 16.09.2026, и он стоил потерянной записи. Находку `a98cee5` починило
    #348 и сняло строкой «Разобрано» 14.09 в 15:46. К моменту, когда запись о ней
    появилась в реестре, #348 лежало за тридцатым закрытым изменением — и уборка
    на него уже не смотрела. Работа сделана, запись висит неразобранной, и снять
    её нечем.

    ОТМЕТКА ДВИГАЕТСЯ ТОЛЬКО ПО ПРОЧИТАННОМУ. Отдаётся она вторым значением, и
    записывает её вызывающий: заход, не дошедший до записи, не вправе объявить
    прочитанным то, чего не унёс.

    ОКНО ОСТАЁТСЯ ПРЕДЕЛОМ ЗАПРОСА, а не сроком хранения. Если за один заход
    слито больше, чем помещается на странице, отметка перешагнёт неувиденное — и
    об этом говорится вслух, как у реестра непросмотренного (045).
    """
    marks: dict[str, set[int]] = {}
    mark = since
    merged, page = ghrest.merged_page(repo, token, limit)
    # САМЫЙ СТАРЫЙ НОМЕР БЕРЁТСЯ СО СТРАНИЦЫ, А НЕ СО СЛИТЫХ НА НЕЙ. При нуле
    # слитых считать его не по чему, и `default=0` делал условие ложным ВСЕГДА:
    # предупреждение молчало ровно в своём предельном случае — полная страница
    # закрытых, из которых не слит ни один. Нашёл внешний взгляд на #431, и
    # назвал трижды подряд, потому что первая починка закрыла только половину.
    # ГРАНИЦА СТРАНИЦЫ МЕРЯЕТСЯ СТРАНИЦЕЙ, А НЕ СЛИТЫМИ НА НЕЙ, и предмет сверки
    # — ВРЕМЯ ЗАКРЫТИЯ. Курсор теперь время, и «самого старого номера» для него
    # не существует; а брать самое раннее СЛИЯНИЕ нельзя по той же причине, по
    # которой нельзя было брать самый старый номер среди слитых: на полной
    # странице закрытых слитых бывает горстка, и счёт по ним молчал бы ровно
    # тогда, когда закрытых без слияния много. Время закрытия есть у каждого
    # закрытого, а у слитого оно совпадает с временем слияния — то есть это та
    # же величина, что и курсор. Находки #418 и #431 сохранены обе.
    closed = [str(one.get("closed_at") or "") for one in page]
    oldest = min((when for when in closed if when), default="")
    for item in merged:
        # СЛИТОЕ БЕЗ ВРЕМЕНИ НЕ ЧИТАЕТСЯ И НЕ ДВИГАЕТ ОТМЕТКУ — «не знаю когда»
        # обязано значить «не прочитано», а не «прочитано сейчас» (045). Держит
        # это `or ""`, а НЕ отдельный сторож: пустая строка меньше любого
        # времени, поэтому она не может ни перешагнуть курсор, ни поднять его.
        # Сторож `if not when: continue` здесь стоял и был снят — откат показал,
        # что он не держит ничего: без него поведение то же. Откат, оставшийся
        # зелёным, — находка, а не облегчение
        # ([014](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/014-red-before-fix-needs-partial-revert.md)).
        # СЛИТОЕ БЕЗ НОМЕРА НЕ ЧИТАЕТСЯ И ОТМЕТКУ НЕ ДВИГАЕТ — как слитое без
        # времени: «не знаю, что это» значит «не прочитано», а не «снято
        # кем-то», и прочитанным его не объявляет и курсор (взгляд на #846).
        # Прежде его снятия принимались с неизвестным снявшим, и три захода
        # взгляда подряд (#838, #843) спорили, в какую сторону решать незнание;
        # держать запись или снимать — выбор без предмета, спросить не у кого
        # (210). Не снимаются из него и находки о коде. «Площадка молчит о
        # файлах» в `closable` — другой случай: снявший там известен, и
        # незнание о его файлах идёт в сторону снятия (039).
        number = int(item.get("number") or 0)
        if not number:
            continue
        when = str(item.get("merged_at") or "")
        mark = max(mark, when)
        if when <= since:
            continue
        for one in changerefs.resolved_in(item.get("body") or ""):
            marks.setdefault(one, set()).add(number)
    # ПОЛНОТА СТРАНИЦЫ МЕРЯЕТСЯ СТРАНИЦЕЙ, А НЕ СЛИТЫМИ НА НЕЙ. Запрос идёт за
    # закрытыми, и слитых на полной странице бывает горстка: счёт по слитым
    # молчал бы ровно тогда, когда закрытых без слияния много, — то есть в том
    # случае, ради которого предупреждение и заведено. Нашёл внешний взгляд
    # на #418.
    if since and len(page) >= limit and oldest > since:
        print(
            f"::warning::страница закрытых заполнена ({limit}), и за ней осталось "
            f"неувиденное: уборка читала от {since}, а самое раннее ЗАКРЫТИЕ на "
            f"странице — {oldest}. Снятия между ними не прочитаны",
            file=sys.stderr,
        )
    return marks, mark


#: Файл, правкой которого чинится находка ОБ ОТВЕТЕ. Один и тот же адрес у
#: механического пола рода и у этой проверки: два понимания «где живёт ответ»
#: разошлись бы молча (022).
ANSWER_FILE: Final = findings.ANSWER_FILE


def touched(repo: str, token: str, number: int) -> set[str]:
    """Пути, тронутые слитым изменением. Пусто — площадка не ответила.

    ЧИТАТЕЛЬ ОБЩИЙ, А ПОЛИТИКА ОТКАЗА — СВОЯ. Сам запрос живёт в транспорте:
    состав изменения спрашивает ещё и очередь слияний, и копия разошлась бы
    молча (090, нашёл внешний взгляд на #458). А вот что делать при отказе
    площадки, решает зовущий: здесь «не знаю состав» означает принять снятие,
    у очереди — не двигать изменение. Один исход на двоих был бы выбором за
    них (084).
    """
    try:
        return set(ghrest.files_of(repo, number, token))
    except ghrest.TransportError:
        return set()


def closable(
    repo: str,
    token: str,
    entries: dict[str, findings.Entry],
    by: dict[str, set[int]],
) -> tuple[set[str], dict[str, str]]:
    """Какие снятия принимаются, а какие — нет, и почему.

    ФАЙЛЫ СПРАШИВАЮТСЯ У СНЯВШЕГО ИЗМЕНЕНИЯ (`by`), а не у того, где находку
    нашли. Прежде проверялось `entry.pr`, и находку об ответе, поднятую на
    изменении без правки ответа, не снимало никакое изменение — даже правившее
    ответ (взгляд на #834, `f73648a`). Снявших несколько — хватает одного,
    тронувшего ответ.

    НАХОДКА ОБ ОТВЕТЕ ЧИНИТСЯ ПРАВКОЙ ОТВЕТА, И ЭТО ПРОВЕРЯЕМО. У находки о коде
    предмет размыт — починить её можно где угодно в дереве, — а у находки об
    ответе он ровно один файл: `.rules/bindings.json`. Значит изменение,
    объявившее её разобранной и не тронувшее этот файл, говорит о работе,
    которой не делало.

    ПОЧЕМУ ЭТО СТАЛО ВОЗМОЖНО ТОЛЬКО СЕЙЧАС: до появления рода предмета отличить
    такую находку от прочих было нечем, и проверка била бы по всем подряд (051).

    ТРЕТИЙ ИСХОД ИДЁТ В СТОРОНУ СНЯТИЯ, А НЕ УДЕРЖАНИЯ. Площадка не ответила о
    файлах — список пуст, и мы не знаем, трогали ответ или нет. Держать запись
    по НЕЗНАНИЮ значило бы наказывать за отказ сети того, кто работу сделал:
    отметка уже стоит в теле слитого, то есть утверждение человеком сделано
    (039, 084).
    """
    берём: set[str] = set()
    держим: dict[str, str] = {}
    файлы: dict[int, set[str]] = {}
    # СНЯТОЕ И СНЯВШИЕ — ОДИН ВХОД: отпечатки выводятся из `by`, и разойтись
    # двум параметрам больше нечем (взгляд на #838).
    for mark in sorted(set(by) & set(entries)):
        entry = entries[mark]
        if entry.kind != findings.ANSWER_KIND:
            берём.add(mark)
            continue
        снявшие = sorted(by[mark])
        for number in снявшие:
            if number not in файлы:
                файлы[number] = touched(repo, token, number)
        if any(not файлы[n] or ANSWER_FILE in файлы[n] for n in снявшие):
            берём.add(mark)
            continue
        names = ", ".join(f"#{n}" for n in снявшие)
        verb = UNTOUCHED_ONE if len(снявшие) == 1 else UNTOUCHED_MANY
        держим[mark] = (
            f"находка об ОТВЕТЕ, а {names} {verb} {ANSWER_FILE}. "
            "Ответ каталогу чинится правкой ответа: снятие говорит о работе, которой нет"
        )
    return берём, держим


def save(
    repo: str,
    token: str,
    entries: dict[str, findings.Entry],
    apply: bool,
    swept_to: str = "",
    recorded: dict[int, int] | None = None,
) -> None:
    """Записывает живую задачу: обновляет по месту или заводит одну."""
    number, _ = live_issue(repo, token)
    body = render_body(entries, swept_to, recorded)
    if not apply:
        print(
            f"записал бы {len(entries)} заметок " + (f"в #{number}" if number else "в новую задачу")
        )
        return
    if number is None:
        created = ghrest.request(
            "POST", f"repos/{repo}/issues", token, {"title": TITLE, "body": body}
        )
        print(f"заведена живая задача #{created['number']}")
        return
    ghrest.request("PATCH", f"repos/{repo}/issues/{number}", token, {"body": body})
    print(f"живая задача #{number} обновлена: заметок {len(entries)}")


def record_fix_check(
    entries: dict[str, findings.Entry], pr: int, look: list[dict[str, Any]]
) -> None:
    """Снимает находки изменения, которые проверка починки назвала закрытыми."""
    verdict = verdict_of(look)
    if verdict is None:
        raise NotRun(f"в проверке починки #{pr} нет строки вердикта — это не «всё закрыто» (075)")
    answers = fix_answers(look)
    closed = sorted(
        mark for mark, ok in answers.items() if ok and mark in entries and entries[mark].pr == pr
    )
    for mark in closed:
        del entries[mark]
    still = sum(1 for ok in answers.values() if not ok)
    if still != verdict:
        print(
            f"::warning::проверка починки #{pr} говорит «находок {verdict}», а не закрытых {still}",
            file=sys.stderr,
        )
    print(
        f"из #{pr}: проверка починки — закрыто {len(closed)}, не закрыто {still}"
        + (f": снято {', '.join(closed)}" if closed else "")
    )


def record_look(
    entries: dict[str, findings.Entry], pr: int, look: list[dict[str, Any]], strict: bool
) -> None:
    """Записывает находки одного захода взгляда в реестр; вердикта нет — отказ.

    ПРОВЕРКА ПОЧИНКИ НОВЫХ ЗАПИСЕЙ НЕ ЗАВОДИТ (#848): она отвечает только о
    прошлых находках этого изменения, и названную закрытой снимает. Чужие
    изменения она не трогает: снимается лишь запись с тем же номером.
    """
    if is_fix_check(look):
        record_fix_check(entries, pr, look)
        return
    # ВЕРДИКТ И СТРОКИ НАХОДОК ЧИТАЮТСЯ С ОДНОГО ОТРЕЗКА. Прежде число
    # брали с последнего захода, а строки — со всей ленты, и спорили
    # они по устройству, а не по вине ревьюера (022).
    verdict = verdict_of(look)
    if verdict is None:
        raise NotRun(
            f"в изменении #{pr} нет строки вердикта — ревьюер не дописал ответ "
            "или не отработал вовсе; это не «находок нет» (075)"
        )
    titles = findings_of(look)
    seen_by = {title: роль for _, title, _, роль in found_in(look)}
    if len(titles) != verdict:
        # Расхождение названо, а не сглажено: вердикт и строки находок
        # пишет один и тот же ответ, и если они спорят, доверять нечему.
        print(
            f"::warning::вердикт по #{pr} говорит «находок {verdict}», "
            f"а строк находок {len(titles)} — записаны строки",
            file=sys.stderr,
        )
    renamed = 0
    # Пары «строка — прежняя запись» решаются для захода ЦЕЛИКОМ, до
    # записи: см. `pair_up`. Построчный выбор зависел от порядка строк.
    retold = pair_up(entries, pr, [title for _, title, _ in titles], strict=strict)
    for (weight, title, род), mark in zip(titles, retold, strict=True):
        # ЗАПИСЬ ИЩЕТСЯ ПРЕЖДЕ, ЧЕМ ЗАВОДИТСЯ. Отпечаток берётся от
        # заголовка, а заголовок ревьюер на новом заходе пересказывает
        # — и та же находка ложилась второй записью. Замер 10.09.2026:
        # четыре записи об одной беде на #149 и две на #148.
        #
        # Прежний отпечаток при этом СОХРАНЯЕТСЯ: по нему находку уже
        # могли назвать разобранной в теле изменения, и смена отпечатка
        # обессмыслила бы снятие.
        if mark is not None:
            renamed += 1
            # Ответ верификатора ПЕРЕЖИВАЕТ пересказ находки: он о
            # премисе, а не о формулировке, и переписывать запись
            # заново значило бы терять уже сделанную работу — тот же
            # класс, что потеря хвоста позднего взгляда в реестре
            # непросмотренного (022).
            entries[mark] = replace(
                entries[mark],
                pr=pr,
                weight=weight,
                kind=род,
                role=seen_by.get(title) or entries[mark].role,
            )
            continue
        entries[fingerprint(title)] = findings.Entry(
            pr, weight, title, kind=род, role=seen_by.get(title, "")
        )
    said = f"из #{pr}: вердикт {verdict}, строк находок {len(titles)}"
    if renamed:
        said += f", из них уже лежат под своим отпечатком {renamed}"
    print(said)


def open_changes(repo: str, token: str) -> set[int]:
    """Номера открытых изменений."""
    return {int(one["number"]) for one in ghrest.paginate(f"repos/{repo}/pulls?state=open", token)}


def catch_up(
    repo: str,
    token: str,
    entries: dict[str, findings.Entry],
    recorded: dict[int, int],
    strict: bool,
) -> None:
    """Дописывает заходы, чья запись вытеснена: у открытых и у отмеченных изменений.

    ЗАЧЕМ (#842). Запись находок идёт через группу `findings-write`, и
    площадка держит в ней один ожидающий прогон: новый вытесняет прежний.
    Замер 25.09.2026 по 1000 прогонам: отменено 7 записей из 662. Следующая
    запись читала только свой заход, и находки вытесненного, которых она не
    повторила, пропадали без следа.

    Изменение, которое уже не открыто, но стоит в отметке, догоняется в
    последний раз, и отметка с него снимается: так ловится запись,
    вытесненная прямо перед слиянием.

    ОТМЕТКИ НЕТ И ОТМЕТКА ПОТЕРЯНА — РАЗНЫЕ СЛУЧАИ (210: вторая находка по
    этому месту, поздние взгляды на #853 и #856). Отметки нет у нового
    изменения, чья первая запись не дошла, — её вытесняет в той же группе
    `findings-write` и сама уборка. Тогда пишется последний заход: отметка
    без записи потеряла бы его находки навсегда. Отметка потеряна, когда её
    заход удалён из ленты, — тогда уборка лишь переставляет её на последний:
    писать заново значило бы вернуть снятое чужим слитым изменением (класс
    #333). ПРЕДЕЛ НАЗВАН: изменение, записанное до выкладки #853 и с тех пор ни
    разу, без отметки тоже, и у него этот риск есть. Замер 26.09.2026: открытых
    изменений, заведённых до выкладки, ноль — все три открыты после неё.

    СБОЙ ПЛОЩАДКИ ПО ОДНОМУ ИЗМЕНЕНИЮ НЕ ОБРЫВАЕТ УБОРКУ. Догон — довесок к
    снятию разобранного, и чужая лента, не отданная площадкой, не должна
    останавливать снятие (поздний взгляд на #853). Отказ назван
    предупреждением, отметка изменения остаётся как была.

    ЦЕНА НАЗВАНА: запрос списка открытых изменений и вся лента (по странице на
    каждые 100 комментариев) каждого открытого и отмеченного изменения — на
    каждой уборке. Замер 26.09.2026: открыто 1, отмечено 1, лент длиннее ста
    комментариев нет, то есть 3 запроса.
    """
    try:
        live = open_changes(repo, token)
    except ghrest.TransportError as exc:
        print(
            f"::warning::догон записи пропущен: список открытых не прочитан — {exc}",
            file=sys.stderr,
        )
        return
    for pr in sorted(live | set(recorded)):
        try:
            comments = list(ghrest.paginate(f"repos/{repo}/issues/{pr}/comments", token))
        except ghrest.TransportError as exc:
            print(
                f"::warning::догон записи #{pr} пропущен: лента не прочитана — {exc}",
                file=sys.stderr,
            )
            continue
        seen = looks(comments)
        ids = [one for one, _ in seen]
        if seen and pr in recorded and recorded[pr] not in ids:
            recorded[pr] = ids[-1]
            print(f"догон записи: #{pr} — отмеченный заход не найден, отметка на {ids[-1]}")
        elif seen:
            for look_id, look in unrecorded(comments, recorded.get(pr)):
                print(f"догон записи: #{pr}, заход {look_id}")
                record_look(entries, pr, look, strict)
                recorded[pr] = look_id
        if pr not in live:
            recorded.pop(pr, None)


def main(argv: list[str] | None = None) -> int:
    """Точка входа: печатает исход и возвращает его код."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo", default=os.environ.get("GITHUB_REPOSITORY", ""))
    parser.add_argument("--pr", type=int, help="изменение, чей вердикт разбирается")
    parser.add_argument("--sweep", action="store_true", help="только уборка разобранного")
    parser.add_argument("--verify", help="отпечаток находки, чью премису проверил верификатор")
    parser.add_argument(
        "--tell", help="отпечаток находки: напечатать её предмет парами ключ=значение"
    )
    parser.add_argument(
        "--strict",
        action="store_true",
        help="сверять заголовки дословно: без сходства слов (102)",
    )
    parser.add_argument("--apply", action="store_true", help="записывать, а не показывать")
    args = parser.parse_args(argv)
    report.announce(not args.apply)

    try:
        token = os.environ.get("GH_TOKEN") or os.environ.get("GITHUB_TOKEN") or ""
        if not token:
            raise NotRun("нет токена: GH_TOKEN или GITHUB_TOKEN")
        if not args.repo:
            raise NotRun("репозиторий не назван: --repo или GITHUB_REPOSITORY")
        if not args.sweep and args.pr is None and not args.verify and not args.tell:
            raise NotRun("не назван предмет разбора: --pr, --sweep, --verify или --tell")

        _, body = live_issue(args.repo, token)
        entries = parse_entries(body)
        recorded = parse_recorded(body)

        if args.tell:
            # ПРЕДМЕТ ВЕРИФИКАТОРА ЧИТАЕТСЯ ИЗ РЕЕСТРА, а не передаётся кнопкой
            # второй раз: номер изменения у находки уже записан, и два его
            # источника разошлись бы молча — а проверять премису не на том
            # изменении хуже, чем не проверять вовсе (022, 049).
            one = entries.get(args.tell)
            if one is None:
                raise NotRun(f"находки «{args.tell}» в реестре нет — проверять нечего")
            print(f"pr={one.pr}")
            print(f"weight={one.weight}")
            print(f"title={one.title}")
            return EXIT_PENDING

        if args.verify:
            # ПРЕДМЕТ БЕРЁТСЯ ИЗ РЕЕСТРА, А НЕ ИЗ ВХОДА. Номер изменения у
            # находки уже записан, и второй его источник разошёлся бы с первым
            # молча — а проверять премису не на том изменении хуже, чем не
            # проверять вовсе (022).
            entry = entries.get(args.verify)
            if entry is None:
                raise NotRun(f"находки «{args.verify}» в реестре нет — проверять нечего")
            heard = list(ghrest.paginate(f"repos/{args.repo}/issues/{entry.pr}/comments", token))
            answer = premise_of(heard)
            if answer is None:
                raise NotRun(
                    f"в изменении #{entry.pr} нет строки «ПРЕМИСА:» — верификатор не ответил "
                    "или не отработал вовсе; это не «премиса подтверждена» (075)"
                )
            word, why = answer
            entries[args.verify] = verified(
                entry, word, why, datetime.now(UTC).strftime("%d.%m.%Y")
            )
            print(f"премиса «{args.verify}» из #{entry.pr}: {word}" + (f" — {why}" if why else ""))

        if args.pr is not None:
            comments = list(ghrest.paginate(f"repos/{args.repo}/issues/{args.pr}/comments", token))
            # ДОПИСЫВАЮТСЯ ВСЕ ЗАХОДЫ ПОСЛЕ ЗАПИСАННОГО, а не последний: прежняя
            # запись могла быть вытеснена в группе `findings-write` (#842).
            # Заходов нет вовсе — читается вся лента, и отказ «нет вердикта»
            # звучит, как прежде (075).
            pending = (
                unrecorded(comments, recorded.get(args.pr))
                if looks(comments)
                else [(0, list(comments))]
            )
            if not pending:
                print(f"из #{args.pr}: последний заход уже записан")
            for look_id, look in pending:
                record_look(entries, args.pr, look, args.strict)
                if look_id:
                    recorded[args.pr] = look_id

        if args.sweep:
            catch_up(args.repo, token, entries, recorded, args.strict)

        # Уборка идёт ПОСЛЕ записи, а не вместо: обратный порядок терял бы
        # заметку, снятую и заново найденную одним заходом.
        marks, swept_to = resolved_marks(args.repo, token, parse_swept(body))
        swept, held = closable(args.repo, token, entries, marks)
        twins = drop_resolved(entries, set(swept), strict=args.strict)
        if swept:
            print(f"снято как разобранное: {', '.join(sorted(swept))}")
        for mark, was in sorted(twins.items()):
            # Дубль снятого уходит ВСЛУХ: иначе запись пропала бы без строки
            # «Разобрано» и без следа, почему (045).
            print(f"снято как дубль снятого: {mark} — дубль {was}")
        for mark, why in sorted(held.items()):
            # ОТКАЗ СНЯТИЯ НАЗЫВАЕТСЯ ВСЛУХ, А НЕ МОЛЧА ОСТАВЛЯЕТ ЗАПИСЬ.
            # Иначе разбирающий видит «отметку поставил, а запись висит» и
            # решает, что сломалась уборка (045).
            print(f"::warning::снятие `{mark}` не принято: {why}", file=sys.stderr)

        save(args.repo, token, entries, args.apply, swept_to, recorded)
    except (NotRun, ghrest.TransportError) as exc:
        print(f"механизм не отработал: {exc}", file=sys.stderr)
        return EXIT_BROKEN

    return EXIT_PENDING if entries else EXIT_NOTHING


if __name__ == "__main__":
    raise SystemExit(main())
