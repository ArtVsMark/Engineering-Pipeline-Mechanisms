def fingerprint(title: str) -> str:
    """Семь знаков от хэша заголовка находки."""
    return hashlib.sha1(" ".join(title.split()).encode()).hexdigest()[:7]


#: Насколько два заголовка должны совпасть, чтобы считаться одной находкой.
#: Величина не подобрана на глаз: замер 10.09.2026 по 50 парам в реестре #23
#: дал 0.960 у настоящего дубля и 0.400 у ближайшей пары РАЗНЫХ находок — между
#: ними нет ни одной пары. Порог поставлен в этот пустой промежуток; двигать его
#: имеет смысл, только если замер покажет другое.
SAME_ENOUGH: Final = 0.85


def same_finding(one: str, other: str, *, strict: bool = False) -> bool:
    """Одна ли это находка, названная дважды: по сходству СЛОВ, а не по месту.

    Ошибаться здесь можно в обе стороны, и цены разные: лишняя запись стоит
    строки в реестре, а слипшиеся находки стоят потерянной находки. Поэтому
    порог стоит в пустоте между замеренными значениями, а не посередине шкалы.

    СОВПАВШИЙ АДРЕС ТОЖДЕСТВОМ БОЛЬШЕ НЕ СЧИТАЕТСЯ. Прежде он решал сам, при
    любых словах: место в дереве пересказ не меняет. Но у одного места бывает и
    новая беда, и тогда она ложилась на запись прежней и уходила вместе с её
    снятием — `Разобрано: <прежний отпечаток>` уносил обе (`7b62e1a`). Замер
    24.09.2026 по 567 ответам с 09.09.2026: пар строк с равными адресами в
    разных заходах одного изменения 76; ниже порога слов — 18, из них 17
    пересказов со сходством от 0.056 и одна пара разных бед с 0.057 (#657).
    Порога между ними нет, различить по словам нельзя — и выбрана дешёвая
    ошибка: пересказ без сходства слов заводит вторую запись, а не прячет новую
    находку. Сократить дубли может ревьюер: подсказка требует повтора
    ДОСЛОВНО, и дословная строка узнаётся без угадывания.

    СРАВНИВАЮТСЯ СЛОВА, А НЕ ЗНАКИ, и это не мелочь. Посимвольное сходство
    рушится от перестановки слов — «не может измениться» и «измениться не
    может» дают 0.827, то есть НИЖЕ порога, хотя это одна и та же фраза.
    Пословное на том же примере даёт 0.857, а на живых данных ещё и шире
    разводит дубль с чужой находкой: 0.960 против 0.400 (по знакам было 0.986
    против 0.514).
    """
    if strict:
        # СТРОГИЙ РЕЖИМ НЕ ПРОЩАЕТ НИЧЕГО, и нужен он не из аккуратности.
        # Послабление ошибается в обе стороны, и одна из сторон дорогая:
        # слипшиеся находки стоят потерянной находки. Когда есть подозрение,
        # что реестр слепил две разные, строгий заход покажет их по отдельности
        # — и это единственный способ такое подозрение проверить (102).
        return one == other
    return SequenceMatcher(None, one.lower().split(), other.lower().split()).ratio() >= SAME_ENOUGH


def existing_mark(
    entries: dict[str, Entry], pr: int, title: str, *, strict: bool = False
) -> str | None:
    """Отпечаток уже лежащей записи о ТОЙ ЖЕ находке, если она есть.

    Ищется только среди находок ТОГО ЖЕ изменения: одна и та же беда в двух
    разных изменениях — это две находки, и снимать их надо по отдельности.

    ЭТО ЧАСТНЫЙ СЛУЧАЙ `pair_up` ДЛЯ ОДНОЙ СТРОКИ, а не второй выбор рядом. Жатва
    зовёт `pair_up` для захода целиком; здесь тот же выбор отдаётся по одной
    строке. Две реализации одного выбора разошлись бы молча
    ([022](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/022-one-canonical-document.md)).
    """
    return pair_up(entries, pr, [title], strict=strict)[0]


def pair_up(
    entries: dict[str, Entry], pr: int, titles: list[str], *, strict: bool = False
) -> list[str | None]:
    """Какую прежнюю запись пересказывает каждая строка захода; ``None`` — новая.

    ЗАХОД РАЗБИРАЕТСЯ ЦЕЛИКОМ, А НЕ ПОСТРОЧНО. Пока строки шли по порядку и
    каждая забирала ближайшую запись себе, исход зависел от ПОРЯДКА строк в
    ответе. Проверено прогоном: новая находка по адресу, стоящая РАНЬШЕ
    пересказа старой, забирала старую запись — запись хранит прежний заголовок,
    и новая находка пропадала молча, а пересказ заводил дубль. Счёт записей при
    этом сходился, расходилось содержимое
    ([045](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/045-no-silent-fallback.md)).
    Второй случай того же рода нашёл внешний взгляд на #662: два пересказа по
    одному адресу, и ранний отбирает запись, которая ближе позднему.

    Поэтому пары решаются вместе: все допустимые пары «строка — запись»
    сортируются по сходству слов, и сильнейшие занимаются первыми. Строка, чья
    запись уже занята более сильной парой, остаётся новой.

    НИЧЬЯ НЕ РЕШАЕТСЯ ПОРЯДКОМ. Пока равные по сходству пары шли по месту
    строки в ответе, порядок строк возвращался через ничью — нашёл внешний
    взгляд на #666 (`939c19b`). Теперь уровень сходства решается ЦЕЛИКОМ:

    * запись, на которую с равным сходством претендуют ДВЕ строки, не
      достаётся ни одной — какая из них пересказ, в ничьей не знает никто, а
      угадав не ту, разбор поглотил бы новую находку молча. Обе заводятся
      новыми: цена — дубль в реестре, а не потеря (та же асимметрия, что у
      `same_finding`);
    * строка, равно близкая к двум записям, садится на одну — такая ничья
      потерь не несёт, обе записи остаются, — и выбирает отпечаток, а не
      порядок, в котором реестр их отдал.

    ГРАНИЦА НАЗВАНА, И ОНА ЗАМЕРЕНА. Сильнейшие-первыми — не полный перебор
    назначений: в нарочно подобранном случае сумма сходства может выйти не
    наибольшей. Касается это только ответов, где одну запись пересказывает
    больше одной близкой строки; близость теперь — только слова (порог
    `SAME_ENOUGH`), и таких строк ещё меньше, чем прежде строк на один адрес.
    Замер 23.09.2026 по всем комментариям изменений с ключом `НАХОДКА[` с
    09.09.2026 — 567 ответов, 360 адресов в пределах одного ответа: на 357
    одна строка, на трёх две, трёх и больше не встречалось ни разу. Полный
    перебор стоил бы непрозрачности ради трёх случаев из 360
    ([195](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/195-a-narrowed-predicate-names-its-neighbour.md)).
    """
    pairs: list[tuple[float, int, str]] = []
    for place, title in enumerate(titles):
        words = title.lower().split()
        for mark, entry in entries.items():
            if entry.pr == pr and same_finding(entry.title, title, strict=strict):
                close = SequenceMatcher(None, entry.title.lower().split(), words).ratio()
                pairs.append((close, place, mark))
    found: list[str | None] = [None] * len(titles)
    taken: set[str] = set()
    for close in sorted({weight for weight, _, _ in pairs}, reverse=True):
        level = [
            (place, mark)
            for weight, place, mark in pairs
            if weight == close and found[place] is None and mark not in taken
        ]
        claims = Counter(mark for _, mark in level)
        taken.update(mark for mark, count in claims.items() if count > 1)
        for place, mark in sorted(level, key=lambda one: one[1]):
            if found[place] is None and mark not in taken:
                found[place] = mark
                taken.add(mark)
    return found


def marks_in(raw: str) -> list[str]:
    """Слова из скобки находки: `[дефект · ответ]` — два, `[дефект]` — одно.

    Разделителем служит точка-разделитель или запятая: ревьюер пишет то, что
    видит в подсказке, и требовать от него одного знака значило бы ронять
    запись из-за оформления (051).
    """
    return [" ".join(part.strip("*_` ").split()).lower() for part in re.split(r"[·,]", raw)]


def weight_of(raw: str) -> str:
    """Вес из строки находки: из объявленной шкалы либо «без веса».

    Слово вне шкалы весом не считается и НЕ приводится к ближайшему: приведение
    решило бы за ревьюера, а объявленное «без веса» видно и разбирающему, и
    тому, кто правит подсказку ревью (154).

    СКОБКА НЕСЁТ ДВА СЛОВА, И ВТОРОЕ НЕ ПОРТИТ ПЕРВОГО. С появлением рода
    предмета ревьюер пишет `[дефект · ответ]`; прежний разбор брал скобку
    ЦЕЛИКОМ, не находил её в шкале и объявлял «без веса» — то есть новая
    пометка обнуляла бы старую (090).
    """
    for said in marks_in(raw):
        if said in WEIGHTS:
            return said
    return UNWEIGHED


#: Чем взгляд говорит «находок нет» В ТОЙ ЖЕ СТРОКЕ, что и находку. Формат
#: требует строки `НАХОДКА:`, и при пустом заходе ревьюер пишет в неё отрицание
#: — это ОТВЕТ «предмета нет», а не находка с таким заголовком.
#:
#: ЗАМЕР: на #414 взгляд написал «ВЕРДИКТ: находок 0» и рядом «НАХОДКА: нет».
#: Разбор завёл запись с заголовком «нет», и она пролежала в реестре сутки,
#: пережив пять заходов уборки: снять её нечем — работы, которая бы её починила,
#: не существует. Расхождение при этом БЫЛО НАЗВАНО вслух предупреждением
#: «вердикт говорит 0, а строк находок 1» — и предупреждение никого не
#: остановило, потому что запись всё равно записывалась
#: ([045](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/045-no-silent-fallback.md)).
#:
#: СПИСОК ЗАКРЫТЫЙ И СРАВНЕНИЕ ТОЧНОЕ. «нет проверки на пустой ввод» — законный
#: заголовок находки, и отвергать всё, что начинается с «нет», значило бы
#: запретить целый класс формулировок (051).
ABSENCE: Final = frozenset({"нет", "нет находок", "находок нет", "none", "no findings"})
#: Знаки конца, которые снимаются перед сверкой со словарём. Список закрытый:
#: `rstrip(".")` снимал точку и пропускал «нет!», «нет?», «нет…» — призрак
#: заводился снова, просто с восклицательным знаком в заголовке. Нашёл внешний
#: взгляд на #453.
ENDINGS: Final = ".!?…"


def findings_of(comments: list[dict[str, Any]]) -> list[tuple[str, str, str]]:
    """Находки: вес, заголовок и род — без роли (прежний вид для всех читателей)."""
    return [(weight, title, род) for weight, title, род, _ in found_in(comments)]


def found_in(comments: list[dict[str, Any]]) -> list[tuple[str, str, str, str]]:
    """Находки ревьюера парами «вес, заголовок» — по порядку и без повторов.

    Третьим в паре идёт РОД предмета: «код» либо «ответ» (`findings.KINDS`).
    Строка отрицания находкой не считается: см. `ABSENCE`.
    """
    found: list[tuple[str, str, str, str]] = []
    seen: set[str] = set()
    known = findings.roles()
    for comment in comments:
        for line in bare_lines(comment.get("body") or ""):
            said = FINDING_RE.match(line)
            if said is None:
                continue
            raw_weight, title = said.group(1) or "", said.group(2)
            # ЗАГОЛОВОК НЕ СРЕЗАЕТСЯ ПО ЗНАКАМ: обёртка уже снята со строки
            # целиком, а `strip` по набору съедал бы знаки, принадлежащие
            # ТЕКСТУ. Так в реестре и лежит сегодня «SERVICE_STEPS` объявлен» —
            # с висящей кавычкой вместо парной (022, 016).
            cleaned = " ".join(bare(title).split())
            if cleaned.casefold().rstrip(ENDINGS).strip() in ABSENCE:
                continue
            if cleaned and cleaned not in seen:
                seen.add(cleaned)
                род = next(
                    (one for one in marks_in(raw_weight) if one in findings.KINDS),
                    "",
                )
                # РОЛЬ — ТРЕТЬЕ СЛОВО СКОБКИ, из закрытого списка карты ролей
                # (#763): `[риск · архитектор]`. Незнакомое слово ролью не
                # считается и не приводится к ближайшему — как и вес (154).
                роль = next((one for one in marks_in(raw_weight) if one in known), "")
                found.append((weight_of(raw_weight), cleaned, findings.kind_of(cleaned, род), роль))
    return found


def verdict_of(comments: list[dict[str, Any]]) -> int | None:
    """Число из последней строки вердикта; None — вердикта нет вовсе."""
    verdict: int | None = None
    for comment in comments:
        for line in bare_lines(comment.get("body") or ""):
            said = VERDICT_RE.match(line)
            if said is not None:
                verdict = int(said.group(1))
    return verdict


def is_verification(comment: dict[str, Any]) -> bool:
    """Это ответ верификатора: автор-прогон и метка верификатора первой строкой.

    Ответ верификатора — не заход взгляда. Он может процитировать `ВЕРДИКТ:` и
    `НАХОДКА[` из находки, которую проверяет, и читатели заходов его
    отсеивают: замер цепочек, `last_look` и `unlooked.is_run_answer` — через
    него очередь слияний и `look_at` (взгляды на #827, #833).

    ПРЕДЕЛ НАЗВАН: ответ верификатора, перенесённый до #825, лежит под меткой
    позднего взгляда и здесь не узнаётся.
    """
    body = str(comment.get("body") or "").lstrip()
    author = str((comment.get("user") or {}).get("login") or "")
    return author == LATE_AUTHOR and body.startswith(VERIFY_MARKER)


def last_look(comments: list[dict[str, Any]]) -> list[dict[str, Any]]:
    """Лента ПОСЛЕДНЕГО захода взгляда, а не всё изменение целиком.

    ЗАХОД КОНЧАЕТСЯ ВЕРДИКТОМ. Ответ ревьюера складывается из нескольких
    комментариев: строки находок пишет живой комментарий действия, число находок
    доносит отдельная запись механизма, и авторы у них разные. Границей захода
    поэтому взят вердикт, а не автор и не час: это единственная строка, которой
    заход объявляет себя законченным.

    ПОЧЕМУ НЕ ВСЯ ЛЕНТА. Строки находок прошлого захода остаются на изменении
    навсегда, и РАЗОБРАННАЯ находка возвращалась в реестр при каждом новом
    взгляде. Снятие к этому часу уже уходило из окна последних слитых изменений
    — и убрать запись становилось нечем: работа сделана, запись висит
    неразобранной, а механизма снять её больше нет
    ([045](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/045-no-silent-fallback.md)).

    ЗАМЕР 16.09.2026 на #333. Находку `a98cee5` починило #348 и сняло строкой
    «Разобрано: a98cee5» 14.09 в 15:46. Поздний взгляд 16.09 в 12:42 объявил
    «находок 2», а в реестр уехало три записи: две свои и одна, перечитанная из
    комментария от 13.09. К этому часу #348 лежало за тридцатым закрытым
    изменением, и уборка на него уже не смотрела.

    ЕДИНСТВЕННЫЙ ЗАХОД ЧИТАЕТСЯ ЦЕЛИКОМ. Пока вердикт один, отрезать нечего:
    находки этого захода лежат ДО него, и «брать только последний отрезок»
    означало бы выбросить их все — то есть превратить работающий канал в
    «находок нет»
    ([075](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/075-a-guard-that-finds-nothing-must-fail.md)).
    """
    # ОТВЕТ ВЕРИФИКАТОРА ЗАХОДОМ НЕ СЧИТАЕТСЯ: процитированный им `ВЕРДИКТ:`
    # резал бы отрезок, а процитированная находка шла бы в реестр новой
    # записью (взгляд на #833).
    comments = [comment for comment in comments if not is_verification(comment)]
    ends = [
        place
        for place, comment in enumerate(comments)
        if any(VERDICT_RE.match(line) for line in bare_lines(comment.get("body") or ""))
    ]
    if len(ends) < 2:
        return list(comments)
    # ОТРЕЗОК ИДЁТ ДО КОНЦА ЛЕНТЫ, а не до последнего вердикта: находку
    # дописывают и после числа — тем же заходом, отдельным комментарием, — и
    # обрыв на вердикте терял бы находку ровно того захода, ради которого
    # отрезок и берётся.
    return list(comments[ends[-2] + 1 :])


def looks(comments: list[dict[str, Any]]) -> list[tuple[int, list[dict[str, Any]]]]:
    """Все заходы взгляда по порядку: id комментария с вердиктом и лента захода.

    Границы те же, что у `last_look`: заход кончается вердиктом, последний
    тянется до конца ленты, ответ верификатора заходом не считается. Последний
    элемент — ровно `last_look`, пока вердиктов больше одного.

    ЗАЧЕМ ВСЕ, А НЕ ПОСЛЕДНИЙ. Запись находок вытесняется в группе
    `findings-write` (#842): отменённый заход не записан, а следующий читает
    только себя, и находки, которых он не повторил, терялись без следа.
    Догону нужен каждый заход после записанного.
    """
    comments = [comment for comment in comments if not is_verification(comment)]
    ends = [
        place
        for place, comment in enumerate(comments)
        if any(VERDICT_RE.match(line) for line in bare_lines(comment.get("body") or ""))
    ]
    out: list[tuple[int, list[dict[str, Any]]]] = []
    for step, end in enumerate(ends):
        start = ends[step - 1] + 1 if step else 0
        stop = end + 1 if step + 1 < len(ends) else len(comments)
        out.append((int(comments[end].get("id") or 0), list(comments[start:stop])))
    return out


def is_fix_check(look: list[dict[str, Any]]) -> bool:
    """Заход — проверка починки: ревьюер объявил это первой строкой ответа (#848)."""
    return any(
        str((comment.get("user") or {}).get("login") or "") == REVIEWER_AUTHOR
        and FIXCHECK_MARKER in bare_lines(comment.get("body") or "")
        for comment in look
    )


def fix_form(mark: str, closed: bool, said: str) -> str:
    """Строка ответа проверки починки — та, которую читает `FIX_RE`."""
    return f"{FIX_HEAD}[{mark}]: {FIX_CLOSED if closed else FIX_OPEN} — {said}"


def fix_answers(look: list[dict[str, Any]]) -> dict[str, bool]:
    """Ответы проверки починки: отпечаток → закрыта ли. Только от ревьюера."""
    said: dict[str, bool] = {}
    for comment in look:
        if str((comment.get("user") or {}).get("login") or "") != REVIEWER_AUTHOR:
            continue
        for line in bare_lines(comment.get("body") or ""):
            one = FIX_RE.match(line)
            if one is not None:
                said[one.group(1)] = " ".join(one.group(2).lower().split()) == FIX_CLOSED
    return said


def unrecorded(
    comments: list[dict[str, Any]], since: int | None
) -> list[tuple[int, list[dict[str, Any]]]]:
    """Заходы после записанного; отметки нет или она не найдена — только последний.

    ПОЧЕМУ БЕЗ ОТМЕТКИ НЕ ВСЁ. Изменение без отметки записывалось ещё до неё,
    и перечитка всей ленты вернула бы в реестр находки, снятые с тех пор, —
    ровно то, от чего `last_look` и заведён (замер на #333). Предел назван: у
    изменения без отметки, чей последний заход вытеснен, пропавшее не догнать.
    """
    seen = looks(comments)
    ids = [one for one, _ in seen]
    if since is None or since not in ids:
        return seen[-1:]
    return seen[ids.index(since) + 1 :]


