#: Взгляда не было вовсе: ни строк находок, ни строки вердикта.
STATE_NONE: Final = "вердикта нет"
#: Ревьюер отвечал, но вердикта не поставил: строки находок есть, итоговой нет.
#: Это и есть видимая часть «прогон упал» — большего артефакты не говорят.
STATE_CUT: Final = "ответ оборван: находки есть, вердикта нет"
#: Был поздний взгляд — по общей ветке, после слияния. Другой предмет, и
#: называется он другим словом.
STATE_LATE: Final = "поздний взгляд по общей ветке"
#: Прогон взгляда упал. Это НЕ «ответ оборван»: там ревьюер начал отвечать, а
#: здесь не отработал сам прогон, и разбирать надо не работу, а канал.
STATE_BROKEN: Final = "прогон взгляда упал — смотреть надо канал, а не работу"
#: Прогон прошёл, а ответа нет. Причин у этого несколько, и механизм НЕ
#: выбирает между ними: он называет видимое, а варианты перечислены в теле
#: реестра (154). Замер 10.09.2026: четыре записи подряд выглядели одинаково, а
#: у #120 причина была своя — оно правило сам файл прогона, и действие ревью
#: отказалось работать по расхождению с общей веткой (152).
STATE_SILENT: Final = "прогон взгляда прошёл, а ответа нет"
#: Прогон взгляда ещё ИДЁТ. Вердикта нет и не должно быть: спрашивать рано.
#: Прежде это падало в «вердикта нет» — то есть механизм объявлял отсутствующим
#: то, что ещё не наступило, а перечитать реестр было нечем, кроме следующего
#: захода. Заход у реестра ночной, и «рано» держалось сутки. Нашёл внешний
#: взгляд на #127.
STATE_RUNNING: Final = "прогон взгляда ещё идёт — вердикта пока нет"
#: Прогон взгляда ОТМЕНЁН: погашен группой отмены или снят руками. Вердикта не
#: будет, и это ближе к каналу, чем к «не запускался»: шаг стартовал и был
#: прерван. Разница не косметическая — «не запускался» зовёт смотреть условия
#: шага, а отмена зовёт смотреть, кто его гасит (154).
STATE_CANCELLED: Final = "прогон взгляда отменён — вердикта не будет"
#: Шаг взгляда ПРОПУЩЕН условием. Площадка отдаёт `skipped`, и это не «прогон
#: не запускался»: запись есть, условие вычислено и оказалось ложным. Условие у
#: джоба ровно одно — голова изменения лежит в этом же репозитории, — значит
#: `skipped` здесь означает ФОРК, и больше ничего.
#:
#: ПРАВКА САМОГО ФАЙЛА ПРОГОНА СЮДА НЕ ОТНОСИТСЯ, и это замер, а не рассуждение.
#: Джоб при ней стартует; отказывается работать действие ревью, а шаг объявлен
#: `continue-on-error` — запись выходит ЗЕЛЁНОЙ. Живой случай #120 лежит в
#: реестре как «прогон прошёл, а ответа нет», и там ему и место. Прежняя
#: редакция приписывала эту причину пропуску, противореча собственному замеру.
#: Нашёл внешний взгляд на #180.
STATE_SKIPPED: Final = "шаг взгляда пропущен условием — изменение из форка"
#: Прогон кончился исходом, которого разбор не знает: `neutral`, `timed_out`,
#: `action_required`, `stale`. Запись ЕСТЬ — значит «шаг не запускался» неверно,
#: и отправлять читателя искать условия шага значит послать его не туда (046).
#: Исход называется словом площадки: догадываться о нём здесь нечем (154).
STATE_ODD: Final = "прогон взгляда кончился исходом, которого разбор не знает"
STATES: Final = (
    STATE_NONE,
    STATE_CUT,
    STATE_LATE,
    STATE_BROKEN,
    STATE_SILENT,
    STATE_RUNNING,
    STATE_CANCELLED,
    STATE_SKIPPED,
    STATE_ODD,
)
#: Состояния, которые заход перечитывает: вердикт бывает позже слияния.
#: «Поздний взгляд» сюда не входит — его ставит человек, и вердикта на самом
#: изменении от этого не появится.
OPEN_STATES: Final = (
    STATE_NONE,
    STATE_CUT,
    STATE_BROKEN,
    STATE_SILENT,
    STATE_RUNNING,
    STATE_CANCELLED,
    STATE_SKIPPED,
    STATE_ODD,
)


def is_open(state: str) -> bool:
    """Перечитывается ли запись с этим состоянием.

    СРАВНЕНИЕ ПО НАЧАЛУ, А НЕ ПО РАВЕНСТВУ, и это не мелочь разбора. Состояние
    «исход, которого разбор не знает» несёт САМ исход суффиксом — иначе оно
    ничего не говорит читателю. При точном равенстве такая запись не попадала
    ни в одну из трёх проверок: она не перечитывалась (то есть не снималась бы
    сама НИКОГДА, вопреки обещанию реестра), не попадала в очередь позднего
    взгляда — и, что хуже всего, считалась «позже просмотренной», то есть
    объявлялась взглядом то, на что никто не смотрел. Нашёл внешний взгляд
    на #187.
    """
    return any(state.startswith(one) for one in OPEN_STATES)


#: Имя проверки, по записи которой на голове различаются причины. Берётся из
#: договора, а не из памяти: имя джоба и есть имя контекста (`docs/pipeline.md`).
REVIEW_CHECK: Final = "review"

#: Скрытая строка, которой поздний взгляд называет себя поздним. Его вердикт
#: тоже строка «ВЕРДИКТ: находок N», и без этой отметки он снял бы запись
#: «взгляда не было»: реестр сказал бы, что взгляд был вовремя, — ровно та
#: подмена, ради которой состояния и разведены (154).
LATE_MARKER: Final = "<!-- late-look: этот взгляд по общей ветке, а не по изменению -->"

#: Запись реестра читается СТРОКОЙ: номер, состояние, дата слияния.
ENTRY_RE: Final = re.compile(r"^- #(\d+) · ([^·]+) · (\S*)(?: · поздний взгляд (\S+))?\s*$", re.M)
#: Хвост записи, которым поздний взгляд ДОПИСЫВАЕТСЯ к состоянию, а не заменяет
#: его. Пока он заменял, после позднего взгляда узнать, ПОЧЕМУ изменение попало
#: в реестр, было нечем — а это и есть мера надёжности канала.
LATE_TAIL: Final = "поздний взгляд"
#: Отметка обхода: до какого номера реестр уже смотрел. Без неё каждый заход
#: перечитывал бы комментарии всего окна — тридцать запросов к площадке на
#: каждое событие очереди.
WATERMARK_RE: Final = re.compile(r"^Просмотрено до: #(\d+)\s*$", re.M)

EXIT_NOTHING: Final = 0
EXIT_BROKEN: Final = 2
EXIT_RECORDED: Final = 3

#: Сколько последних слитых изменений видно за заход. Окно закрывает
#: пропущенное событие, а не заменяет обход истории: если между заходами слито
#: больше, отметка обхода перешагнёт неувиденное, и об этом будет сказано.
#: Значение общее с остальными механизмами окна: «недавно» у них одно.
WINDOW: Final = ghrest.MERGED_WINDOW


class NotRun(RuntimeError):
    """Шаг не отработал: третий исход, а не «всё просмотрено»."""


@dataclass(frozen=True, slots=True)
class Entry:
    """Одна запись реестра: что слито, в каком состоянии, когда и был ли поздний взгляд."""

    number: int
    state: str
    merged: str
    late: str = ""

    def said(self) -> str:
        """Строка записи. Хвост появляется, только если поздний взгляд был."""
        tail = f" · {LATE_TAIL} {self.late}" if self.late else ""
        return f"- #{self.number} · {self.state} · {self.merged}{tail}"


def parse_entries(body: str | None) -> dict[int, Entry]:
    """Разбирает реестр: номер изменения → запись."""
    return {
        int(number): Entry(int(number), state.strip(), merged, late)
        for number, state, merged, late in ENTRY_RE.findall(body or "")
    }


def parse_watermark(body: str | None) -> int:
    """Докуда реестр уже смотрел; ноль — не смотрел никуда."""
    found = WATERMARK_RE.findall(body or "")
    return int(found[-1]) if found else 0


merged_changes = ghrest.merged_changes


def look_of(comments: list[dict[str, Any]], runs: list[dict[str, Any]] | None = None) -> str | None:
    """Что видно о взгляде на изменение: ``None`` — вердикт был, иначе состояние.

    Читаются те же строки тем же разбором, что и у механизма находок: второе
    понимание одного формата разошлось бы с первым молча
    ([090](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/090-shared-helpers-move-up-not-sideways.md)).

    Записи проверок нужны только тогда, когда ответа НЕТ: оборванный ответ сам
    себя объясняет, а «тишина» бывает трёх разных причин.
    """
    if review_findings.verdict_of(comments) is not None:
        return None
    if review_findings.findings_of(comments):
        return STATE_CUT
    return why_quiet(runs or [])


def why_quiet(runs: list[dict[str, Any]]) -> str:
    """Почему ответа нет — по записи проверки взгляда на голове изменения.

    ЗАЧЕМ. Прежде все три случая назывались одним словом «вердикта нет», и
    реестр честно писал, что различить их можно только логом прогона. Лог
    живёт 90 дней и требует прав, а причина нужна тому, кто читает реестр
    ([046](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/046-name-the-gaps-do-not-level-them.md)):
    «прогон упал» зовёт чинить канал, «ключа нет» — настроить секрет, «записи
    нет вовсе» — посмотреть, почему шаг не запускался.

    Площадки здесь нет: записи приходят списком, и подделать их в проверке
    можно, не подделывая транспорт (140).
    """
    ours = [run for run in runs if str(run.get("name") or "") == REVIEW_CHECK]
    if not ours:
        return STATE_NONE

    # ИДУЩИЙ ПРОГОН СИЛЬНЕЕ ЛЮБОГО ПРОШЛОГО ИСХОДА, и порядок здесь — предмет,
    # а не оформление. У имени бывает несколько записей: повторный заход руками
    # кладёт новую рядом со старой. Пока «прошёл» проверялся первым, свежий
    # идущий прогон прятался за вчерашним зелёным — реестр говорил «прошёл, а
    # ответа нет» там, где ответа ещё просто не было. Нашёл внешний взгляд
    # на #180.
    #
    # ИДУЩИМ СЧИТАЕТСЯ ЗАПИСЬ БЕЗ ИСХОДА, а не просто незавершённая: площадка
    # оставляет записи-зомби с готовым `conclusion` при переходном `status`.
    # Тот же приём и по той же причине — в `ci_complete.roster_of`.
    if any(
        str(run.get("status") or "") != "completed" and run.get("conclusion") is None
        for run in ours
    ):
        return STATE_RUNNING
    # Худшее из завершённых: «упал» важнее «прошёл» — иначе повторный зелёный
    # заход спрятал бы упавший.
    if any(str(run.get("conclusion") or "") == "failure" for run in ours):
        return STATE_BROKEN
    if any(str(run.get("conclusion") or "") == "success" for run in ours):
        return STATE_SILENT
    # ЗАПИСЬ ЕСТЬ, А ВЕРДИКТА НЕТ — ЭТО НЕСКОЛЬКО РАЗНЫХ СОСТОЯНИЙ, А НЕ ОДНО.
    # Прежде все они назывались «вердикта нет» — тем же словом, каким
    # называется отсутствие записи ВООБЩЕ. А зовут они к разному: отменённый
    # прогон — посмотреть, кто гасит, пропущенный — прочитать условие шага.
    # Уровнять их значило бы стереть различие, которое уже видно в данных (046).
    if any(str(run.get("conclusion") or "") == "cancelled" for run in ours):
        return STATE_CANCELLED
    if any(str(run.get("conclusion") or "") == "skipped" for run in ours):
        return STATE_SKIPPED
    # ИСХОД, КОТОРОГО РАЗБОР НЕ ЗНАЕТ, НАЗЫВАЕТСЯ, А НЕ СВОРАЧИВАЕТСЯ В «НЕТ
    # ЗАПИСИ». Площадка отдаёт ещё `neutral`, `timed_out`, `action_required`,
    # `stale`; запись при них ЕСТЬ, и говорить «шаг не запускался» значит
    # послать читателя искать не там. Список наших исходов разрешительный, а
    # всё за его пределами получает своё имя вместе с исходом (068, 154).
    # Нашёл внешний взгляд на #180.
    odd = sorted({str(run.get("conclusion")) for run in ours if run.get("conclusion")})
    if odd:
        return f"{STATE_ODD}: {', '.join(odd)}"
    return STATE_NONE


def look_at(repo: str, number: int, token: str) -> str | None:
    """То же по живому изменению: спрашивает площадку и разбирает ответ.

    Комментарии позднего взгляда исключаются по его отметке: они говорят о
    коде в общей ветке, а вопрос здесь — смотрел ли кто-нибудь на изменение,
    пока оно было изменением.
    """
    comments = [
        comment
        for comment in ghrest.paginate(f"repos/{repo}/issues/{number}/comments", token)
        if LATE_MARKER not in (comment.get("body") or "")
    ]
    if review_findings.verdict_of(comments) is not None or review_findings.findings_of(comments):
        # Второй запрос делается ТОЛЬКО ради причины тишины: у изменения с
        # ответом причина уже видна, и платить за неё лишним обращением незачем.
        return look_of(comments)
    return look_of(comments, head_runs(repo, number, token))


def head_runs(repo: str, number: int, token: str) -> list[dict[str, Any]]:
    """Записи проверок на голове изменения; отказ — пустой список, а не падение.

    Причина — уточнение к записи, и потерять из-за неё саму запись значило бы
    разменять факт на подробность о нём (084).
    """
    try:
        change = ghrest.request("GET", f"repos/{repo}/pulls/{number}", token) or {}
        head = str((change.get("head") or {}).get("sha") or "")
        if not head:
            return []
        return list(
            ghrest.paginate(f"repos/{repo}/commits/{head}/check-runs", token, key="check_runs")
        )
    except ghrest.TransportError as exc:
        print(f"  причина по #{number} не выяснена: {report.cut(str(exc))}")
        return []


def scan(
    merged: Iterable[dict[str, Any]],
    known: dict[int, Entry],
    watermark: int,
    look: Callable[[int], str | None],
) -> tuple[dict[int, Entry], int]:
    """Ведёт реестр по окну слитого: новое записывает, просмотренное снимает.

    Площадки здесь нет намеренно: она приходит одним `look`, и подделать её в
    проверке можно, не подделывая транспорт
    ([140](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/140-a-gate-is-tested-by-what-it-must-reject.md)).
    """
    entries = dict(known)
    # Сначала перечитывается уже записанное: вердикт мог опоздать к слиянию, и
    # запись обязана уйти сама, а не ждать, пока её снимут рукой. Состояние при
    # этом тоже уточняется: оборванный ответ бывает дописан.
    for number, entry in list(entries.items()):
        if not is_open(entry.state):
            continue
        state = look(number)
        if state is None:
            entries.pop(number)
        elif state != entry.state:
            entries[number] = Entry(number, state, entry.merged)
    mark = watermark
    for item in merged:
        number = int(item["number"])
        mark = max(mark, number)
        if number <= watermark or number in entries:
            continue
        state = look(number)
        if state is None:
            continue
        entries[number] = Entry(number, state, str(item.get("merged_at") or "")[:10])
    return entries, mark


def mark_late(entries: dict[int, Entry], number: int, day: str) -> dict[int, Entry]:
    """ДОПИСЫВАЕТ поздний взгляд к записи, не трогая её состояния.

    ПРЕЖНЕЕ СОСТОЯНИЕ — ЭТО ОТВЕТ НА ДРУГОЙ ВОПРОС. «Прогон взгляда прошёл, а
    ответа нет» говорит о КАНАЛЕ; «поздний взгляд состоялся» — о том, что
    остаток всё-таки посмотрели. Пока второе заменяло первое, после позднего
    взгляда узнать, почему изменение вообще попало в реестр, было нечем, — а
    счёт этих причин и есть мера надёжности канала. Ровно этого счёта не
    хватило 12.09.2026, когда предмет автоперезапуска искали среди исходов
    проверок, не найдя его там по построению
    (`docs/decisions/014-a-flake-must-be-visible-before-it-is-rerun.md`).

    Записи о таком изменении может и не быть — тогда она заводится, и состояние
    у неё одно: сам поздний взгляд. Терять его из-за того, что реестр этого
    номера не знал, значило бы отчитаться о меньшем, чем было.
    """
    entry = entries.get(number)
    if entry is None:
        return {**entries, number: Entry(number, STATE_LATE, "", day)}
    return {**entries, number: replace(entry, late=day)}


#: Сколько изменений берётся в один заход обхода. Ограничение не про нагрузку
#: площадки, а про цену: каждый поздний взгляд — прогон агента. Три за заход
#: рассасывают очередь за дни, а не за месяцы, и не съедают смену целиком (051).
LOOK_AT_ONCE: Final = 3


def queue_of(entries: dict[int, Entry], limit: int = LOOK_AT_ONCE) -> list[int]:
    """Очередь на поздний взгляд: самые СТАРЫЕ непросмотренные, до `limit`.

    ПОЧЕМУ САМЫЕ СТАРЫЕ. Свежее слитое ещё может получить вердикт само —
    ревьюер бывает медленнее очереди, и запись снимется на следующем заходе.
    Старое такой надежды не имеет: чем дольше изменение лежит без взгляда, тем
    вернее, что его не посмотрит никто.

    «СТАРЫЕ» СЧИТАЮТСЯ ПО ДАТЕ СЛИЯНИЯ, А НЕ ПО НОМЕРУ. Номер говорит, когда
    изменение ОТКРЫЛИ, а очередь про то, сколько оно лежит СЛИТЫМ. Числа
    расходятся ровно в том случае, ради которого очередь и есть: изменение с
    меньшим номером может пролежать на ревью неделю и слиться позже соседа, —
    и тогда сортировка по номеру ставила его первым, хотя по факту слияния оно
    самое свежее. Нашёл внешний взгляд на #131; прежний тест этого не ловил,
    потому что в его выборке номер и дата были упорядочены одинаково
    ([107](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/107-it-works-for-the-author-means-tested-on-the-authors-sample.md)).

    ДАТА МОЖЕТ БЫТЬ ПУСТОЙ — у записи, пришедшей из старой формы реестра.
    Такая идёт ПЕРВОЙ: «даты нет» значит «лежит с неизвестных пор», и ставить
    её в конец очереди означало бы прятать самое старое. Номер остаётся вторым
    ключом — при равной дате порядок обязан быть определённым, иначе заход
    отдаёт разный ответ на одном и том же реестре
    ([053](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/053-queue-order-is-a-rule-not-arrival.md)).

    ПОЧЕМУ ЭТО ЧИСТАЯ ФУНКЦИЯ. Очередь выводится из реестра, а не хранится
    вторым списком: второй разошёлся бы с первым молча
    ([049](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/049-derive-state-from-live-artifacts.md)).
    """
    open_now = [entry for entry in entries.values() if is_open(entry.state)]
    ordered = sorted(open_now, key=lambda entry: (entry.merged or "", entry.number))
    return [entry.number for entry in ordered[:limit]]


