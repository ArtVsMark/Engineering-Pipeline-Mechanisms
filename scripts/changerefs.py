"""Ссылки изменения наружу: задача и снятая находка — одно чтение на всех.

Читали её двое и по-разному. Шаг открытия — строгой строкой целиком
(``^Refs #12$``), гейт разметки — свободным поиском по заголовку и телу. Строка
`Refs #2, #29`, написанная в коммите, для первого не существовала вовсе: он
**молча** открыл изменение без раздела связи — ровно то изменение, которое
гейт тут же отверг. Один вход, два понимания: тот же дрейф, что был на составе
меток, только на другом поле.

Цена замерена: PR #32, красный `pr-meta` на здоровом коммите, где связь с
задачей была написана и человеком читалась.

СПИСОК ПОСЛЕ ОДНОГО ГЛАГОЛА РАЗБИРАЕТСЯ, НО В ТЕЛО ИДЁТ ПО СТРОКЕ НА ЗАДАЧУ.
По документации площадки ключевое слово действует на **каждый** номер
отдельно: `Closes #12, #13` закрывает только первую задачу. Замером это здесь
не проверялось и помечено гипотезой
([044](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/044-check-the-premise-before-fixing.md)),
но собирать тело по строке на задачу дешевле, чем выяснять это отказом при
слиянии.

ЗДЕСЬ ЖЕ ЧИТАЕТСЯ СНЯТИЕ НАХОДКИ. Строка `Разобрано: <отпечаток>` снимает
запись из живой задачи-адресата, и ищется она в теле СЛИТОГО изменения. Тело
собирает шаг открытия из коммитов — значит перенести строку туда обязан он,
иначе «снятие едет вместе с работой» держится тем, что кто-то вспомнит про
описание. Разбор общий по той же причине, что и у связи с задачей: два чтения
одной строки расходятся молча.
"""

from __future__ import annotations

import re
from collections.abc import Iterable, Iterator
from dataclasses import dataclass
from typing import Final

#: Глаголы читаются списком разрешённого (068). Новый глагол добавляется сюда
#: осознанно: `resolves` площадка понимает, а этот проект — нет, и добавить его
#: значит поменять поведение обоих механизмов сразу.
VERBS: Final = ("closes", "fixes", "refs", "part of")
CANON: Final = {"closes": "Closes", "fixes": "Fixes", "refs": "Refs", "part of": "Part of"}
CLOSING: Final = frozenset({"Closes", "Fixes"})

LINK_RE: Final = re.compile(
    r"\b(?P<verb>" + "|".join(VERBS) + r")\s+(?P<tasks>#\d+(?:\s*,\s*#?\d+)*)",
    re.IGNORECASE,
)
NUMBER_RE: Final = re.compile(r"#?(\d+)")
#: Кодовые вставки из разбора вырезаются: площадка ключевые слова внутри них
#: тоже не читает. Замер, стоивший ложной связи: описание правки цитировало
#: старую регулярку `^Refs #12$`, и механизм записал изменению задачу #12,
#: которой оно не касается (PR #32). Пример в тексте — не ссылка.
INLINE_RE: Final = re.compile(r"`[^`\n]*`")
#: Забор блока узнаётся по началу строки, как его понимает и разметка.
FENCE_RE: Final = re.compile(r"^\s*```")
#: Отступный блок кода: четыре пробела (или табуляция) после пустой строки.
#: Разметка читает его как код, а разбор — не читал, и пример внутри него
#: становился настоящим ключом. Замер 21.09.2026 (#581): так подрывались ВСЕ
#: ПЯТЬ ключей сразу, и первым это случилось вживую — изменение #579 открылось
#: со стоп-меткой, которой никто не ставил, а причиной в теле стоял пример из
#: тела коммита. Нашёл владелец, а не набор.
#:
#: ЧИНИТСЯ МАСКИРОВКОЙ, А НЕ ПРИВЯЗКОЙ КЛЮЧА К ПЕРВОЙ КОЛОНКЕ. Привязка
#: пробовалась и отвергнута прогоном: она ломает два ОБЪЯВЛЕННЫХ свойства —
#: связь читается посреди строки («см. refs #9 в теле») и две связи на одной
#: строке различимы. У проекта уже выбран ответ на «где кончается пример»: им
#: ответили на инцидент #32, где цитата регулярки записала изменению чужую
#: задачу, и ответом была маскировка (022, 090).
#:
#: ГРАНИЦА НАЗВАНА: продолжение пункта списка, отбитое четырьмя пробелами, тоже
#: замаскируется. Цена измерена, а не оценена — в 577 коммитах истории ключей с
#: отступом НОЛЬ при 1179 в первой колонке, и в 300 изменениях на площадке
#: столько же ([046](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/046-name-the-gaps-do-not-level-them.md)).
INDENTED_RE: Final = re.compile(r"^(?: {4}|\t)")
#: Отпечаток находки — семь шестнадцатеричных знаков, как короткий хэш.
#: Кавычки вокруг отпечатка допускаются: строку пишет человек, и оформить хэш
#: как код — первое, что он делает. Без этого отпечаток в кавычках терялся
#: молча: разбор вырезал кодовую вставку раньше, чем доходил до отпечатка.
#:
#: СТРОКА НЕСЁТ СПИСОК, А НЕ ОДИН ОТПЕЧАТОК. Прежний образец брал ровно первый
#: и молча терял остальные: изменение #325 сняло семь находок, а из реестра
#: ушла одна — шесть починенных остались висеть как неразобранные. Нашёл это
#: внешний взгляд, и иначе бы никто: снятие выглядело удавшимся. Форма списка
#: не выдумана — ею же читаются связи с задачами (`Refs #1, #2`), и автор
#: вправе ждать того же здесь
#: ([045](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/045-no-silent-fallback.md)).
RESOLVED_RE: Final = re.compile(
    r"^\s*(?P<mark>Разобрано:)\s*(?P<text>[0-9a-f`][^\n]*)", re.IGNORECASE | re.MULTILINE
)

#: Отпечатки ИЗ ГОЛОВЫ хвоста: подряд, через запятую, пробел или кавычку.
#: Разбор кончается на первом же слове, отпечатком не являющемся, — так
#: «`abc1234` — почему» по-прежнему снимает одну находку и не ищет хэшей в
#: пояснении, где семь букв подряд из a—f сложились бы случайно (068).
#: Хвостовая разметка входит в ПРОБЕГ отпечатков, а не в причину: иначе
#: закрывающая кавычка от «`abc1234`» уезжала в пояснение и печаталась в общей
#: ветке огрызком.
MARK_RUN_RE: Final = re.compile(r"\A(?:[\s,;`]*[0-9a-f]{7}(?![0-9a-f]))+[\s,;`]*")
MARK_RE: Final = re.compile(r"[0-9a-f]{7}")
#: Дубль после отпечатков: `Разобрано: A дубль B`. Снимаются ОБА — строку так
#: пишут, и архив (`findings_archive`) читает её парой. Пока разбор брал
#: отпечатки только до первого слова, B уходила в пояснение и висела в реестре
#: исправленной: четыре такие записи на 25.09.2026 (#807).
TWIN_RE: Final = re.compile(
    r"\A\s*дубль(?=[\s`])((?:[\s,;`]*[0-9a-f]{7}(?![0-9a-f]))+)[\s,;`]*", re.IGNORECASE
)
#: ЗАКРЫТЫЙ ПУНКТ ЧЕК-ЛИСТА. Площадка умеет только полное закрытие: `Closes #N`
#: закрывает задачу целиком, и задача из нескольких этапов закрывается
#: преждевременно вместе с несделанными. `Refs #N` не отмечает ничего, и после
#: десяти изменений непонятно, что в задаче сделано.
#:
#: Отметка едет ВМЕСТЕ С РАБОТОЙ, тем же приёмом, что снятие находки: строка в
#: теле изменения, а не отдельный жест, который забудут (002).
#:
#: Пункт называется ТЕКСТОМ, а не номером строки: номер сдвигается от любой
#: правки тела задачи, и отметка уехала бы на соседний пункт молча.
CLOSED_ITEM_RE: Final = re.compile(
    r"^\s*(?P<mark>Закрывает пункт:)\s*(?P<text>\S.*?)\s*$", re.IGNORECASE | re.MULTILINE
)

#: ЗАДЕРЖКА, ОБЪЯВЛЕННАЯ ДО ОТКРЫТИЯ. Стоп-метку `hold` можно поставить только
#: ПОСЛЕ того, как изменение открыто, а согласие очереди шаг открытия ставит
#: сразу — между этими мгновениями изменение полностью готово к слиянию.
#:
#: ЗАМЕР 19.09.2026 ПО ЖИВОЙ ЛЕНТЕ СОБЫТИЙ #549: `automerge` в 19:40:09,
#: снят в 19:40:40, `hold` в 19:40:41 — согласие простояло 31 секунду на
#: изменении, которое сливать было нельзя. Спасло только то, что обязательная
#: проверка была в ту минуту красной; внешний взгляд назвал это риском и был
#: прав — сливал бы `automerge`, а не проза в комментарии файла
#: ([002](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/002-rule-without-mechanism.md)).
#:
#: Трейлер едет В КОММИТЕ, то есть существует раньше изменения, и шаг открытия
#: читает его до того, как поставит согласие. Причина обязательна: задержка без
#: причины неотличима от забытой метки (154).
#: Чего ждёт задержанное изменение — строкой в теле коммита. Ключ тот же, что
#: у строки в теле ИЗМЕНЕНИЯ (решение 018), и это не совпадение имён, а
#: намерение: перевода между ними нет вовсе.
#:
#: КЛЮЧ БЫЛ `Hold:` И ПЕРЕИМЕНОВАН 21.09.2026 ПО ДВУМ ПРИЧИНАМ (#587).
#:
#: ПЕРВАЯ — ЯЗЫК, и её назвал владелец. Ключей в теле у проекта пять: три
#: своих (`Разобрано:`, `Закрывает пункт:`, `Ждёт:`) написаны по-русски, а
#: `Refs`/`Closes` по-английски вынужденно — их разбирает площадка. `Hold:`
#: был единственным СВОИМ ключом на чужом языке, и принуждения у него не было
#: никакого. Метки площадки при этом остаются английскими: это другая
#: поверхность с другим читателем
#: ([021](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/021-split-docs-by-reader.md)).
#:
#: ВТОРАЯ — ПЕРЕВОД, и она дороже. Автор писал `Hold:`, шаг открытия клал в
#: тело изменения прозу, а `stuck.py` искал `Ждёт:` — и не находил. Внешний
#: взгляд нашёл дефект: задержка с ЯВНО названной причиной попадала в реестр
#: застрявших как ЗАБЫТАЯ метка (находка `fb95a71` на #579). Два имени одной
#: вещи разошлись ровно там, где их стык
#: ([022](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/022-one-canonical-document.md)).
#: Теперь строка одна от тела коммита до реестра, и переводить нечего.
#: Какой красный шаг общей ветки чинит изменение — строкой в теле коммита.
#: Ключ по-русски, как и соседи: чужие здесь только `Refs`/`Closes`, которые
#: разбирает площадка.
#:
#: ЗАЧЕМ ЭТО ЕСТЬ (#585). Красная общая ветка замораживает очередь, и выход из
#: заморозки — метка `fix-main`. Ставит её ЧЕЛОВЕК, и пока его нет, починка не
#: уезжает: замер 20.09.2026 — #565 простояла зелёной и неслитой; замер
#: 21.09.2026 — #583 не уехала бы вовсе без двух вмешательств владельца.
#: Выход был заперт на того, кого может не быть
#: ([126](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/126-a-freeze-needs-a-thaw-path.md)).
#:
#: ОКНО НЕ РЕШАЕТ, ЧТО СЧИТАТЬ ПОЧИНКОЙ, — ОНО ПРЕДЪЯВЛЯЕТ ПРЕДМЕТ. Строка
#: называет ИМЯ шага, и шаг открытия спрашивает у площадки, красен ли он на
#: голове общей ветки. Не красен — метки нет, и отказ называет, чего не хватило
#: ([154](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/154-none-must-name-its-reason.md),
#: [051](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/051-warn-on-likely-block-on-certain.md)).
FIXES_MAIN_RE: Final = re.compile(
    r"^\s*(?P<mark>Чинит main:)\s*(?P<text>\S.*?)\s*$", re.IGNORECASE | re.MULTILINE
)

#: БУКВА «Ё» НЕОБЯЗАТЕЛЬНА, И ЭТО НЕ ПОБЛАЖКА (#602). Прежний ключ `Hold:` был
#: ASCII и этой развилки не знал; русский знает: «Ждет» вместо «Ждёт» — обычная
#: замена при наборе, и молчаливая потеря ключа здесь стоит дорого — задержка
#: не встанет, а изменение уйдёт в очередь. Нашёл внешний взгляд находкой
#: `0b3e86b`. Регистр ключ и так не различает; буква «ё» — тот же класс
#: ([045](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/045-no-silent-fallback.md)).
WAITS_RE: Final = re.compile(
    r"^\s*(?P<mark>Жд[её]т:)\s*(?P<text>\S.*?)\s*$", re.IGNORECASE | re.MULTILINE
)


@dataclass(frozen=True, slots=True)
class Link:
    """Одна связь: глагол и номер задачи."""

    verb: str
    number: int

    def __str__(self) -> str:
        """Строка ровно того вида, который читает площадка."""
        return f"{self.verb} #{self.number}"

    @property
    def closes(self) -> bool:
        """Закроет ли эта связь задачу при слиянии."""
        return self.verb in CLOSING


@dataclass(frozen=True, slots=True)
class Resolution:
    """Одно снятие: отпечатки из головы строки и причина, как написал автор."""

    marks: tuple[str, ...]
    why: str
    #: Группы отпечатков, разделённые словом «дубль», как написал автор. Пусто —
    #: одна группа, `marks`. Хранятся затем, чтобы строка доехала до тела
    #: изменения В ТОЙ ЖЕ ФОРМЕ: архив читает связь дублей оттуда (#807).
    groups: tuple[tuple[str, ...], ...] = ()

    @property
    def twin_of(self) -> dict[str, str]:
        """Отпечаток → первый отпечаток следующей группы: «A дубль B» — A дубль B."""
        found: dict[str, str] = {}
        for here, there in zip(self.groups, self.groups[1:], strict=False):
            for mark in here:
                found[mark] = there[0]
        return found

    def __str__(self) -> str:
        """Строка того вида, который едет в тело изменения и читает человек."""
        said = " дубль ".join(", ".join(group) for group in self.groups or (self.marks,))
        return f"Разобрано: {said} {self.why}".rstrip()


def blank(match: re.Match[str]) -> str:
    """Пробелы вместо вырезанного — ровно столько же, сколько было знаков."""
    return " " * len(match.group(0))


def outside_code(text: str) -> str:
    """Текст без кодовых вставок: пример в них ссылкой не считается.

    Разбор построчный и НЕ ЖАДНЫЙ через границы, потому что шаг открытия
    склеивает тела всех коммитов ветки в один текст. Одним образцом это
    ловится дважды и оба раза молча:

    * одиночная кавычка без пары тянулась до следующей — через абзацы и через
      границу коммита, унося строку связи из соседнего;
    * незакрытый забор смыкался не со своим концом, а с ОТКРЫВАЮЩИМ забором
      настоящего блока из более позднего коммита, съедая всё между ними.

    Оба замера сделаны на подделанном входе, оба показали пропажу `Refs #N`.
    Цена молчания — ветка с честно названной задачей, которая не открывается:
    связи не нашлось, шаг отказал.

    Поэтому: непарное число заборов означает, что блоков в тексте нет вовсе —
    заборы тогда просто разметка, и вырезать по ним нечего. Опечатка не
    уносит данные с собой.
    """
    return "\n".join(mask for mask, _ in masked_lines(text))


def masked_lines(text: str) -> list[tuple[str, str]]:
    """Строки текста парами «маска, как есть».

    Маска — строка с вырезанным кодом: по ней РЕШАЮТ, настоящая это строка или
    пример. Оригинал нужен тем, кто берёт из строки текст: инлайн-код внутри
    пункта — часть пункта, а не пример.

    ЗАМЕР 10.09.2026, на слиянии #88. Пункт «`debt` печатает это число рядом с
    находками и правилами» приехал в тело изменения как «печатает это число
    рядом с находками и правилами»: разбор вырезал `debt` вместе с кавычками
    ДО того, как взял текст. В задаче пункт остался целым, совпадения не
    вышло, и механизм честно сказал «пункт не найден» — то есть отметил не всё
    и назвал это вслух, но пункт остался неотмеченным, а человек увидел в теле
    изменения огрызок собственной строки
    ([045](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/045-no-silent-fallback.md)).
    """
    lines = text.splitlines()
    fences = {index for index, line in enumerate(lines) if FENCE_RE.match(line)}
    # Незакрытый забор не открывает блок: половина пары — это не пара.
    paired = len(fences) % 2 == 0

    pairs: list[tuple[str, str]] = []
    inside = False
    blank_before = True
    indented_run = False
    for index, line in enumerate(lines):
        if paired and index in fences:
            inside = not inside
            pairs.append((" " * len(line), line))
            blank_before = False
            continue
        # ОТСТУПНЫЙ БЛОК ОТКРЫВАЕТСЯ ТОЛЬКО ПОСЛЕ ПУСТОЙ СТРОКИ — так его
        # понимает и разметка. Без этого условия замаскировалась бы любая
        # отбитая строка, включая перенос абзаца, и предикат стал бы шире
        # предмета вчетверо (195).
        indented = INDENTED_RE.match(line) is not None and (blank_before or indented_run)
        # Длина сохраняется: по маске сверяют ПОЛОЖЕНИЕ маркера в оригинале, а
        # сдвиг на длину вырезанного увёл бы сверку на соседние знаки.
        masked = " " * len(line) if inside or indented else INLINE_RE.sub(blank, line)
        pairs.append((masked, line))
        indented_run = indented
        blank_before = not line.strip()
    return pairs


def marked_lines(text: str, pattern: re.Pattern[str]) -> Iterator[re.Match[str]]:
    """Совпадения построчного маркера: решает маска, а текст даёт оригинал.

    Один разбор на всех, кто читает строку-маркер: у `Разобрано:` и у
    `Закрывает пункт:` предмет разный, а вопрос один — где кончается пример и
    начинается настоящая строка
    ([090](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/090-shared-helpers-move-up-not-sideways.md)).

    Образец обязан назвать две группы: ``mark`` — сам маркер, по нему решают,
    настоящая строка или пример, и ``text`` — то, что из строки берут.
    """
    for mask, line in masked_lines(text):
        for found in pattern.finditer(line):
            # Настоящий маркер — тот, что в маске уцелел. Сверяется ровно он, а
            # не вся строка: сам текст вырезанным быть вправе — инлайн-код
            # внутри пункта это часть пункта, а не пример, и отпечаток человек
            # оформляет кодом чаще, чем не оформляет.
            head = slice(*found.span("mark"))
            if mask[head] == line[head]:
                yield found


def links_in(text: str) -> list[Link]:
    """Связи с задачами в порядке появления, без повторов."""
    found: list[Link] = []
    seen: set[tuple[str, int]] = set()
    for match in LINK_RE.finditer(outside_code(text)):
        verb = CANON[match["verb"].lower()]
        for number in NUMBER_RE.findall(match["tasks"]):
            key = (verb, int(number))
            if key in seen:
                continue
            seen.add(key)
            found.append(Link(verb, int(number)))
    return found


def has_link(text: str) -> bool:
    """Названа ли в тексте хотя бы одна задача."""
    return bool(links_in(text))


def resolved_in(text: str) -> list[str]:
    """Отпечатки находок, названных разобранными, в порядке появления.

    Строка читается ЦЕЛИКОМ, а не первым отпечатком: одно изменение снимает
    столько находок, сколько починило, и молча оставить шесть из семи — значит
    сказать реестру неправду о сделанной работе (045).
    """
    found: list[str] = []
    for record in resolutions_parsed(text):
        for mark in record.marks:
            if mark not in found:
                found.append(mark)
    return found


def resolutions_parsed(text: str) -> list[Resolution]:
    """Снятия одного текста РАЗОБРАННЫМИ: отпечатки отдельно, причина отдельно.

    Один разбор на всех читателей строки, а их трое: реестру нужны отпечатки,
    телу изменения — строка целиком, а сверке повторов — отпечатки внутри
    строки. Пока разбор был у каждого свой, они расходились молча: сборка по
    ветке искала отпечатки во ВСЕЙ строке, включая причину, — то есть список из
    разрешительного становился запретительным, ровно против 068. Замер
    14.09.2026: «Разобрано: 1111111 — сосед deadbeef рядом» давал лишний
    отпечаток `deadbee`, и настоящее снятие `deadbee` из следующего коммита
    ветки в общую ветку не уезжало (090).
    """
    found: list[Resolution] = []
    for match in marked_lines(text, RESOLVED_RE):
        tail = match.group("text").strip()
        run = MARK_RUN_RE.match(tail.lower())
        if not run:
            continue
        groups = [tuple(MARK_RE.findall(run.group(0)))]
        rest = tail[run.end() :]
        # ЦЕПОЧКА ДУБЛЕЙ, А НЕ ОДИН: `A, C дубль B, D дубль E`. Всё, что стоит в
        # цепочке, снимается — это один дефект, названный несколько раз, и
        # работа, починившая одно имя, починила все (решение владельца
        # 25.09.2026, #807). Дубль, взятый одним, оставлял C и D пояснением
        # (взгляд на #809, та же беда, что #325 у списка).
        while twin := TWIN_RE.match(rest):
            groups.append(tuple(MARK_RE.findall(twin.group(1).lower())))
            rest = rest[twin.end() :]
        marks = tuple(mark for group in groups for mark in group)
        found.append(Resolution(marks, rest.strip(), tuple(groups) if len(groups) > 1 else ()))
    return found


def closed_items_in(text: str) -> list[str]:
    """Пункты чек-листа, названные закрытыми, — КАК НАПИСАНЫ, в порядке появления.

    Приведённый вид отдавать нельзя: строка едет в тело изменения и попадается
    на глаза человеку, а приведение опускает регистр и срезает знак в конце.
    Читатель увидел бы не пункт задачи, а его огрызок. Приводится текст только
    при сравнении — там, где это и нужно.

    Повторы при этом снимаются ПО ПРИВЕДЁННОМУ виду: «Первый пункт» и «первый
    пункт;» — один и тот же пункт, названный дважды.
    """
    found: list[str] = []
    seen: set[str] = set()
    for match in marked_lines(text, CLOSED_ITEM_RE):
        item = match.group("text")
        cleaned = " ".join(item.split())
        key = normalise(item)
        if key and key not in seen:
            seen.add(key)
            found.append(cleaned)
    return found


#: Хвост, который к пункту не относится: разметка вокруг и знак конца строки.
#: В теле задачи пункты идут списком и кончаются точкой с запятой или точкой,
#: а в теле изменения их пишут рукой и без неё.
ITEM_EDGES: Final = "*_`.,;:!? \t"


def normalise(text: str) -> str:
    """Приводит пункт к виду, в котором его сравнивают.

    Перенос строки, лишние пробелы, оформление и знак в конце — не часть
    пункта: в теле задачи он живёт с разметкой и заканчивается точкой с
    запятой, а в теле изменения его пишут рукой. Сравнивать посимвольно значило
    бы требовать совпадения того, что совпадать не обязано.

    ЗАМЕР 09.09.2026, на самом этом механизме. Первое же слияние с объявленным
    пунктом ничего не отметило: в задаче #26 пункт кончается «;», в теле
    изменения — нет. Механизм честно сказал «пункт не найден» — то есть
    поломка была видна, а не молчалива, — но работать от этого не начал.
    """
    return " ".join(text.split()).strip(ITEM_EDGES).lower()


def links_in_all(texts: Iterable[str]) -> list[Link]:
    """Связи из НЕСКОЛЬКИХ текстов, каждый со своей разметкой.

    Границы текстов знает вызывающий, разбор — нет, и склеенные тела коммитов
    для него неразличимы. Замер на подделанном входе: два коммита, в каждом
    свой незакрытый забор. Число заборов чётное, разбор считает их парой и
    вырезает всё между ними — вместе с настоящей строкой связи. Ни счётом, ни
    третьим образцом это не лечится: одна разметка на два документа.

    Поэтому тела разбираются по одному, а объединяются уже связи.
    """
    found: list[Link] = []
    seen: set[tuple[str, int]] = set()
    for text in texts:
        for link in links_in(text):
            key = (link.verb, link.number)
            if key in seen:
                continue
            seen.add(key)
            found.append(link)
    return found


def resolutions_in_all(texts: Iterable[str]) -> list[str]:
    """Строки снятия со всех тел ветки: один отпечаток — ровно одна запись.

    ПОВТОР УЗНАЁТСЯ ПО ОТПЕЧАТКУ, А НЕ ПО СТРОКЕ. Одну находку разбирают в
    нескольких коммитах ветки, и текст рядом с ней каждый раз свой: «Разобрано:
    abc1234» и «Разобрано: abc1234 — премиса не подтвердилась» — это одно
    снятие, описанное дважды. Сверка строк пропускала оба, и в общую ветку
    ехали две записи об одной находке (нашёл внешний взгляд на #331).

    ПОБЕЖДАЕТ ПЕРВАЯ ЗАПИСЬ отпечатка: она ближе к работе, которая его сняла.

    ПОВТОР СНИМАЕТСЯ С ОТПЕЧАТКА, А НЕ СО СТРОКИ. Строка несёт список, и у
    второй строки ветки часть отпечатков бывает новой: «Разобрано: abc1234,
    def5678» после «Разобрано: abc1234» — это одно повторённое снятие и одно
    новое. Прежде вся строка отбрасывалась по одному совпадению, и `def5678`
    пропадал молча: работа сделана, а запись в реестре осталась висеть
    неразобранной — тот же вред, что у потери шести отпечатков из семи на #325
    ([045](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/045-no-silent-fallback.md)).
    Замер 14.09.2026 на этих двух телах: из двух снятий уезжало одно.

    ПРИЧИНА ОСТАЁТСЯ ПРИ УЦЕЛЕВШИХ отпечатках: автор писал её обо всей строке,
    и отбросить её вместе с уже записанным отпечатком значило бы снова свести
    два исхода снятия к одному (039).

    ПОЧЕМУ ОДНИХ ОТПЕЧАТКОВ НЕ ХВАТАЕТ — ДОВОД ПЕРЕЕХАЛ СЮДА С `resolutions_in`
    ВМЕСТЕ С ПРЕДМЕТОМ. У снятия два разных исхода: находка ПОЧИНЕНА либо её
    премиса НЕ ПОДТВЕРДИЛАСЬ — и второй закрывается «как неверная, с записью
    причины», иначе вернётся следующим обходом
    ([044](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/044-check-the-premise-before-fixing.md)).
    В общую ветку же ехал ГОЛЫЙ ОТПЕЧАТОК: тело уплотнения собиралось из
    отпечатков заново, и причина, написанная автором, терялась по дороге. Через
    месяц два исхода в истории неотличимы (039).

    СТРОКА ОТДАЁТСЯ КАК НАПИСАНА, приводится только регистр отпечатков: причину
    читает человек, и огрызок пояснения хуже его отсутствия.
    """
    found: list[str] = []
    seen: set[str] = set()
    for text in texts:
        for record in resolutions_parsed(text):
            fresh: list[str] = []
            for mark in record.marks:
                if mark not in seen and mark not in fresh:
                    fresh.append(mark)
            if not fresh:
                continue
            seen.update(fresh)
            # СТРОКА С «ДУБЛЬ» ЕДЕТ ЦЕЛИКОМ. Тело уплотнения собирается здесь, и
            # строка без групп приезжала в общую ветку списком: архив терял связь
            # дублей по дороге (взгляд на #809). Резать группы по уже снятому
            # нельзя: «Разобрано: B», затем «A дубль B» дали бы «Разобрано: A» —
            # связи нет, а у «A дубль B дубль C» при снятом B — выдуманную A→C
            # (взгляд на #814). Повтор снятого безвреден: архив и реестр ставят
            # снятие через `setdefault`.
            if len(record.groups) > 1:
                found.append(str(record))
                continue
            found.append(str(Resolution(tuple(fresh), record.why)))
    return found


def held_in(text: str) -> str | None:
    """Причина задержки, объявленной трейлером, или ``None``.

    Причина отдаётся КАК НАПИСАНА: она едет в тело изменения и попадается на
    глаза человеку — тому же читателю, что и у снятых находок.
    """
    for match in marked_lines(text, WAITS_RE):
        said = " ".join(match.group("text").split())
        if said:
            return said
    return None


def fixes_main_in(text: str) -> str | None:
    """Имя красного шага, который изменение объявляет чинимым, или ``None``.

    Разбор общий с прочими ключами — тем же `marked_lines`: пример в блоке кода
    объявлением не становится
    ([090](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/090-shared-helpers-move-up-not-sideways.md)).
    """
    for match in marked_lines(text, FIXES_MAIN_RE):
        said = " ".join(match.group("text").split())
        if said:
            return said
    return None


def fixes_main_in_all(texts: Iterable[str]) -> str | None:
    """Объявление из нескольких тел: ПЕРВОЕ названное имя.

    Хватает одного: изменение чинит красноту общей ветки или нет, и второе имя
    в соседнем коммите того же не усиливает.
    """
    for text in texts:
        said = fixes_main_in(text)
        if said:
            return said
    return None


def held_in_all(texts: Iterable[str]) -> str | None:
    """Задержка из нескольких тел: ПЕРВАЯ названная причина.

    Хватает одной: задержка — состояние изменения, а не список. Второй трейлер
    в соседнем коммите ту же задержку не усиливает, и складывать причины
    значило бы выдавать одно решение за несколько.
    """
    for text in texts:
        said = held_in(text)
        if said:
            return said
    return None


def resolved_in_all(texts: Iterable[str]) -> list[str]:
    """Снятия находок из нескольких текстов — по той же причине, что и связи."""
    found: list[str] = []
    for text in texts:
        for mark in resolved_in(text):
            if mark not in found:
                found.append(mark)
    return found


def closed_items_in_all(texts: Iterable[str]) -> list[str]:
    """Закрытые пункты из нескольких текстов — по той же причине, что и связи.

    Повтор снимается ПО ПРИВЕДЁННОМУ виду, а не по строке. Один пункт,
    объявленный в двух коммитах ветки с разной раскладкой или знаком в конце,
    попал бы в тело изменения дважды — и человек читал бы это как два разных
    пункта. Внутри одного текста это уже так; между текстами было по строке.
    """
    found: list[str] = []
    seen: set[str] = set()
    for text in texts:
        for item in closed_items_in(text):
            key = normalise(item)
            if key not in seen:
                seen.add(key)
                found.append(item)
    return found
