#: Номер прогона внутри адреса записи проверки: `…/actions/runs/<id>/job/<id>`.
#: Разбор один на весь конвейер — у очереди (214): второй образец расходился
#: бы с первым молча при правке одного из них.
RUN_ID_RE: Final = automerge.RUN_ID_RE
#: Мигание в теле задачи: копится списком, потому что событие в артефактах не
#: остаётся. Читается строкой, чтобы заход не заводил его заново.
#: ПЕРЕВОД СТРОКИ В ИМЯ НЕ ВХОДИТ, И ЭТО НЕ ПРИДИРКА. Класс с отрицанием
#: (`[^·]`) матчит и перевод строки: имя первого мигания заглатывало ВСЁ тело до
#: первой настоящей записи — вместе с заголовками разделов, — а сборка печатала
#: это обратно. Реестр рос с каждым заходом и врал читателю двумя списками одного
#: раздела. Замер 14.09.2026: 19 «миганий», первое из них полтора килобайта, шесть
#: разделов вместо трёх, тело выросло за один заход с 3052 до 3144 знаков
#: ([045](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/045-no-silent-fallback.md)).
FLAKE_RE: Final = re.compile(
    r"^- (?P<name>[^·\n]+) · (?P<day>\S+) · прогон (?P<run>\d+)(?: · (?P<where>\S+))?\s*$",
    re.M,
)

#: Где мигнуло, если не на общей ветке. Умолчание молчаливое намеренно: записи
#: общей ветки были заведены раньше и переписывать их задним числом незачем.
SHARED: Final = "общая ветка"

EXIT_GREEN: Final = 0
EXIT_BROKEN: Final = 2
EXIT_RED: Final = 3


class NotRun(RuntimeError):
    """Шаг не отработал: третий исход, а не «ветка зелена»."""


@dataclass(frozen=True, slots=True)
class Flake:
    """Мигание: имя проверки, день, прогон и где это увидели."""

    name: str
    day: str
    run: int
    where: str = SHARED

    def said(self) -> str:
        """Строка записи. Общая ветка не подписывается: она умолчание."""
        tail = "" if self.where == SHARED else f" · {self.where}"
        return f"- {self.name} · {self.day} · прогон {self.run}{tail}"

    @property
    def same(self) -> tuple[str, int]:
        """ТОЖДЕСТВО МИГАНИЯ: имя проверки и прогон, на котором его увидели.

        Объявлено ОДИН раз и здесь, потому что спрашивают его двое — отсев
        повтора при чтении и добавление новой записи, — а два ключа для одного
        понятия расходятся молча (022, 090). Именно это и разошлось: чтение
        отсеивало по `(имя, прогон, где)`, добавление считало тождеством
        `(имя, прогон)`, и повтор с иным «где» при том же прогоне читателем не
        отсеивался. Нашёл внешний взгляд находками `acdf734` и `f8d8414` на #372.

        «ГДЕ» В ТОЖДЕСТВО НЕ ВХОДИТ, И ЭТО НЕ УПРОЩЕНИЕ. Прогон принадлежит ровно
        одному месту: из номера прогона место выводится, а не выбирается. Две
        записи одного прогона с разным «где» означают не два мигания, а ошибку
        записи — и вторую из них надо отсеять, а не сохранить как отдельную.

        ДЕНЬ В ТОЖДЕСТВО НЕ ВХОДИТ ПО ТОЙ ЖЕ ПРИЧИНЕ: он свойство наблюдения, а
        не мигания, и одно мигание не становится двумя от того, что его
        перезаписали назавтра.
        """
        return (self.name, self.run)


#: Исходы, которые считаются НАСТОЯЩИМ красным. Отменённая и пропущенная сюда не
#: входят: пройденной ни одна не считается, но и отказом не является.
REAL_RED: Final = frozenset({"failure", "timed_out", "action_required"})

#: Прогон, которым доказывается зелень общей ветки. Имя файла, а не номер
#: площадки: номер в дереве не виден и сверить его нечем, а файл виден оба раза
#: ([049](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/049-derive-state-from-live-artifacts.md)).
PROOF_RUN: Final = "ci.yml"

#: ПРЕДЕЛ ПОПЫТОК ДОКАЗАТЬ ЗЕЛЕНЬ. «Чиним, пока не позеленеет» без предела не
#: сходится, если причина не в коде вовсе — отказал внешний сервис, кончились
#: исполнители. После предела следующий шаг не починка, а владелец
#: ([109](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/109-every-exit-from-a-transient-state-must-be-terminal.md),
#: [100](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/100-two-deadlines-start-and-work.md)).
#:
#: ПОЧЕМУ ТРИ. Два — это одна починка: красное бывает и от осечки площадки, и
#: отдавать владельцу после единственной попытки значило бы будить его на
#: мигании. Пять — три починки подряд по одной причине; если две не помогли,
#: третья тем же способом не поможет тоже. Число объявлено, а не выведено из
#: замера, и это сказано: замер 14.09.2026 по 273 прогонам `ci` на общей ветке
#: нашёл пять красных полос, и каждая длиной в ОДИН заход — полосы длиннее в
#: проекте не случалось ни разу. То есть предел сегодня не срабатывает, и цена
#: его объявления — ноль; условие пересмотра — в записи решения 021.
TRIES_LIMIT: Final = 3


@dataclass(frozen=True, slots=True)
class Proof:
    """Счёт неудачных доказательств зелени: число и полнота замера."""

    tries: int
    whole: bool

    @property
    def spent(self) -> bool:
        """Исчерпан ли предел попыток — то есть дальше владелец, а не починка."""
        return self.tries >= TRIES_LIMIT

    def said(self) -> str:
        """Число словами. Неполный замер называет себя НЕ МЕНЬШЕ, а не точным."""
        about = "не меньше " if not self.whole else ""
        return f"{about}{self.tries}"


def proofs(repo: str, token: str) -> Proof:
    """Сколько заходов подряд НЕ доказали зелень общей ветки.

    СЧЁТЧИК ВЫВОДИТСЯ ИЗ ПЛОЩАДКИ, А НЕ ХРАНИТСЯ — по той же причине, что и
    номер попытки прогона: свой счётчик разошёлся бы с ней молча, и в сторону
    бесконечных попыток (049). Попытка здесь — ЗАХОД, доказывающий зелень:
    слияние починки, ручная кнопка, заход по расписанию. Именно так это и
    объявлено в контуре 3: «Проверка» считает прогоны от расписания и от руки,
    потому что доказательство зелени не имеет права идти через замороженное
    слияние ([126](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/126-a-freeze-needs-a-thaw-path.md)).

    ОТМЕНЁННАЯ ПОПЫТКОЙ НЕ СЧИТАЕТСЯ И ПОЛОСУ НЕ РВЁТ: у неё нет вердикта
    вовсе, а считать отсутствие вердикта доказательством зелени — то же
    молчаливое умолчание, от которого страхует 045. Такой заход пропускается, и
    счёт идёт дальше по следующему.

    ПОЛНОТА ЗАМЕРА НАЗЫВАЕТСЯ. Читается одна страница — сто заходов; если
    зелёного в ней нет вовсе, число это НЕ МЕНЬШЕ прочитанного, и выдавать его
    за точное значило бы врать в сторону, удобную механизму (045).
    """
    payload = (
        ghrest.request(
            "GET",
            f"repos/{repo}/actions/workflows/{PROOF_RUN}/runs"
            f"?branch={paths.TRUNK}&status=completed&per_page=100",
            token,
        )
        or {}
    )
    tries = 0
    for run in payload.get("workflow_runs") or []:
        end = str(run.get("conclusion") or "")
        if end == "success":
            return Proof(tries, True)
        if end in REAL_RED:
            tries += 1
    return Proof(tries, False)


def flaky_names(runs: list[dict[str, Any]]) -> dict[str, int]:
    """Имена, давшие на ОДНОЙ голове настоящее красное и затем зелёное.

    ЭТО И ЕСТЬ МИГАНИЕ, И ВИДНО ОНО БЕЗ ПЕРЕЗАПУСКА. Голова та же — значит
    дерево то же, и зелёное после красного получено не правкой. Прежний замер
    искал мигания среди перезапусков и не мог их найти: перезапускать было
    некому, и отсутствие перезапусков доказывало само себя
    ([044](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/044-check-the-premise-before-fixing.md)).
    Разбор — `docs/decisions/014-a-flake-must-be-visible-before-it-is-rerun.md`.

    Порядок читается по времени начала записи, а не по порядку ответа площадки:
    зелёное ДО красного — это обычная краснота, а не мигание.
    """
    fell: dict[str, tuple[str, int]] = {}
    rose: dict[str, str] = {}
    for run in runs:
        if run.get("status") != "completed":
            continue
        name = str(run.get("name") or "")
        started = str(run.get("started_at") or "")
        outcome = run.get("conclusion")
        if outcome in REAL_RED:
            if name not in fell or started < fell[name][0]:
                fell[name] = (started, run_id_of(run))
        elif outcome == "success":
            rose[name] = max(rose.get(name, started), started)
    # НОМЕР ПАДАВШЕГО ПРОГОНА — ЧАСТЬ НАХОДКИ, А НЕ УКРАШЕНИЕ. По нему запись
    # отличается от следующей такой же: одно имя мигает не единожды, и сводить
    # эти случаи в один значило бы потерять частоту — то самое, ради чего
    # мигания и записывают. Нашёл внешний взгляд на #222.
    return {
        name: where[1] for name, where in fell.items() if rose.get(name, "") > where[0] and where[1]
    }


#: Класс проверки, которой нет в ответе проекта. Слово, а не пустая строка: у
#: записи обязан быть виден каждый разряд, иначе форма схлопывается в чужую.
NO_CLASS: Final = "класс не объявлен"


@dataclass(frozen=True, slots=True)
class Unfixed:
    """Красное, ПЕРЕЖИВШЕЕ слияние: оно лежит на голове слитого изменения.

    Это не мигание и не краснота общей ветки, а третье: работа помечена
    закрытой, а часть её проверок на её же голове красна — и позеленеть им
    больше нечем. Голова слитого изменения не пересобирается, прогонов по ней
    никто не назначает.

    ЗАМЕР 16.09.2026, окно тридцати слитых: таких записей три — `task-items` на
    #366, #367 и #368, все совещательные, у всех объявлен адресат. Увидел их
    человек глазами; механизм, который их назвал бы, отсутствовал
    ([002](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/002-rule-without-mechanism.md)).
    """

    name: str
    where: str
    run: int
    klass: str = ""

    def said(self) -> str:
        """Строка записи: имя, изменение, класс и прогон.

        КЛАСС СТОИТ ВСЕГДА, И ЭТО НЕ УКРАШЕНИЕ. Пропущенный при пустом значении,
        он давал строку `- имя · #7 · прогон N` — синтаксически НЕОТЛИЧИМУЮ от
        записи мигания, и следующий заход читал долг слитого изменения как
        мигание с выдуманным днём («#7») и выдуманным местом («общая ветка»).
        Разделы живут в одном теле задачи, разбор у них общий — значит и формы
        обязаны не совпадать (045). Нашёл внешний взгляд находкой `b5dd9e7` на
        #379.

        Пустой класс называется словом: имя, которого нет в `.pipeline.yml`,
        бывает — и молчать об этом значит выбирать за читателя (154).
        """
        return f"- {self.name} · {self.where} · {self.klass or NO_CLASS} · прогон {self.run}"


def unfixed_names(runs: list[dict[str, Any]]) -> dict[str, int]:
    """Имена, чья ПОСЛЕДНЯЯ запись на этой голове — настоящее красное.

    ДОПОЛНЕНИЕ МИГАНИЯ, И ЧИТАЕТСЯ ТА ЖЕ ВЫБОРКА. Мигание — красное, за которым
    пришло зелёное; здесь — красное, за которым не пришло ничего. Два разбора
    одной выборки, а не два обхода площадки: второй обход того же источника
    стоил бы вызовов из общей квоты
    ([058](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/058-when-the-quota-is-out-stop.md)).

    Порядок читается по времени начала записи — тем же приёмом, что у мигания:
    иначе «последняя» зависела бы от порядка ответа площадки.

    Отменённая запись не считается ни красным, ни вердиктом: её разбирает
    сводный гейт, и здесь она прошла бы за отказ, которым не является.
    """
    last: dict[str, tuple[str, str, int]] = {}
    for run in runs:
        if run.get("status") != "completed" or run.get("conclusion") == "cancelled":
            continue
        name = str(run.get("name") or "")
        started = str(run.get("started_at") or "")
        if name not in last or started >= last[name][0]:
            last[name] = (started, str(run.get("conclusion") or ""), run_id_of(run))
    return {name: where[2] for name, where in last.items() if where[1] in REAL_RED and where[2]}


def red_of(runs: list[dict[str, Any]]) -> list[dict[str, Any]]:
    """Записи, которые на общей ветке означают красное.

    «Идёт» красным не считается: незавершённая проверка это не отказ, а
    отсутствие вердикта, и объявлять по ней заморозку значило бы морозить
    ветку на каждом прогоне. Отменённая — тоже: она пройденной не считается,
    но и отказом не является (её разбирает сводный гейт на изменении).
    """
    return [
        run
        for run in runs
        if not ci_complete.pending(run)
        and run.get("conclusion") not in (None, "success", "skipped", "cancelled")
    ]


def split(runs: list[dict[str, Any]], required: list[str]) -> tuple[list[str], list[str]]:
    """Делит красные имена на держащие слияние и не держащие."""
    names = sorted({str(run.get("name", "")) for run in runs})
    holds = [name for name in names if name in required]
    rest = [name for name in names if name not in required]
    return holds, rest


def run_id_of(run: dict[str, Any]) -> int:
    """Номер прогона, которому принадлежит запись проверки.

    Берётся из адреса записи: у площадки нет поля с номером прогона в ответе
    check-runs, а адрес его несёт. Разбор строгий — не разобралось, значит
    запись поставило не то приложение, и перезапускать нечего.
    """
    found = RUN_ID_RE.search(str(run.get("details_url") or ""))
    return int(found.group(1)) if found else 0


def attempt(repo: str, run: int, token: str) -> int:
    """Какая это попытка прогона: больше единицы — перезапуск уже был."""
    payload = ghrest.request("GET", f"repos/{repo}/actions/runs/{run}", token) or {}
    return int(payload.get("run_attempt") or 1)


def rerun_failed(repo: str, run: int, token: str) -> None:
    """Перезапускает ТОЛЬКО упавшие джобы прогона — минимум, а не всё."""
    ghrest.request("POST", f"repos/{repo}/actions/runs/{run}/rerun-failed-jobs", token, {})


#: Почему перезапуск не делается. Причина называется словами: «не будем»
#: без причины и «нечем» снаружи одинаковы (154).
NOT_ALONE: Final = "упал не один — это похоже на дефект, а не на мигание"
ALREADY: Final = "уже перезапускался — значит это дефект, а не мигание (124)"
NO_ADDRESS: Final = "адрес записи не разобрался — перезапускать нечем"
#: ОБЯЗАТЕЛЬНАЯ ВНЕ СПИСКА НЕ ПЕРЕЗАПУСКАЕТСЯ, И ЭТО ВОЗВРАТ К РЕШЕНИЮ 013.
#: Оно называет семь обязательных поимённо — `lint`, `test`, `pr-meta`,
#: `journal`, `attribution`, `pipeline`, `contract` — и говорит: они СЧИТАЮТ
#: ДЕРЕВО, их красное означает дефект, и зелёное со второго раза скрыло бы
#: находку (124).
#:
#: ЗАМЕР 21.09.2026, ИЗ-ЗА КОТОРОГО ПРИЧИНА И ПОЯВИЛАСЬ (#607): код
#: перезапускал ВСЕ СЕМЬ. Одиночное обязательное красное доходило до `one_fall`
#: и проходило его ВАКУУМНО — `all(...)` по пустому списку истинно, — то есть
#: `lint` перезапустился бы наравне с `ci-complete`. Комментарий над этим же
#: кодом обещал обратное: «обязательные не перезапускаются никогда».
#:
#: РЕШАЕТ ТЕПЕРЬ ИСТОРИЯ МИГАНИЯ, А НЕ КЛАСС. Имя попадает в разрешённый список
#: по записям детектора (решение 014), и `holds` спрашивает его наравне с
#: `rest`: прежде обязательное не спрашивалось вовсе.
#:
#: ЧЕРЕЗ ЭТУ ПРИЧИНУ `ci-complete` НЕ ПРОХОДИТ, И ЭТО НЕ ПРОТИВОРЕЧИЕ. `holds` и
#: `rest` разводит `split` по ОТВЕТУ ПРОЕКТА `.pipeline.yml`, а сводного гейта в
#: ответе нет намеренно — «его класс задан построением: он единственный
#: обязательный контекст защиты и сам себя не опрашивает». Значит на деле он
#: всегда в `rest`, и решает по нему ветка совещательных, спрашивающая тот же
#: разрешённый список. Обязательность у него перед ЗАЩИТОЙ ВЕТКИ, а не перед
#: этим разбором, и путать эти два смысла — ровно та ошибка, которую нашёл
#: внешний взгляд находкой `83a0071`: проза описывала путь, которым код не ходит.
#:
#: ПРЕДМЕТ У ПРИЧИНЫ ВСЁ РАВНО ЕСТЬ, И ОН ТОТ САМЫЙ: семь имён выше. Замер
#: 21.09.2026 на настоящих данных дерева — все семь идут в `holds`, и все семь
#: до этой правки перезапускались.
REQUIRED_UNLISTED: Final = (
    "упало обязательное, которого нет в разрешённом списке — его красное считает "
    "дерево и означает дефект (013, 124)"
)
#: Красных ОБЯЗАТЕЛЬНЫХ нет, а совещательные есть, и ни одна из них не в
#: разрешённом списке. Перезапуска не будет, и причина здесь своя: не «упал не
#: один», а «упало то, что ничего не держит и перезапуску не подлежит».
ADVISORY_ONLY: Final = (
    "красных обязательных нет, а упавшее совещательное не в разрешённом списке — "
    "уходит в долг, а не в перезапуск (084)"
)
#: Совещательных красных несколько. Перезапуск одного не вернул бы ветку в
#: зелень, а несколько сразу похожи на дефект, не на осечку канала (124).
ADVISORY_NOT_ALONE: Final = (
    "красных совещательных больше одной — это похоже на дефект, а не на осечку канала"
)


def rerunnable(where: Path | None = None) -> dict[str, str]:
    """Проверки, чьё одиночное красное перезапускается: имя → причина.

    СПИСОК РАЗРЕШИТЕЛЬНЫЙ И ЖИВЁТ В ДАННЫХ (068, 042). Имя попадает в него по
    одной причине — красное этой проверки НЕ означает дефекта дерева, — и причина
    объявляется рядом с именем. «Перезапускать всё красное» прятало бы дефект:
    зелёное со второго раза выглядит как работа
    ([124](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/124-rerun-the-minimum-and-record-the-flake.md)).

    Пустой список — законное состояние: до 15.09.2026 он был пуст, и это было
    ИЗМЕРЕНО, а не забыто (решения 013, 014, 025).
    """
    path = where or paths.RERUN
    try:
        said = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise NotRun(f"разрешённый список перезапуска не прочитан ({path}): {exc}") from exc
    found: dict[str, str] = {}
    for one in said.get("allowed") or []:
        name, why = str(one.get("check") or ""), str(one.get("why") or "")
        if not name or not why:
            raise NotRun(f"{path}: имя в списке без причины — перезапуск без объяснения (154)")
        found[name] = why
    return found


#: Чем запись проверки отделена от параметра матрицы. Площадка называет ячейку
#: `<имя джоба> (<значение>)`, и это ОДИН разделитель на весь модуль: пока он
#: стоял подстрокой в одном месте, второй читатель сравнивал имя записи целиком
#: — и матричная проверка не совпадала ни с чем (022).
CELL: Final = " ("


def job_of(name: str) -> str:
    """Имя ДЖОБА по имени записи: матричный параметр отрезается.

    ЭТО НЕ КОСМЕТИКА, А УСЛОВИЕ СОВПАДЕНИЯ. Ответ проекта и разрешительный
    список называют ДЖОБ (`test-next`), а площадка кладёт на голову запись
    ЯЧЕЙКИ (`test-next (3.15)`). Сравнение имени записи целиком не совпадало с
    ними никогда, и молча: имя просто не находилось в списке, и это выглядело
    как «перезапускать незачем».

    Замер 23.09.2026: из сорока объявленных проверок матричных ТРИ —
    `test-matrix`, `test-next`, `late-look`. Ни одна из них не могла попасть в
    разрешительный список работающей записью: гейт списка требует имени,
    объявленного в `.pipeline.yml`, то есть БЕЗ параметра, а сравнение шло с
    параметром. Форма, которой механизм не видит, и есть обход
    ([206](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/206-a-form-the-gate-cannot-see-is-a-bypass.md)).
    """
    return name.split(CELL)[0]


def listed(name: str, allowed: dict[str, str] | None) -> bool:
    """Разрешено ли перезапускать проверку с таким именем записи."""
    return job_of(name) in (allowed or {})


def one_fall(holds: list[str], rest: list[str], fed: dict[str, set[str]]) -> bool:
    """Одно ли это падение, отражённое несколькими именами.

    МАТРИЦА И ЕЁ АГРЕГАТ КРАСНЕЮТ ВМЕСТЕ ВСЕГДА. Агрегат ждёт матрицу через
    `needs` и краснеет ровно потому, что красна ячейка: два имени, одно
    падение. Пока это считалось двумя, перезапуск мигнувшей общей ветки не
    случался НИКОГДА — условие «упал ровно один» не выполнялось по построению.

    Замер 10.09.2026: `main` встала красной на `test` и `test-matrix (3.12)`,
    очередь заморозилась, и снять заморозку было нечем — новых слияний в
    замороженной очереди не бывает. Тупик разомкнулся руками.

    Связь читается из `needs` прогонов, то есть из данных, а не из прозы: имя
    матричной ячейки несёт версию (`test-matrix (3.12)`), поэтому сверяется
    начало имени до скобки.
    """
    if len(holds) != 1:
        return False
    feeding = fed.get(holds[0], set())
    return all(job_of(name) in feeding for name in rest)


def target_run(
    holds: list[str], rest: list[str], red: list[dict[str, Any]], fed: dict[str, set[str]]
) -> int:
    """Номер прогона, который перезапускают; ``0`` — перезапускать нечего.

    Решение о перезапуске и ВЫБОР ЕГО ПРЕДМЕТА — один вопрос, и спрашиваться он
    обязан одинаково. Пока выбор жил своим условием внутри захода, он
    расходился с решением: `one_fall` уже говорил «одно падение», а предмет
    по-прежнему не находился, и отказ приходил под другим именем.

    Перезапускается запись ОБЯЗАТЕЛЬНОГО имени: она и держит слияние. Соседние
    имена того же падения (матричные ячейки) поедут вместе с ней — их вердикт
    в неё и доезжает.

    СОВЕЩАТЕЛЬНОЕ ОДИНОЧНОЕ — ТОТ ЖЕ ВОПРОС, И ОТВЕТ ТОТ ЖЕ. Когда обязательных
    красных нет вовсе, предметом становится единственное красное совещательное:
    решение о его перезапуске принимает `rerun_reason` по разрешённому списку, а
    выбор предмета обязан спрашиваться здесь же — иначе он снова разойдётся с
    решением (это уже стоило отказа под чужим именем).
    """
    if not holds:
        if len(rest) != 1:
            return 0
        for item in red:
            if str(item.get("name")) == rest[0]:
                return run_id_of(item)
        return 0
    if not one_fall(holds, rest, fed):
        return 0
    for item in red:
        if str(item.get("name")) == holds[0]:
            return run_id_of(item)
    return 0


def rerun_reason(
    holds: list[str],
    rest: list[str],
    run: int,
    tries: int,
    feeds: dict[str, set[str]] | None = None,
    allowed: dict[str, str] | None = None,
) -> str:
    """Почему перезапуска НЕ будет; пустая строка — будет.

    Решение вынесено из захода отдельно, потому что оно и есть предмет правила
    124, а проверять его внутри `main()` пришлось бы подделкой всей площадки —
    то есть не проверять вовсе
    ([140](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/140-a-gate-is-tested-by-what-it-must-reject.md)).

    Причины разведены поимённо. «Попытка уже была» и «адрес записи не
    разобрался» дают одинаковое бездействие, а значат разное: первое —
    состояние работы (дефект, идём чинить), второе — поломка чтения (площадка
    ответила не тем). Одно сообщение на оба отправило бы разбирать дефект,
    которого нет.
    """
    # ОДИНОЧНОЕ ПЕРЕЗАПУСКАЕТСЯ, ЕСЛИ ИМЯ В РАЗРЕШЁННОМ СПИСКЕ — И КЛАСС ЗДЕСЬ
    # НИ ПРИ ЧЁМ. Список наполняется по записям детектора: имя попадает в него,
    # когда его красное ИЗМЕРЕННО не означало дефекта дерева (решения 013, 014,
    # 025). Замеры: `badges` 15.09.2026, `debt` 16.09.2026, `ci-complete`
    # 21.09.2026 — прогон 35519799055, попытка 2 зелена.
    #
    # ОБЕ ВЕТКИ СПРАШИВАЮТ ОДИН И ТОТ ЖЕ СПИСОК, и разница между ними только в
    # том, ЧТО ЗНАЧИТ ОТСУТСТВИЕ ИМЕНИ: у совещательного — «перезапускать
    # незачем», у обязательного — «это дефект дерева». Поэтому сообщения разные,
    # а данные одни.
    #
    # ЗДЕСЬ СТОЯЛО «обязательные не перезапускаются никогда», и код этого НЕ
    # делал: одиночное обязательное проходило `one_fall` вакуумно и
    # перезапускалось — все семь, включая `lint` (#607).
    if not holds:
        if len(rest) != 1:
            return ADVISORY_NOT_ALONE if rest else ADVISORY_ONLY
        if not listed(rest[0], allowed):
            return ADVISORY_ONLY
        if not run:
            return NO_ADDRESS
        return ALREADY if tries > 1 else ""
    if not one_fall(holds, rest, feeds or {}):
        return NOT_ALONE
    # ОДНО ИМЯ — СПРАШИВАЕМ СПИСОК; НЕСКОЛЬКО — ЭТО ОДНО ПАДЕНИЕ ПОД РАЗНЫМИ
    # ИМЕНАМИ. `one_fall` заведён ради второго случая: агрегат краснеет ровно
    # потому, что красна его матричная ячейка, и перезапускать их порознь
    # нечего. А обязательное БЕЗ соседей — это само по себе красное, и решает
    # по нему история мигания, а не класс (#607).
    if not rest and not listed(holds[0], allowed):
        return REQUIRED_UNLISTED
    if not run:
        return NO_ADDRESS
    return ALREADY if tries > 1 else ""


def parse_flakes(body: str | None) -> list[Flake]:
    """Мигания, уже записанные в задаче.

    ПОВТОР ОТСЕИВАЕТСЯ НА ЧТЕНИИ, И ЭТИМ РЕЕСТР ЗАЖИВАЕТ САМ. Запись добавляют
    по прогону (`flakes_after`), но тело пересобирается ИЗ ПРОЧИТАННОГО: повтор,
    попавший в него однажды, переписывался бы обратно каждым заходом и не
    уходил бы никогда — список без входа не растёт, но и не чинится.

    ЗАМЕР 16.09.2026: в реестре #99 лежал ровно один такой повтор —
    `ci-complete · прогон 34721547141 · #266` дважды. Родился он 14.09, когда
    разбор строки был сломан и `known` приходил неверным: сам дефект починен,
    а след его остался — и снять его было некому
    ([049](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/049-derive-state-from-live-artifacts.md)).

    ПЕРВАЯ ЗАПИСЬ ВЫЖИВАЕТ, А НЕ ПОСЛЕДНЯЯ: у мигания есть день, и день первого
    наблюдения — это то, что записали, а не то, что переписали.
    """
    found: list[Flake] = []
    seen: set[tuple[str, int]] = set()
    for one in FLAKE_RE.finditer(body or ""):
        flake = Flake(one["name"].strip(), one["day"], int(one["run"]), one["where"] or SHARED)
        if flake.same in seen:
            continue
        seen.add(flake.same)
        found.append(flake)
    return found


def flakes_after(
    known: list[Flake], name: str, run: int, day: str, where: str = SHARED
) -> list[Flake]:
    """Добавляет мигание, если этого прогона в списке ещё нет.

    ТОЖДЕСТВО СПРАШИВАЕТСЯ У САМОГО МИГАНИЯ (`Flake.same`), а не собирается
    здесь: второй ключ того же понятия разошёлся бы с первым молча, и это уже
    случилось (022, 090).

    По прогону, а не по имени: одна и та же проверка мигает не единожды, и
    сводить эти случаи в один значило бы потерять частоту — то самое, ради чего
    мигания и записывают.
    """
    fresh = Flake(name, day, run, where)
    if fresh.same in {item.same for item in known}:
        return known
    return [*known, fresh]


def live_changes(repo: str, token: str) -> list[automerge.Change] | None:
    """Живые изменения площадки: ОДНО чтение на заход.

    Тот же список нужен трём предметам захода — миганиям на головах изменений,
    счёту очереди и метке заморозки, — и каждый прежде спрашивал его сам. Три
    обхода одного источника стоят вызовов из ОБЩЕЙ квоты
    ([058](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/058-when-the-quota-is-out-stop.md))
    и расходятся между собой молча: пока читал первый, второй мог увидеть уже
    другое (022, 090).

    Читается КАНОНИЧЕСКИМ читателем очереди, а не сырым обходом: разбор метки и
    черновика живёт там, и второй его экземпляр разошёлся бы с первым. Нашёл
    внешний взгляд находкой `b0396e9` на #364 — тем же классом, каким находил
    счёт очереди на #168.

    ``None`` — площадка не ответила, и это НЕ «живых изменений нет»: потребитель
    обязан отличать одно от другого
    ([045](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/045-no-silent-fallback.md),
    049).
    """
    try:
        return automerge.open_changes(repo, token)
    except ghrest.TransportError as exc:
        # Отказ здесь не роняет заход: краснота общей ветки — главный предмет
        # шага, и терять её из-за соседнего чтения нельзя (084).
        print(f"живые изменения не прочитаны: {report.cut(str(exc))}")
        return None


@dataclass(frozen=True, slots=True)
class Seen:
    """Что увидел один обход голов изменений: два предмета, одна выборка.

    Мигания КОПЯТСЯ (событие, из артефактов исчезает), стойко красное —
    ЗЕРКАЛО окна слитых (запись на голове остаётся лежать). Разные контракты, и
    поэтому они названы врозь, а не сложены в один список (016).
    """

    flakes: list[Flake]
    unfixed: list[Unfixed]

    #: СПИСКИ МОГУТ НАЗВАТЬ ОДНО ИМЯ, И ЭТО НЕ ДЕФЕКТ. Голова, прошедшая
    #: красное → зелёное → красное, несёт ДВА разных факта: мигание на первом
    #: прогоне (дерево не при чём — зелёное получено без правки) и долг на
    #: последнем (проверка так и осталась красной). Спрятать один ради
    #: непересечения значило бы потерять наблюдение — ровно то, что запрещает
    #: [016](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/016-no-silent-truncation.md).
    #:
    #: Прежняя запись проекта утверждала обратное — «списки делят выборку без
    #: пересечения», — и утверждение было неверным: нашёл внешний взгляд
    #: находкой `359a558` на #379. Настоящая граница другая и держится тестом:
    #: РАЗНЫЕ ПРОГОНЫ. Мигание называет прогон, на котором упало и поднялось;
    #: долг — прогон последней записи.


def seen_on_changes(
    repo: str,
    token: str,
    known: list[Flake],
    day: str,
    live: list[automerge.Change] | None,
    answer: dict[str, policy.Check] | None = None,
    *,
    required: list[str] | None = None,
    fed: dict[str, set[str]] | None = None,
    apply: bool = False,
) -> Seen:
    """Один обход голов изменений — и мигания, и красное, пережившее слияние.

    ДВА ПРЕДМЕТА, ОДНА ВЫБОРКА. Записи проверок головы читаются РАЗ, и разбор
    их идёт дважды: `flaky_names` ищет зелёное после красного, `unfixed_names` —
    красное, за которым не пришло ничего. Второй обход того же источника стоил
    бы вызовов из общей квоты и расходился бы с первым молча (058, 022) — это
    уже стоило находки `b0396e9`.

    ПОЧЕМУ ЗДЕСЬ, А НЕ ОТДЕЛЬНЫМ МЕХАНИЗМОМ. Реестр мигания один — #99, — и он
    уже ведётся этим шагом. Второй механизм, пишущий в тот же список, разошёлся
    бы с первым молча
    ([022](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/022-one-canonical-document.md)),
    а второй список того же — ровно то, ради чего реестр и заведён один.

    ПЕРЕЗАПУСК ЗДЕСЬ ПОЯВИЛСЯ 21.09.2026, И ЭТО СНЯТИЕ ОБЪЯВЛЕННОЙ ОТСРОЧКИ.
    Здесь стояло: «перезапуска нет намеренно... разрешённый список остаётся
    пустым, пока эти записи не назовут первое имя» — то есть у отсрочки было
    названо УСЛОВИЕ пересмотра, а не срок
    ([126](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/126-a-freeze-needs-a-thaw-path.md)).

    Условие наступило и проверено числом: в реестре #99 двадцать девять
    миганий, `ci-complete` среди них семнадцать, и двадцать из двадцати девяти
    — на голове ИЗМЕНЕНИЯ. Решение принимает `rerun_on_change` тем же
    `rerun_reason`, что и общая ветка.
    """
    found = list(known)
    unfixed: list[Unfixed] = []
    # ОТВЕТ ПРОЕКТА И СВЯЗИ ПРОГОНОВ ПРИХОДЯТ СВЕРХУ, А НЕ ЧИТАЮТСЯ ЗДЕСЬ: их
    # уже прочитал заход, и второе чтение того же разошлось бы с первым молча
    # (022, 058).
    required = required if required is not None else []
    fed = fed if fed is not None else {}
    # ЖИВЫЕ ПРИХОДЯТ СПИСКОМ, А НЕ ЧИТАЮТСЯ ЗДЕСЬ: их читает `live_changes`, один
    # раз на заход (058, 022). Слитые читаются здесь — они свой источник, и
    # список открытых их не содержит.
    heads: list[tuple[int, str]] = [(one.number, one.head) for one in live or []]
    #: Головы СЛИТЫХ изменений: только на них красное «пережило слияние». У
    #: живого изменения красное ещё держит очередь или ждёт починки — это не
    #: долг по сделанному, и путать их значило бы звать чинить то, что в работе.
    merged: set[int] = set()
    try:
        # СЛИТЫЕ ОБХОДЯТСЯ НАРАВНЕ С ОТКРЫТЫМИ, И БЕЗ ЭТОГО СПИСОК БЫЛ ПУСТ ПО
        # ПОСТРОЕНИЮ. Мигание — свойство ГОЛОВЫ, и слияние его не отменяет:
        # записи проверок остаются лежать там же. А изменение, слившееся за
        # минуты, из списка открытых исчезает раньше, чем шаг успевает
        # заглянуть, — то есть чем БЫСТРЕЕ работает очередь, тем меньше
        # миганий видит детектор.
        #
        # Замер 13.09.2026: реестр #99 говорил «повторных зелёных не было», а
        # на головах слитых #259 и #262 лежало по настоящему миганию
        # `ci-complete` — красное и затем зелёное без правки дерева. Молчание
        # реестра было не наблюдением, а следствием того, куда он смотрит
        # ([044](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/044-check-the-premise-before-fixing.md)).
        #
        # Цена молчания здесь не «одна потерянная запись»: пока записей нет,
        # не наступает и условие пересмотра решения `014`, то есть разрешённый
        # список автоперезапуска остаётся пустым НАВСЕГДА.
        after = [
            (int(one.get("number") or 0), str((one.get("head") or {}).get("sha") or ""))
            for one in ghrest.merged_changes(repo, token)
        ]
        heads += after
        merged = {number for number, _ in after}
    except ghrest.TransportError as exc:
        # Отказ здесь не роняет ни заход, ни разбор ЖИВЫХ голов: краснота общей
        # ветки — главный предмет шага, а слитые и живые — разные источники, и
        # отказ одного не отменяет второго (084).
        print(f"мигания слитых изменений не сосчитаны: {report.cut(str(exc))}")
    for number, head in heads:
        if not head or not number:
            continue
        try:
            # СПИСОК ИДЁТ СТРАНИЦАМИ, как и у общей ветки. Умолчание площадки
            # обрезает хвост молча, а хвост — это и есть вторая запись имени,
            # без которой мигание неотличимо от обычной красноты (#222).
            runs = list(
                ghrest.paginate(f"repos/{repo}/commits/{head}/check-runs", token, key="check_runs")
            )
        except ghrest.TransportError as exc:
            print(f"  #{number}: записи проверок не прочитаны: {report.cut(str(exc))}")
            continue
        for name, run in flaky_names(runs).items():
            before = len(found)
            found = flakes_after(found, name, run, day, where=f"#{number}")
            if len(found) > before:
                print(f"  #{number}: мигание «{name}» на прогоне {run} — зелёное после красного")
        if number not in merged:
            # ПЕРЕЗАПУСКАЕТСЯ ТОЛЬКО ЖИВОЕ. На голове слитого перезапускать
            # нечего: слияние уже состоялось, и зелёное со второго раза там
            # ничего не решает — оно только тратит квоту (058).
            told = rerun_on_change(repo, token, number, runs, required, fed, apply=apply)
            if told:
                print(f"  {told}")
            continue
        for name, run in sorted(unfixed_names(runs).items()):
            said = answer.get(name) if answer else None
            unfixed.append(
                Unfixed(name=name, where=f"#{number}", run=run, klass=said.klass if said else "")
            )
            print(f"  #{number}: «{name}» осталась красной после слияния — прогон {run}")
    return Seen(flakes=found, unfixed=unfixed)


def rerun_on_change(
    repo: str,
    token: str,
    number: int,
    runs: list[dict[str, Any]],
    required: list[str],
    fed: dict[str, set[str]],
    *,
    apply: bool,
) -> str:
    """Перезапускает одиночное красное на голове ИЗМЕНЕНИЯ; отдаёт, что вышло.

    РЕШЕНИЕ ЗДЕСЬ НЕ СВОЁ, А ТО ЖЕ. Условия берутся у `rerun_reason` и
    `target_run` — тех же, по которым живёт общая ветка. Вторая копия «когда
    перезапускать» разошлась бы с первой молча, и разошлась бы в сторону, где
    механизм прячет дефект
    ([022](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/022-one-canonical-document.md),
    [090](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/090-shared-helpers-move-up-not-sideways.md)).

    ПОЧЕМУ ЭТО ПОЯВИЛОСЬ ТОЛЬКО СЕЙЧАС, И ЭТО НЕ НЕДОСМОТР. Соседняя докстрока
    `seen_on_changes` объявляла отсрочку с УСЛОВИЕМ ПЕРЕСМОТРА: «записать можно
    то, чего ещё не перезапускали; обратное — нет. Разрешённый список остаётся
    пустым, пока эти записи не назовут первое имя»
    ([126](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/126-a-freeze-needs-a-thaw-path.md)).

    ЗАМЕР 21.09.2026, ПО КОТОРОМУ УСЛОВИЕ НАСТУПИЛО (#584): в реестре #99
    двадцать девять миганий, и `ci-complete` среди них **семнадцать** — больше,
    чем все остальные двенадцать имён вместе. Где: **двадцать из двадцати
    девяти — на голове ИЗМЕНЕНИЯ**, девять — на общей ветке. То есть
    большинство случалось там, где перезапуска не было вовсе, и каждое гасил
    человек рукой либо оно гасло следующим толчком.

    ЗАПИСЬ ИНЦИДЕНТА ОТДЕЛЬНО НЕ ВЕДЁТСЯ, И ЭТО НЕ ПРОБЕЛ. Удавшийся перезапуск
    даёт «зелёное после красного» — ровно то, что ловит `flaky_names` на
    следующем заходе, и запись ляжет в тот же реестр #99 с пометкой места.
    Второй список того же разошёлся бы с первым молча (022). Не удался —
    записи не будет, и окно разбудит оклик (`scripts/hail.py`): это настоящий
    дефект, а не осечка.
    """
    # ЗАПИСИ ОТБИРАЮТСЯ ПО ХУДШЕЙ НА ИМЯ, КАК НА ОБЩЕЙ ВЕТКЕ (#602). Без этого
    # устаревшая `failure` рядом со свежей `success` на той же голове читалась
    # как краснота: перезапускался бы зелёный, а мигание записывалось бы на
    # пустом месте. Отбор общий со сводным гейтом — второе понимание «какая из
    # двух главная» разошлось бы с первым молча
    # ([090](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/090-shared-helpers-move-up-not-sideways.md)).
    # Нашёл внешний взгляд находкой `3dd9203`.
    red = red_of(ci_complete.worst_per_name(runs))
    if not red:
        return ""
    holds, rest = split(red, required)
    target = target_run(holds, rest, red, fed)

    # ПЛОЩАДКУ СПРАШИВАЕМ ПОСЛЕДНЕЙ, А НЕ ПЕРВОЙ. Номер попытки — единственное,
    # что нельзя вывести из уже прочитанного, и стоит он вызова из ОБЩЕЙ квоты
    # ([058](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/058-when-the-quota-is-out-stop.md)).
    # На общей ветке голова одна и цена незаметна; здесь голов столько, сколько
    # живых изменений, и спрашивать у каждой значило бы платить за ответ,
    # который в большинстве случаев ничего не меняет. Поэтому сначала
    # проверяются условия, выводимые ИЗ ПРОЧИТАННОГО, и только если они прошли
    # — спрашивается попытка.
    said = rerun_reason(holds, rest, target, 1, fed, rerunnable())
    if said:
        return f"#{number}: перезапуска не будет: {said}"
    tries = attempt(repo, target, token) if target else 1
    why = rerun_reason(holds, rest, target, tries, fed, rerunnable())
    if why:
        return f"#{number}: перезапуска не будет: {why}"
    if apply:
        rerun_failed(repo, target, token)
    did = "перезапущен" if apply else "перезапустил бы"
    return f"#{number}: упал ровно один — «{(holds or rest)[0]}»: {did} прогон {target} (124)"


#: Метка заморозки. Имя читает очередь (`scripts/automerge.py`), объявлено оно в
#: составе меток дерева, а ставит и снимает его ЭТОТ шаг: у метки один владелец —
#: механизм, и этим она отличается от `hold`, которую ставит человек (022).
LABEL_PAUSED: Final = automerge.LABEL_PAUSED
#: Метка починки: её несущее изменение заморозка не останавливает — оно и есть
#: выход из неё.
LABEL_FIX_MAIN: Final = automerge.LABEL_FIX_MAIN


def stamp(repo: str, number: int, token: str, *, on: bool) -> None:
    """Ставит или снимает метку заморозки на одном изменении."""
    if on:
        ghrest.request(
            "POST", f"repos/{repo}/issues/{number}/labels", token, {"labels": [LABEL_PAUSED]}
        )
        return
    # Имя метки несёт косую черту, и в адресе она обязана быть закодирована:
    # иначе площадка ищет метку «main-red» внутри пути «paused» и отвечает
    # «не найдено» — снятие выглядело бы сделанным (045).
    ghrest.request(
        "DELETE", f"repos/{repo}/issues/{number}/labels/{ghrest.quote(LABEL_PAUSED)}", token
    )


def pause(
    repo: str,
    token: str,
    live: list[automerge.Change] | None,
    *,
    frozen: bool,
    apply: bool,
) -> tuple[list[int], list[int]]:
    """Отмечает заморозку на живых изменениях: ставит на все, кроме починки.

    ПОЧЕМУ МЕТКА, А НЕ ТОЛЬКО СНЯТИЕ ВЗВЕДЕНИЯ. Очередь и так снимает согласие
    при красной общей ветке, но снятие живёт в выводе её захода: человек на
    списке изменений видит зелёные проверки и не видит причины, почему ничего не
    сливается. Метка — состояние НА изменении, и она не отменяется следующим
    решением очереди
    ([142](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/142-a-scheduled-red-needs-an-addressee.md)).

    ПОЧИНКА НЕ ОСТАНАВЛИВАЕТСЯ: изменение с меткой `fix-main` — единственный
    выход из заморозки, и остановить его значило бы запереть выход
    ([126](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/126-a-freeze-needs-a-thaw-path.md)).

    СНЯТИЕ — ТОГО ЖЕ ШАГА, а не человека: у метки один владелец. Позеленела
    общая ветка — метка уходит сама, и «забытая метка» означает не забывчивость
    человека, а незашедший механизм; об этом говорит счёт пропущенных заходов по
    расписанию, а не вторая метка.

    Возвращает два списка: помеченные и освобождённые.
    """
    # СПИСОК ПРИХОДИТ, А НЕ ЧИТАЕТСЯ ЗДЕСЬ. Прежде шаг обходил `pulls?state=open`
    # сам — третьим обходом одного источника за заход, — и это стоило вызовов из
    # общей квоты (058). Нашёл внешний взгляд находкой `b0396e9` на #364.
    #
    # НЕ ПРОЧИТАНО — НЕ «НЕТ ЖИВЫХ». Пустой список означал бы «размечать нечего»,
    # и заморозка молча не отметилась бы ни на ком (045).
    if live is None:
        print("метки заморозки не расставлены: живые изменения не прочитаны")
        return [], []

    marked: list[int] = []
    freed: list[int] = []
    for change in live:
        number = change.number
        if not number:
            continue
        paused_now = LABEL_PAUSED in change.marks
        want = frozen and LABEL_FIX_MAIN not in change.marks
        if want == paused_now:
            continue
        try:
            if apply:
                stamp(repo, number, token, on=want)
        except ghrest.TransportError as exc:
            print(f"#{number}: метка заморозки не {'поставлена' if want else 'снята'}: {exc}")
            continue
        (marked if want else freed).append(number)
    if marked:
        print(f"заморозка отмечена{'' if apply else ' была бы'} на: {marked}")
    if freed:
        print(f"метка заморозки снята{'' if apply else ' была бы'} с: {freed}")
    return marked, freed


@dataclass(frozen=True, slots=True)
class Queue:
    """Очередь на момент захода: числа И ПРОЧИТАНЫ ЛИ ОНИ.

    Признак прочитанности стоит рядом с числом по той же причине, что `whole` у
    счётчика попыток: ноль, взятый из отказа чтения, и ноль, взятый у пустой
    очереди, — РАЗНЫЕ утверждения, а выглядят одинаково. Пока их сводили в одну
    пару чисел, текст в теле задачи говорил «очередь пуста, двигать нечего» там,
    где площадка просто не ответила
    ([045](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/045-no-silent-fallback.md)).
    Нашёл внешний взгляд находкой `4925118` на #370.
    """

    waiting: int
    fixing: int
    read: bool = True


def queue_now(live: list[automerge.Change] | None) -> Queue:
    """Сколько изменений ждёт очереди и сколько из них помечены починкой.

    ЧИТАЕТСЯ У ПЛОЩАДКИ, А НЕ СЧИТАЕТСЯ ЗАНОВО. Предмет — живые изменения и их
    метки; вести это вторым списком значило бы разойтись с площадкой на первом
    же закрытом изменении (049).

    СПИСОК БЕРЁТСЯ У ОЧЕРЕДИ, А НЕ СОБИРАЕТСЯ ЗДЕСЬ ВТОРОЙ РАЗ. Прежде шаг
    запрашивал открытые изменения сам, одной страницей на пятьдесят: при
    большем числе счёт «в очереди» занижался молча, и хуже того — занижался
    счёт помеченных `fix-main`, то есть механизм мог сказать «разблокировать
    некому», когда разблокирующее изменение уже стояло. Тот же список читает
    `automerge.open_changes`, страницами и с теми же метками; второе прочтение
    одного источника расходится с первым молча (022, 090). Нашёл внешний
    взгляд на #168 — трижды, и все три раза об одном.
    """
    # НЕ ПРОЧИТАНО — ПЕРВЫМ ВОПРОСОМ, А НЕ ПОСЛЕ РАБОТЫ. Проверка стояла ниже
    # сборки списка, и та шла по `live or []`: работа делалась впустую, а
    # читателю причина раннего возврата была не видна. Нашёл внешний взгляд
    # находкой `79585a4` на #374.
    if live is None:
        return Queue(0, 0, read=False)
    queued = [
        change for change in live if automerge.LABEL_AUTOMERGE in change.marks and not change.draft
    ]
    fixing = sum(1 for change in queued if automerge.LABEL_FIX_MAIN in change.marks)
    return Queue(len(queued), fixing)


def said_queue(queue: Queue) -> list[str]:
    """Что заморозка значит для очереди ПРЯМО СЕЙЧАС — словами и числом.

    ЗАЧЕМ. Заморозка объявлена, метка названа — и всё равно дважды за смену
    починка стояла в очереди без метки, потому что «это чинит общую ветку»
    решает человек, а не механизм. Очередь при этом молчала: она пишет «нет
    изменения с меткой» в лог своего прогона, куда никто не смотрит. Адресат у
    такого сообщения есть — эта самая задача (142).

    ЭТОТ шаг метку не ставит, и это по-прежнему верно: из дерева не следует,
    чинит ли изменение красноту, и решать это за человека значило бы пропускать
    в замороженную очередь что попало (154). Сказать, что очередь стоит и никто
    её не разблокирует, он обязан.

    ЗДЕСЬ СТОЯЛО «Механизм НЕ ставит метку сам», и с 21.09.2026 это неверно как
    утверждение о проекте: `fix-main` ставит ещё и шаг открытия — но лишь когда
    изменение ОБЪЯВИЛО предмет трейлером «Чинит main: <имя шага>» И этот шаг
    действительно красен на голове общей ветки (#585). Решает по-прежнему
    проверяемый признак, а не мнение; здешняя запись про «никто не
    разблокирует» от этого не меняется. Нашёл внешний взгляд находкой
    `b810481`.
    """
    # НЕ ПРОЧИТАНО — СВОЙ СЛУЧАЙ, И ОН ПЕРВЫЙ. Иначе ноль отказа доезжает до
    # ветки «пуста», и запись утверждает про очередь то, чего никто не смотрел.
    if not queue.read:
        return [
            "**Очередь не прочитана: площадка не ответила.** Сколько изменений ждёт и",
            "есть ли среди них починка — неизвестно, и это НЕ «пусто» (045).",
            "",
        ]
    if queue.fixing:
        return [
            f"В очереди {queue.waiting}, из них с меткой `fix-main`: "
            f"**{queue.fixing}** — они и пойдут.",
            "",
        ]
    if queue.waiting:
        return [
            f"**В очереди {queue.waiting}, и ни одно не помечено `fix-main`.** Очередь не",
            "двинется, пока метку не поставят: механизм её не ставит сам — из дерева",
            "не следует, чинит ли изменение красноту (154).",
            "",
        ]
    return ["Очередь пуста: чинить некому и нечего двигать.", ""]


def said_tries(proof: Proof) -> list[str]:
    """Счётчик попыток словами — и смена адресата, когда предел исчерпан.

    ДНО У ЦИКЛА НАЗЫВАЕТСЯ ЗАРАНЕЕ, А НЕ ПОСЛЕ. Пока предела нет, «чиним, пока
    не позеленеет» звучит как план и при причине вне кода не сходится никогда
    (109). Механизм при этом никого не останавливает и останавливать не вправе:
    он называет число и того, кому дальше решать, — решает человек (154).

    АДРЕСАТ МЕНЯЕТСЯ ТЕМИ ЖЕ СЛОВАМИ, ЧТО У ОКЛИКА. Два понимания «дальше
    владелец» разошлись бы молча, а читатель у обеих записей один (090).
    """
    said = [f"Заходов подряд, не доказавших зелень: **{proof.said()}** из {TRIES_LIMIT}.", ""]
    if not proof.whole:
        said = [
            f"Заходов подряд, не доказавших зелень: **{proof.said()}** из {TRIES_LIMIT} —"
            " зелёного захода в прочитанном окне нет вовсе, поэтому число это не",
            "меньшее, а не точное (045).",
            "",
        ]
    if not proof.spent:
        return said
    return [
        *said,
        "**Адресат — владелец.** Причина смены адресата: предел попыток доказать",
        f"зелень исчерпан ({proof.said()} из {TRIES_LIMIT}). Следующий шаг не починка:",
        "столько заходов подряд без зелени значит, что причина может быть вне кода",
        "вовсе — отказала площадка, кончились исполнители, — и выбор между",
        "«чиним дальше» и «ждём» делает человек, а не механизм (109, 100).",
        "",
    ]


def render_body(
    holds: list[str],
    rest: list[str],
    flakes: list[Flake],
    sha: str,
    queue: Queue | None = None,
    tries: Proof | None = None,
    unfixed: list[Unfixed] | None = None,
) -> str:
    """Собирает тело задачи: три зеркала и один журнал."""
    lines = [
        MARKER,
        "",
        "> **Читатель:** окно, берущее работу, и владелец. Здесь то, что красно",
        "> на общей ветке прямо сейчас, что осталось красным на слитом, и то,",
        "> что мигало.",
        "",
        "Разделы ниже, кроме последнего, — **зеркало живых артефактов**: они",
        "пересобираются каждым заходом. Позеленело — запись уходит сама, упало",
        "снова — возвращается. Снимать их рукой не нужно и не следует. Мигания",
        "копятся отдельно и по своей причине: из артефактов они исчезают.",
        "",
        f"Голова общей ветки: `{sha[:7] or '—'}`.",
        "",
        "## Держит слияние — источник 0",
        "",
    ]
    if holds:
        lines += [
            "Очередь заморожена: слить не может никто, кроме починки. Это первый",
            "источник работы контура 1 — стоит работа всей семьи.",
            "",
            *[f"- **{name}**" for name in holds],
            "",
            "Починка подаётся изменением с меткой `fix-main`: очередь пропускает",
            "только его, а состав проверок метка НЕ трогает — обойти их ею",
            "нельзя по построению.",
            "",
            *(said_queue(queue) if queue else []),
            *(said_tries(tries) if tries else []),
        ]
    else:
        lines += ["Пусто — обязательные проверки на голове зелены.", ""]

    lines += ["## Не держит слияние, но не потеряно — источник 3", ""]
    if rest:
        lines += [
            "Совещательная проверка слияния не держит, и очередь идёт. Но работа,",
            "помеченная закрытой, частью не работает — это долг по УЖЕ сделанному,",
            "и он идёт перед правилами и планом.",
            "",
            *[f"- **{name}**" for name in rest],
            "",
            "Починка такого бывает крупной — вплоть до переезда на другую версию",
            "языка. Тогда из записи заводится задача, и запись уходит вместе с",
            "починкой, а не с забвением.",
            "",
        ]
    else:
        lines += ["Пусто — совещательные проверки на голове зелены.", ""]

    lines += ["## Красное, пережившее слияние — источник 3", ""]
    lines += [
        "Работа помечена закрытой, а часть её проверок на её же голове **красна**,",
        "и позеленеть им больше нечем: голова слитого изменения не пересобирается,",
        "прогонов по ней никто не назначает. Это долг по УЖЕ сделанному.",
        "",
        "Раздел — **зеркало окна последних слитых изменений**, а не накопитель:",
        "запись читается из живых артефактов каждым заходом (049). Ушедшее из окна",
        "из раздела исчезает — если запись нужна дольше, из неё заводят задачу, и",
        "тогда она живёт там, а не здесь.",
        "",
    ]
    if unfixed:
        lines += [item.said() for item in unfixed]
        lines.append("")
    else:
        lines += ["Пусто — на головах слитых изменений красного не осталось.", ""]

    lines += [
        "## Мигания",
        "",
        "Зелёное со второго раза — **находка, а не починка** (124). В артефактах",
        "после позеленения этого не остаётся, поэтому список копится и его",
        "снимает человек: механизм не знает, разобрано мигание или надоело.",
        "",
    ]
    if flakes:
        lines += [item.said() for item in flakes]
    else:
        lines.append("Пусто — повторных зелёных не было.")
    # ДЕНЬ ОБХОДА СТОИТ ДАЖЕ КОГДА ПУСТО, И ОСОБЕННО КОГДА ПУСТО: «пусто» без
    # даты неотличимо от «не смотрели», и обе записи выглядят одинаково спокойно
    # ([027](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/027-empty-state-is-a-state.md)).
    lines += ["", f"Обход: {datetime.now(UTC).strftime('%Y-%m-%d %H:%M')} UTC."]
    return "\n".join(lines) + "\n"


def save(repo: str, token: str, body: str, apply: bool) -> None:
    """Записывает задачу: обновляет по месту или заводит одну."""
    number, _ = findings.live_issue(repo, token, MARKER)
    if not apply:
        print("записал бы в " + (f"#{number}" if number else "новую задачу"))
        return
    if number is None:
        created = ghrest.request(
            "POST", f"repos/{repo}/issues", token, {"title": TITLE, "body": body}
        )
        print(f"задача заведена: #{(created or {}).get('number')}")
        return
    ghrest.request("PATCH", f"repos/{repo}/issues/{number}", token, {"body": body})
    print(f"задача обновлена: #{number}")


def main(argv: list[str] | None = None) -> int:
    """Точка входа: считает красноту головы, перезапускает минимум и пишет."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo", default=os.environ.get("GITHUB_REPOSITORY", ""))
    parser.add_argument("--sha", default="", help="голова общей ветки; по умолчанию — её вершина")
    parser.add_argument("--branch", default=paths.TRUNK, help="общая ветка")
    parser.add_argument("--apply", action="store_true", help="записать и перезапустить")
    args = parser.parse_args(argv)
    report.announce(not args.apply)

    holds: list[str] = []
    rest: list[str] = []
    try:
        token = ghrest.token_from_env()
        if not token:
            raise NotRun("нет токена: GH_TOKEN или GITHUB_TOKEN")
        if not args.repo:
            raise NotRun("репозиторий не назван: --repo или GITHUB_REPOSITORY")

        sha = args.sha or str(
            (ghrest.request("GET", f"repos/{args.repo}/commits/{args.branch}", token) or {}).get(
                "sha", ""
            )
        )
        if not sha:
            raise NotRun(f"голова ветки «{args.branch}» не прочитана — считать нечего")

        runs = ci_complete.worst_per_name(
            ci_complete.on_the_shared_branch(
                list(
                    ghrest.paginate(
                        f"repos/{args.repo}/commits/{sha}/check-runs?filter=latest",
                        token,
                        key="check_runs",
                    )
                )
            )
        )
        if not runs:
            raise NotRun(f"на голове {sha[:7]} нет ни одной записи проверки — считать нечего (075)")

        # ОТВЕТ ПРОЕКТА ЧИТАЕТСЯ ОДИН РАЗ НА ЗАХОД: его спрашивают и разбивка
        # красного по классу, и запись стойко красного на слитом. Второе чтение
        # того же файла разошлось бы с первым молча (022).
        answer = policy.load()
        required = policy.names_of(answer, policy.REQUIRED)
        # СВЯЗИ ПРОГОНОВ ЧИТАЮТСЯ ОДИН РАЗ НА ЗАХОД (#602). Их спрашивают два
        # предмета — решение о перезапуске на общей ветке и он же на головах
        # изменений, — и каждый прежде читал их сам. Второе чтение того же
        # стоит вызовов из общей квоты и расходится с первым молча: докстрока
        # соседнего обхода требует ровно этого, а сам заход требования не
        # держал. Нашёл внешний взгляд находкой `b568a0a` (022, 058).
        fed = policy.feeds()
        red = red_of(runs)
        holds, rest = split(red, required)

        _, body = findings.live_issue(args.repo, token, MARKER)
        flakes = parse_flakes(body)
        day = datetime.now(UTC).strftime("%d.%m.%Y")

        # Мигание видно ТАМ ЖЕ, где всё остальное: зелёная запись прогона,
        # который шёл не с первой попытки. Отдельного состояния для этого не
        # нужно — площадка помнит номер попытки за нас.
        for run in runs:
            if run.get("conclusion") != "success":
                continue
            number = run_id_of(run)
            if number and attempt(args.repo, number, token) > 1:
                flakes = flakes_after(flakes, str(run.get("name", "")), number, day)

        if holds or rest:
            # Упал ровно один — перезапускается он один и один раз. Номер
            # попытки спрашивается у площадки: свой счётчик разошёлся бы с ней
            # молча, и в сторону бесконечных перезапусков.
            #
            # УСЛОВИЕ ЗДЕСЬ ТО ЖЕ, ЧТО И В РЕШЕНИИ. Пока оно было своим
            # («ровно один и никого рядом»), сценарий «агрегат плюс его
            # матрица» до перезапуска не доходил: номер прогона не вычислялся,
            # и отказ приходил уже по другой причине — «адрес записи не
            # разобрался». Починка меняла причину отказа, а не исход. Нашёл
            # внешний взгляд на #160.
            number = target_run(holds, rest, red, fed)
            tries = attempt(args.repo, number, token) if number else 1
            why = rerun_reason(holds, rest, number, tries, fed, rerunnable())
            if why:
                print(f"перезапуска не будет: {why}")
            else:
                if args.apply:
                    rerun_failed(args.repo, number, token)
                print(
                    f"упал ровно один — «{(holds or rest)[0]}»: "
                    + ("перезапущен" if args.apply else "перезапустил бы")
                    + f" прогон {number} (124)"
                )

        print(f"голова {sha[:7]}: держат слияние {len(holds)}, не держат {len(rest)}")
        for name in holds:
            print(f"  [источник 0] {name}")
        for name in rest:
            print(f"  [источник 3] {name}")
        # МИГАНИЕ НА ГОЛОВЕ ИЗМЕНЕНИЯ ВИДНО ОТСЮДА ЖЕ. Реестр мигания один
        # (#99), и второй список того же разошёлся бы с первым молча (022).
        # ПЕРЕЗАПУСК НА ИЗМЕНЕНИИ ДЕЛАЕТСЯ С 21.09.2026 — им занят
        # `rerun_on_change` (#584). Здесь стояло «НЕ делается, пока у
        # разрешённого списка нет ни одного измеренного имени»: условие
        # отсрочки было объявлено и НАСТУПИЛО, а строка осталась. Нашёл внешний
        # взгляд находкой `60eea93`; разбор отсрочки — в решении
        # `docs/decisions/014-a-flake-must-be-visible-before-it-is-rerun.md`.
        # ЖИВЫЕ ИЗМЕНЕНИЯ ЧИТАЮТСЯ ОДИН РАЗ НА ЗАХОД И РАЗДАЮТСЯ. Тот же список
        # нужен трём предметам ниже, и каждый прежде читал его сам: три обхода
        # одного источника за заход стоят вызовов из общей квоты (058) и
        # расходятся между собой молча (022, 090).
        live = live_changes(args.repo, token)
        seen = seen_on_changes(
            args.repo,
            token,
            flakes,
            day,
            live,
            answer,
            required=required,
            fed=fed,
            apply=args.apply,
        )
        flakes = seen.flakes

        # Очередь СЧИТАЕТСЯ только при заморозке: без неё этот счёт ничего не
        # решает. Спрашивать площадку для него больше не нужно — счёт идёт по
        # уже прочитанному списку, и его цена теперь нулевая.
        queue = queue_now(live) if holds else None
        # МЕТКА ЗАМОРОЗКИ РАССТАВЛЯЕТСЯ В ОБЕ СТОРОНЫ И КАЖДЫМ ЗАХОДОМ: она
        # зеркало состояния общей ветки, а не журнал события. Позеленело —
        # снимается сама, покраснело снова — вернулась (049).
        pause(args.repo, token, live, frozen=bool(holds), apply=args.apply)
        # СЧЁТЧИК ПОПЫТОК СПРАШИВАЕТСЯ ТОЛЬКО ПРИ ЗАМОРОЗКЕ. Предел живёт в
        # контуре 3 у состояния «Проверка», а оно наступает от красной
        # ОБЯЗАТЕЛЬНОЙ: совещательное красное очередь не морозит, чинить его
        # никто не обязан прямо сейчас, и будить владельца по его счёту значило
        # бы сделать приоритет, который звучит всегда (051).
        proof = proofs(args.repo, token) if holds else None
        if proof:
            print(f"заходов подряд без зелени: {proof.said()} из {TRIES_LIMIT}")
            if proof.spent:
                print("предел попыток исчерпан — адресат владелец (109)")
        save(
            args.repo,
            token,
            render_body(holds, rest, flakes, sha, queue, proof, seen.unfixed),
            args.apply,
        )
    except NotRun as exc:
        print(f"шаг не отработал: {exc}", file=sys.stderr)
        return EXIT_BROKEN
    except policy.BadPolicy as exc:
        print(f"шаг не отработал: {exc}", file=sys.stderr)
        return EXIT_BROKEN
    except ghrest.TransportError as exc:
        print(f"шаг не отработал: {report.cut(str(exc))}", file=sys.stderr)
        return EXIT_BROKEN
    return EXIT_RED if holds or rest else EXIT_GREEN


if __name__ == "__main__":
    raise SystemExit(main())
