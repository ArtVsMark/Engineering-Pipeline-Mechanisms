"""Живая задача-адресат находок: одно чтение на все механизмы.

Находка внешнего взгляда обязана иметь адресата, переживающего слияние
([142](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/142-a-scheduled-red-needs-an-addressee.md)):
комментарий на изменении после слияния перестают читать. Адресат — одна живая
задача, и находят её по скрытому маркеру, а не по заголовку: заголовок правят.

Читателей у неё двое — механизм, который записывает и снимает находки, и шаг,
который печатает остаток на каждом изменении. Читать по-разному им нечего:
второе понимание одного формата расходится с первым молча, и это здесь уже
проходили на составе меток и на связи с задачей.
"""

from __future__ import annotations

import re
from typing import Final

import ghrest

MARKER: Final = "<!-- review-findings: не удаляйте, по этой строке задача находится снова -->"
TITLE: Final = "Находки внешнего взгляда: не разобранные"
#: Запись читается СТРОКОЙ, а не прозой: формулировка ревьюера меняется от
#: прогона к прогону, отпечаток — нет.
ENTRY_RE: Final = re.compile(r"^- `([0-9a-f]{7})` · #(\d+) — (.+?)\s*$", re.M)


#: Задача-«входящие» каталога правил: её ведёт ночной прогон действия каталога,
#: и в ней лежат три числа правила 177 — задачи по правилам, очередь без ответа
#: и «признано действующим, но держится ничем». Считает их каталог, здесь их
#: только читают: второй счёт того же разошёлся бы с первым молча (022).
INBOX_MARKER: Final = "<!-- rules-inbox: не удаляйте, по этой строке задача находится снова -->"


def live_issue(repo: str, token: str, marker: str = MARKER) -> tuple[int | None, str]:
    """Находит живую задачу по скрытому маркеру.

    Списком, а не поиском: поисковый индекс площадки догоняет с задержкой в
    минуты, и за это время механизм заводит вторую задачу вместо одной.

    Маркер — параметр: живых задач-адресатов в проекте больше одной, а способ
    их находить один.
    """
    for item in ghrest.paginate(f"repos/{repo}/issues?state=open", token):
        # REST кладёт изменения в /issues наравне с задачами — отсеиваем.
        if item.get("pull_request") is not None:
            continue
        body = item.get("body") or ""
        if marker in body:
            return int(item["number"]), body
    return None, ""


def parse_entries(body: str | None) -> dict[str, tuple[int, str]]:
    """Разбирает записи живой задачи: отпечаток → (изменение, заголовок)."""
    return {mark: (int(pr), title) for mark, pr, title in ENTRY_RE.findall(body or "")}
