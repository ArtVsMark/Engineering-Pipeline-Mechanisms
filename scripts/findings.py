"""Живая задача-адресат находок: одно чтение на все механизмы.

Находка внешнего взгляда обязана иметь адресата, переживающего слияние
([142](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/142-a-scheduled-red-needs-an-addressee.md)):
комментарий на изменении после слияния перестают читать. Адресат — одна живая
задача, и находят её по скрытому маркеру, а не по заголовку: заголовок правят.

Читателей у неё двое — механизм, который записывает и снимает находки, и шаг,
который печатает остаток на каждом изменении. Читать по-разному им нечего:
второе понимание одного формата расходится с первым молча, и это здесь уже
проходили на составе меток и на связи с задачей.
"""

from __future__ import annotations

import json
import re
import sys
from dataclasses import dataclass
from functools import cache
from pathlib import Path
from typing import Any, Final

import ghrest
import paths

#: Слова, по которым живая задача узнаётся СВОИМ механизмом и отличается от
#: задачи, которую ведёт человек. Тело такой задачи механизм переписывает
#: целиком каждым заходом: галочка, поставленная рукой, исчезнет на следующем.
#:
#: ФРАЗА ЖИВЁТ В ОДНОМ МЕСТЕ, А НЕ В ПЯТИ. Её повторяли дословно пять модулей —
#: реестр находок, «входящие», непросмотренное, краснота общей ветки, дрейф, —
#: и разошлись бы они молча: задача с чуть иной фразой просто перестала бы
#: находиться (022, 090).
KEPT_BY_A_MECHANISM: Final = "не удаляйте, по этой строке задача находится снова"


def marker(name: str) -> str:
    """Метка живой задачи по имени ведущего её механизма."""
    return f"<!-- {name}: {KEPT_BY_A_MECHANISM} -->"


def is_kept_by_a_mechanism(body: str) -> bool:
    """Ведёт ли тело этой задачи механизм, а не человек.

    Спрашивается теми, кто судит о ФОРМЕ задачи: чек-лист, счёт пунктов,
    порядок разделов. Для машинной задачи все они неприменимы — её состояние
    и так счётчик, а тело пересобирается заново каждым заходом.
    """
    return KEPT_BY_A_MECHANISM in body


MARKER: Final = marker("review-findings")
TITLE: Final = "Находки внешнего взгляда: не разобранные"
#: ВЕС НАХОДКИ. Шкала закрытая, как роды у фрагментов журнала: слово вне её —
#: не вес, а мнение, и сравнивать по нему нечего
#: ([086](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/086-the-finder-does-not-grade-the-finding.md)).
#:
#: ПОЧЕМУ ШКАЛА ВООБЩЕ НУЖНА. Без неё слабая находка отличается от сильной
#: только прочтением, и разбирающий читает двадцать записей подряд, чтобы
#: понять, с какой начинать. Порядок разбора становится делом настроения — то
#: же самое, от чего очередь мержа лечится правилом 053.
#:
#: ПОЧЕМУ ТРИ. Больше градаций требуют от ревьюера различать то, что он
#: различить не может: «важно» и «очень важно» на чужом коде неотличимы.
WEIGHTS: Final = {
    "дефект": "поведение расходится с обещанным",
    "риск": "сломается при названном условии, но пока работает",
    "замечание": "текст, ясность, единообразие",
}
#: РОД ПРЕДМЕТА НАХОДКИ — ЗАКРЫТЫЙ СЛОВАРЬ ИЗ ДВУХ, И РАЗНИЦА НЕ КОСМЕТИЧЕСКАЯ.
#: Находка о КОДЕ говорит, что механизм расходится с обещанным; находка об
#: ОТВЕТЕ говорит, что расходится с деревом наш ответ каталогу правил — то есть
#: утверждение, которое живёт годами и читается соседями как факт.
#:
#: ЗАМЕР, ИЗ-ЗА КОТОРОГО ЭТО ЗАВЕДЕНО. Карта, которую проект сам выдаёт взгляду
#: (`scripts/review_map.py`), говорит ему дословно: «это находка об ОТВЕТЕ, а не
#: о коде, и она дороже любой другой». А запись в реестре рода не несла: те же
#: три веса, и ни одного поля про предмет. Механизм объявлял такие находки более
#: ценными и терял различие при записи — то есть отдачу канала по ответам
#: посчитать было нечем. 17.09.2026 ответ 007 («неприменимо») оказался ложным, и
#: нашёл его ПОЛНЫЙ ОБХОД, а не взгляд, при том что карта звала смотреть именно
#: туда ([046](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/046-name-the-gaps-do-not-level-them.md)).
KINDS: Final = {
    "код": "механизм расходится с обещанным",
    "ответ": "наш ответ каталогу расходится с деревом",
}
#: Род по умолчанию: подавляющее большинство находок о коде.
CODE: Final = "код"
ANSWER_KIND: Final = "ответ"
#: МЕХАНИЧЕСКИЙ ПОЛ: находка, называющая файл ответа, — об ОТВЕТЕ, назвал это
#: ревьюер или забыл. Пометка ревьюера и этот признак не два ответа на один
#: вопрос, а требование и его нижняя граница: пометка может быть шире (находка
#: об ответе, не называющая файла), пол — уже, но не забывается (051).
ANSWER_FILE: Final = paths.BINDINGS.as_posix()


#: Вес, которого ревьюер не назвал. Это ОБЪЯВЛЕННОЕ состояние, а не подстановка
#: самого лёгкого: молча приписать находке «замечание» значило бы решить за
#: ревьюера в сторону, удобную разбирающему (154).
UNWEIGHED: Final = "без веса"

#: Запись читается СТРОКОЙ, а не прозой: формулировка ревьюера меняется от
#: прогона к прогону, отпечаток — нет.
#: Запись читается СТРОКОЙ, и поля в ней разделены точкой, а не позицией. Вес
#: берётся до первой же точки-разделителя: иначе необязательный хвост проверки
#: премисы уезжал бы внутрь веса и запись читалась бы как «вес неизвестен».
#: ПОЛЯ НАЗВАНЫ, А НЕ ПЕРЕСЧИТАНЫ. Прежде группы брались номерами, и добавление
#: одной именованной сдвинуло нумерацию: `title` уехал на место `checked`, а
#: разбор упал на первом же прогоне. Имена не сдвигаются от вставки соседа (090).
ENTRY_RE: Final = re.compile(
    r"^- `(?P<mark>[0-9a-f]{7})` · #(?P<pr>\d+) · (?P<weight>[^·—]+?)"
    r"(?: · (?P<kind>об ответе))?"
    r"(?: · глазами (?P<role>[^·—]+?))?"
    r"(?: · (?P<checked>премиса[^—]*?))? — (?P<title>.+?)\s*$",
    re.M,
)
#: Как род пишется в строке записи. Пишется ТОЛЬКО «ответ»: род по умолчанию —
#: молчаливое большинство, и выписывать его в каждую строку значило бы удлинить
#: реестр ради того, что и так говорит заголовок раздела.
KIND_SAID: Final = "об ответе"

#: ПРЕДЕЛ ДЛИНЫ ОДНОЙ НАХОДКИ, И ВЗЯТ ОН ЗАМЕРОМ, А НЕ ИЗ ГОЛОВЫ.
#: Правило 117 требует, чтобы числа стояли в ЗАДАНИИ исполнителя: без них он
#: выбирает их сам, и выбирает плохо. Число здесь — потолок того, что канал уже
#: писал, а не желаемое: замер 17.09.2026 по четырнадцати живым записям реестра
#: дал минимум 35 знаков, медиану 138, девятый дециль 200 и потолок 303. Предел
#: поставлен по потолку — 300, и одна запись из четырнадцати превышает его на
#: три знака. Он ограничивает РАЗРАСТАНИЕ, а не режет написанное.
#:
#: НАЗВАННАЯ ГРАНИЦА ЗАМЕРА: выборка тонкая — четырнадцать записей, потому что
#: разобранное из реестра уходит обходом и в нём не копится. Число подлежит
#: пересмотру, когда выборка вырастет, и это не повод не называть его сегодня
#: ([046](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/046-name-the-gaps-do-not-level-them.md)).
#:
#: РЕЕСТР ПО НЕМУ НЕ РЕЖЕТ. Обрезать чужую находку значило бы потерять её хвост
#: ради формы; предел живёт в задании и адресован тому, кто пишет, а не тому,
#: кто читает.
SAID_LIMIT: Final = 300

#: Ответ верификатора: подтверждена премиса находки или нет. Шкала закрытая, как
#: у веса: слово вне её — мнение, и сравнивать по нему нечего (068).
CONFIRMED: Final = "премиса подтверждена"
REFUTED: Final = "премиса не подтвердилась"
CHECKED: Final = (CONFIRMED, REFUTED)


@dataclass(frozen=True, slots=True)
class Entry:
    """Одна запись живой задачи: откуда пришла, чего стоит, о чём и оспорена ли.

    ХВОСТ ПРОВЕРКИ ДОПИСЫВАЕТСЯ, А НЕ ЗАМЕНЯЕТ ЗАПИСЬ. «Премиса не
    подтвердилась» — не снятие: находку снимает работа, а верификатор только
    говорит, что чинить, возможно, нечего. Решение остаётся за тем, кто берёт
    работу
    ([154](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/154-none-must-name-its-reason.md)).
    """

    pr: int
    weight: str
    title: str
    checked: str = ""
    kind: str = CODE
    #: Роль, глазами которой находка увидена (#763); пусто — не названа.
    role: str = ""

    def said(self) -> str:
        """Строка записи. Хвост появляется, только если проверка была."""
        род = f" · {KIND_SAID}" if self.kind == ANSWER_KIND else ""
        глазами = f" · {ROLE_SAID} {self.role}" if self.role else ""
        tail = f" · {self.checked}" if self.checked else ""
        return f"· #{self.pr} · {self.weight}{род}{глазами}{tail} — {self.title}"


#: Задача-«входящие» каталога правил: её ведёт ночной прогон действия каталога,
#: и в ней лежат три числа правила 177 — задачи по правилам, очередь без ответа
#: и «признано действующим, но держится ничем». Считает их каталог, здесь их
#: только читают: второй счёт того же разошёлся бы с первым молча (022).
INBOX_MARKER: Final = marker("rules-inbox")


def live_issue(repo: str, token: str, marker: str = MARKER) -> tuple[int | None, str]:
    """Находит живую задачу по скрытому маркеру.

    Списком, а не поиском: поисковый индекс площадки догоняет с задержкой в
    минуты, и за это время механизм заводит вторую задачу вместо одной.

    Маркер — параметр: живых задач-адресатов в проекте больше одной, а способ
    их находить один.

    ВТОРАЯ ЖИВАЯ ЗАДАЧА — НЕ ВЫБОР, А ПРОИСШЕСТВИЕ. Механизм обещает ОДНУ, и
    если их две, то часть записей лежит там, куда никто не смотрит: адресат,
    размноженный надвое, — это отсутствующий адресат
    ([142](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/142-a-scheduled-red-needs-an-addressee.md)).
    Замер 09.09.2026: за смену завелось ПЯТЬ копий, и находки разъехались по
    ним. Прежняя редакция брала первую попавшуюся из списка — то есть ту, чей
    номер площадка вернёт первым, — и молчала.

    Здесь выбирается САМАЯ РАННЯЯ (наименьший номер), и о лишних говорится
    вслух. Ранняя, а не любая: она старше остальных, в ней больше записей и на
    неё уже ссылаются. Отказом это не делается намеренно: канал находок
    необязательный, и упасть здесь значило бы потерять запись целиком вместо
    того, чтобы положить её в известное место
    ([084](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/084-best-effort-channels-never-block-the-main-path.md)).
    """
    number, body, _ = live_issue_seen(repo, token, marker)
    return number, body


def live_issue_seen(repo: str, token: str, marker: str = MARKER) -> tuple[int | None, str, str]:
    """То же, но третьим отдаёт, КОГДА задачу последний раз трогали.

    ЗАЧЕМ ВОЗРАСТ. Часть этих задач ведёт не наш механизм, а чужой прогон:
    «входящие» пишет ночной заход каталога. Числа из них читаются как сегодняшние,
    а бывают вчерашними — и по вчерашним уже строилась работа
    ([005](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/005-hand-written-numbers-rot.md)).

    ГРАНИЦА ЭТОЙ ДАТЫ НАЗВАНА ЗДЕСЬ, А НЕ У ЧИТАТЕЛЯ. `updated_at` двигает любая
    правка задачи, включая комментарий человека. Поэтому «старо» она показывает
    надёжно, а «свежо» — нет: свежая дата не доказывает, что числа пересчитаны.
    Годится она ровно на то, для чего взята, — заметить ПРОПУЩЕННЫЙ заход.
    """
    found: list[tuple[int, str, str]] = []
    seen = 0
    for item in ghrest.paginate(f"repos/{repo}/issues?state=open", token):
        seen += 1
        # REST кладёт изменения в /issues наравне с задачами — отсеиваем.
        if item.get("pull_request") is not None:
            continue
        body = item.get("body") or ""
        if marker in body:
            found.append((int(item["number"]), body, str(item.get("updated_at") or "")))
    if not found:
        # ПУСТОЙ ОТВЕТ ПЛОЩАДКИ — НЕ «ЗАДАЧИ НЕТ». Список открытых записей у
        # живого проекта пуст не бывает: там всегда есть хотя бы эта самая
        # задача. Ноль записей означает, что ответ подозрителен — площадка
        # отдала 200 с пустым телом, — и принять его за отсутствие значит
        # завести вторую живую задачу на ровном месте (045).
        #
        # Замер 10.09.2026: так и вышло. Заход в 15:00:50 не нашёл #23, завёл
        # #139 и переписал в неё 47 записей; уникального в ней не оказалось ни
        # одного — все они уже лежали в #23, и следующий заход снова писал туда.
        if not seen:
            raise ghrest.TransportError(
                "площадка вернула пустой список открытых записей — это не «задачи нет», "
                "а подозрительный ответ: заводить вторую живую задачу по нему нельзя (045)"
            )
        return None, "", ""
    found.sort()
    if len(found) > 1:
        extra = ", ".join(f"#{number}" for number, _, _ in found[1:])
        print(
            f"::warning::Живых задач с этим маркером {len(found)}, а обещана одна. "
            f"Записи идут в самую раннюю #{found[0][0]}; сведите и закройте лишние: {extra}",
            file=sys.stderr,
        )
    return found[0]


def kind_of(title: str, said: str = "") -> str:
    """Род предмета находки: объявленный ревьюером либо выведенный по адресу.

    ДВА ИСТОЧНИКА, И ОНИ НЕ СПОРЯТ. Пометка ревьюера шире: находка об ответе
    может не называть файла вовсе. Признак по адресу уже, зато не забывается —
    находка, называющая `.rules/bindings.json`, об ответе по определению.
    Поэтому пол, а не выбор одного из двух.
    """
    if said.strip() == ANSWER_KIND or said.strip() == KIND_SAID:
        return ANSWER_KIND
    return ANSWER_KIND if ANSWER_FILE in title else CODE


#: Как роль пишется в строке записи: «глазами <роль>».
ROLE_SAID: Final = "глазами"
#: Заголовок профиля роли в карте ролей: `### <знак> <Имя>`.
ROLE_RE: Final = re.compile(r"^### \S+ (?P<name>\S.*?)\s*$", re.M)
#: Раздел карты, где лежат профили.
PROFILES_HEAD: Final = "## Профили"


@cache
def roles(path: Path = paths.ROLES) -> frozenset[str]:
    """Роли, глазами которых смотрит взгляд, — из профилей карты ролей (#763).

    СПИСОК НЕ ПИШЕТСЯ ВТОРОЙ РАЗ. Состав ролей живёт в `docs/roles.md`, и
    подсказка взгляда отсылает туда же: второй список разошёлся бы с картой
    молча (022). Карты нет — ролей нет, и пометка в скобке находки просто не
    узнаётся: запись ляжет без роли, а не упадёт.
    """
    if not path.is_file():
        return frozenset()
    text = path.read_text(encoding="utf-8")
    start = text.find(PROFILES_HEAD)
    if start < 0:
        return frozenset()
    end = text.find("\n## ", start + len(PROFILES_HEAD))
    part = text[start : end if end > 0 else len(text)]
    return frozenset(" ".join(found.split()).lower() for found in ROLE_RE.findall(part))


def parse_entries(body: str | None) -> dict[str, Entry]:
    """Разбирает записи живой задачи: отпечаток → запись."""
    return {
        match.group("mark"): Entry(
            int(match.group("pr")),
            match.group("weight").strip(),
            match.group("title"),
            (match.group("checked") or "").strip(),
            kind_of(match.group("title"), match.group("kind") or ""),
            (match.group("role") or "").strip(),
        )
        for match in ENTRY_RE.finditer(body or "")
    }


# --- архив находок: одно чтение формы на всех читателей -----------------------

#: Начало строки `gaps`, которой архив говорит, что наполнение не дошло до
#: головы. Пишет её `findings_archive`, читают замеры — одна константа на обе
#: стороны, иначе переформулировка молча сделала бы архив «полным» (090).
UNFILLED: Final = "наполнение не дошло до головы"


def read_archive(path: Path) -> dict[str, Any]:
    """Архив находок с диска, проверенный по форме; отказ — `ValueError` с причиной.

    Замеры читали архив как придётся, и чужая форма роняла их трассой вместо
    исхода 2 с причиной (039, взгляд на #817). Проверяется ровно то, чем они
    пользуются: словарь записей и номера изменений числами.
    """
    try:
        archive = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise ValueError(f"архив не прочитан — {exc}") from exc
    if not isinstance(archive, dict):
        raise ValueError("архив не словарь")
    entries = archive.get("findings") or {}
    if not isinstance(entries, dict) or not all(isinstance(one, dict) for one in entries.values()):
        raise ValueError("`findings` в архиве — не словарь записей")
    numbers = [*(archive.get("counted") or [])]
    numbers += [number for one in entries.values() for number in one.get("seen_on") or []]
    if not all(isinstance(number, int) and not isinstance(number, bool) for number in numbers):
        raise ValueError("номер изменения в архиве — не число")
    return archive


def unfilled(archive: dict[str, Any]) -> str:
    """Строка архива о неполном наполнении или пусто, если архив дошёл до головы."""
    return next(
        (str(one) for one in archive.get("gaps") or [] if str(one).startswith(UNFILLED)), ""
    )
