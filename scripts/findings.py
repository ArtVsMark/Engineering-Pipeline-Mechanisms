"""Живая задача-адресат находок: одно чтение на все механизмы.

Находка внешнего взгляда обязана иметь адресата, переживающего слияние
([142](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/142-a-scheduled-red-needs-an-addressee.md)):
комментарий на изменении после слияния перестают читать. Адресат — одна живая
задача, и находят её по скрытому маркеру, а не по заголовку: заголовок правят.

Читателей у неё двое — механизм, который записывает и снимает находки, и шаг,
который печатает остаток на каждом изменении. Читать по-разному им нечего:
второе понимание одного формата расходится с первым молча, и это здесь уже
проходили на составе меток и на связи с задачей.
"""

from __future__ import annotations

import re
import sys
from dataclasses import dataclass
from typing import Final

import ghrest

MARKER: Final = "<!-- review-findings: не удаляйте, по этой строке задача находится снова -->"
TITLE: Final = "Находки внешнего взгляда: не разобранные"
#: ВЕС НАХОДКИ. Шкала закрытая, как роды у фрагментов журнала: слово вне её —
#: не вес, а мнение, и сравнивать по нему нечего
#: ([086](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/086-severity-is-set-by-someone-else.md)).
#:
#: ПОЧЕМУ ШКАЛА ВООБЩЕ НУЖНА. Без неё слабая находка отличается от сильной
#: только прочтением, и разбирающий читает двадцать записей подряд, чтобы
#: понять, с какой начинать. Порядок разбора становится делом настроения — то
#: же самое, от чего очередь мержа лечится правилом 053.
#:
#: ПОЧЕМУ ТРИ. Больше градаций требуют от ревьюера различать то, что он
#: различить не может: «важно» и «очень важно» на чужом коде неотличимы.
WEIGHTS: Final = {
    "дефект": "поведение расходится с обещанным",
    "риск": "сломается при названном условии, но пока работает",
    "замечание": "текст, ясность, единообразие",
}
#: Вес, которого ревьюер не назвал. Это ОБЪЯВЛЕННОЕ состояние, а не подстановка
#: самого лёгкого: молча приписать находке «замечание» значило бы решить за
#: ревьюера в сторону, удобную разбирающему (154).
UNWEIGHED: Final = "без веса"

#: Запись читается СТРОКОЙ, а не прозой: формулировка ревьюера меняется от
#: прогона к прогону, отпечаток — нет.
ENTRY_RE: Final = re.compile(r"^- `([0-9a-f]{7})` · #(\d+) · ([^—]+?) — (.+?)\s*$", re.M)


@dataclass(frozen=True, slots=True)
class Entry:
    """Одна запись живой задачи: откуда пришла, чего стоит и о чём."""

    pr: int
    weight: str
    title: str


#: Задача-«входящие» каталога правил: её ведёт ночной прогон действия каталога,
#: и в ней лежат три числа правила 177 — задачи по правилам, очередь без ответа
#: и «признано действующим, но держится ничем». Считает их каталог, здесь их
#: только читают: второй счёт того же разошёлся бы с первым молча (022).
INBOX_MARKER: Final = "<!-- rules-inbox: не удаляйте, по этой строке задача находится снова -->"


def live_issue(repo: str, token: str, marker: str = MARKER) -> tuple[int | None, str]:
    """Находит живую задачу по скрытому маркеру.

    Списком, а не поиском: поисковый индекс площадки догоняет с задержкой в
    минуты, и за это время механизм заводит вторую задачу вместо одной.

    Маркер — параметр: живых задач-адресатов в проекте больше одной, а способ
    их находить один.

    ВТОРАЯ ЖИВАЯ ЗАДАЧА — НЕ ВЫБОР, А ПРОИСШЕСТВИЕ. Механизм обещает ОДНУ, и
    если их две, то часть записей лежит там, куда никто не смотрит: адресат,
    размноженный надвое, — это отсутствующий адресат
    ([142](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/142-a-scheduled-red-needs-an-addressee.md)).
    Замер 09.09.2026: за смену завелось ПЯТЬ копий, и находки разъехались по
    ним. Прежняя редакция брала первую попавшуюся из списка — то есть ту, чей
    номер площадка вернёт первым, — и молчала.

    Здесь выбирается САМАЯ РАННЯЯ (наименьший номер), и о лишних говорится
    вслух. Ранняя, а не любая: она старше остальных, в ней больше записей и на
    неё уже ссылаются. Отказом это не делается намеренно: канал находок
    необязательный, и упасть здесь значило бы потерять запись целиком вместо
    того, чтобы положить её в известное место
    ([084](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/084-best-effort-channels-never-block-the-main-path.md)).
    """
    found: list[tuple[int, str]] = []
    for item in ghrest.paginate(f"repos/{repo}/issues?state=open", token):
        # REST кладёт изменения в /issues наравне с задачами — отсеиваем.
        if item.get("pull_request") is not None:
            continue
        body = item.get("body") or ""
        if marker in body:
            found.append((int(item["number"]), body))
    if not found:
        return None, ""
    found.sort()
    if len(found) > 1:
        extra = ", ".join(f"#{number}" for number, _ in found[1:])
        print(
            f"::warning::Живых задач с этим маркером {len(found)}, а обещана одна. "
            f"Записи идут в самую раннюю #{found[0][0]}; сведите и закройте лишние: {extra}",
            file=sys.stderr,
        )
    return found[0]


def parse_entries(body: str | None) -> dict[str, Entry]:
    """Разбирает записи живой задачи: отпечаток → запись."""
    return {
        mark: Entry(int(pr), weight.strip(), title)
        for mark, pr, weight, title in ENTRY_RE.findall(body or "")
    }
