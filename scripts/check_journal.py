#!/usr/bin/env python3
"""Гейт: изменение несёт фрагмент журнала.

Правило 030: журнал собирается из фрагментов, и фрагмент едет **вместе с
изменением**, а не пишется после выпуска по памяти. Гейт держит именно это:
изменение, тронувшее что-либо кроме журнала и производных файлов, обязано
принести фрагмент.

Правило 154: ответ «журналу это безразлично» — состояние, а не молчание.
Выражается фрагментом рода ``internal``, ПЕРВАЯ строка которого называет
причину в заданной форме: ``> **Потребителю безразлично:** …``. Форму держит
разбор фрагментов (``scripts/build_changelog.py``), один на обоих читателей.

Гейт судит по **коммитам**, а не по рабочему дереву: в прогоне на изменении
всё уже зафиксировано, и рабочего дерева там нет вовсе. Локально это значит,
что фрагмент надо закоммитить, а не только положить рядом.

Исходы (правило 039): ``0`` фрагмент есть · ``1`` изменение отвергнуто ·
``2`` гейт не отработал.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Final

import changerefs
import journal
import paths

FRAGMENT_RE: Final = journal.PATH_RE

# Тронув только это, изменение журналу ничего не сообщает.
EXEMPT_PREFIXES: Final = ("changelog.d/",)

#: СОБРАННЫЙ ЖУРНАЛ НА ИЗМЕНЕНИИ НЕ ТРОГАЮТ, И ЗДЕСЬ ОН БЫЛ ОСВОБОЖДЁН.
#: `CHANGELOG.md` стоял в списке «тронув только это, изменение журналу ничего
#: не сообщает» — то есть гейт РАЗРЕШАЛ ровно то, что запрещает правило 030:
#: сборку делает выпуск, а общий файл, который трогает каждая ветка, даёт
#: конфликт на каждом втором изменении.
#:
#: Замер 21.09.2026 по 90 коммитам общей ветки: `CHANGELOG.md` тронут в
#: шестнадцати — один раз коммитом выпуска (законно, он его и собирает) и
#: пятнадцать раз изменениями одного окна за две смены; до них — ни разу. Один
#: конфликт уже стоил перебазы (#561) — тот самый инцидент, ради которого
#: фрагменты и заведены.
#:
#: ИСКЛЮЧЕНИЯ ДЛЯ ВЫПУСКА ЗДЕСЬ НЕ НУЖНО, и это проверено: коммит `release:
#: 1.2.0` через изменение не проходил — площадка не знает ни одного изменения,
#: его содержащего. Выпуск коммитит в общую ветку напрямую, а гейт идёт на
#: `pull_request`.
#: ИМЯ БЕРЁТСЯ У КАНОНА, А НЕ ПИШЕТСЯ ЗАНОВО (#591). Здесь стоял третий по
#: счёту литерал `"CHANGELOG.md"` в дереве — при том, что канон объявлен
#: (`paths.CHANGELOG`), а этот модуль `paths` уже импортирует. Нашёл внешний
#: взгляд находкой `10ca99d`, и сам `paths.py` документирует этот класс на
#: примере `TRUNK`: три независимых написания имени общей ветки разъехались
#: молча (022, 090). Работало верно сегодня; цена — молчаливый дрейф, если
#: канонический путь переедет.
BUILT_JOURNAL: Final = str(paths.CHANGELOG)
#: Где живут механизмы: правка здесь меняет поведение, а не текст. Состав
#: источников ЧИТАЕТСЯ из объявления и не перечисляется тут: третье написание
#: того же нашлось внешним взглядом (`675d64c`), а здесь оно уже стоило дыры —
#: `packages/transport/` в перечне не было, и починка общего низа проходила
#: гейт БЕЗ единой проверки (022, 090). Прогоны добавлены рядом: они тоже
#: механизм, но объявлению `paths.SOURCES` не принадлежат — это не код проекта,
#: а его обвязка.
CODE_PREFIXES: Final = (
    *(f"{one.as_posix()}/" for one in paths.SOURCES),
    f"{paths.WORKFLOWS.as_posix()}/",
)
#: Где живут проверки.
TESTS_PREFIX: Final = "tests/"
#: Род записи, означающий починку дефекта.
FIXED: Final = "fixed"
#: Род записи, которой потребителю безразлично: внутренняя. Темой изменения она
#: не является — ею сопровождают чужую работу, и считать её второй темой значило
#: бы предупреждать о том, что автор как раз и объявил безразличным.
INTERNAL: Final = "internal"

#: Сколько тем наружу изменение везёт БЕЗ предупреждения. Тема объявляется
#: записью журнала: две записи наружу — это два «зачем», сказанные самим
#: автором, а не догадка машины о смысле правки.
#:
#: ЗАМЕР 13.09.2026 ПО 120 СЛИТЫМ: одна запись наружу у 101 изменения, две — у
#: шести, четыре — у одного. Порог берётся оттуда, а не из головы.
#:
#: ПЕРВЫЙ ПРИЗНАК ЗАМЕР ОТВЕРГ. Считать зоны (`area/*`) не вышло: они вложены
#: друг в друга — правка `automerge.py` даёт разом `area/gates` и `area/merge`,
#: — и порог в четыре зоны дал бы пять ложных срабатываний из 120 и ни одного
#: истинного
#: ([044](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/044-check-the-premise-before-fixing.md)).
TOPICS_WITHOUT_WARNING: Final = 1

EXIT_OK: Final = 0
EXIT_REJECTED: Final = 1
EXIT_BROKEN: Final = 2


#: Отказ чтения дифа приходит из общего модуля: у гейта он остаётся третьим
#: исходом, а разбор его — один на всех читателей.
NotRun = journal.NotRun


def numbered(path: str) -> bool:
    """Назван ли фрагмент номером задачи, а не смыслом записи."""
    match = journal.NAME_RE.match(path.rsplit("/", 1)[-1])
    return bool(match and journal.DIGITS_ONLY_RE.match(match.group("slug")))


def outward(fragments: list[str]) -> list[str]:
    """Записи, обращённые НАРУЖУ: внутренние темой изменения не считаются."""
    return sorted(name for name in fragments if not name.endswith(f".{INTERNAL}.md"))


def say_if_compound(fragments: list[str]) -> None:
    """Предупреждает о сборном изменении — предупреждает, а не отвергает.

    ОДНО ИЗМЕНЕНИЕ — ОДНА ТЕМА
    ([132](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/132-one-change-carries-one-topic.md)).
    Сборное можно сделать честным, объявив все задачи, но нельзя сделать
    разбираемым: его не отревьюить по частям, не откатить по частям и не найти
    в нём причину поломки по частям.

    ОТКАЗА ЗДЕСЬ НЕТ, И ЭТО ТРЕБОВАНИЕ САМОГО ПРАВИЛА: широкая тема — это одна
    тема, и ложный отказ на ней дороже пропуска
    ([051](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/051-warn-on-likely-block-on-certain.md),
    [084](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/084-best-effort-channels-never-block-the-main-path.md)).
    Переименование вместе со всеми его следствиями неделимо, и машине это не
    отличить от сборности — поэтому решает автор, а механизм только спрашивает.

    ПРЕДМЕТ — ОБЪЯВЛЕНИЕ АВТОРА, А НЕ ДОГАДКА О СМЫСЛЕ. Запись журнала отвечает
    «что изменилось» читателю снаружи; две записи наружу — это два «зачем»,
    названные самой работой.
    """
    themes = outward(fragments)
    if len(themes) <= TOPICS_WITHOUT_WARNING:
        return
    # ЧИСЛО СТОИТ ПОСЛЕ СУЩЕСТВИТЕЛЬНОГО, А НЕ ПЕРЕД НИМ. «5 записи» — то, что
    # печаталось при пяти темах: согласование числительного зависит от самого
    # числа, и склеенная строка врёт на каждом значении, кроме тех, на которых
    # её написали. Нашёл внешний взгляд на #322.
    print(
        f"::warning::Изменение везёт записей журнала наружу: {len(themes)} "
        f"({', '.join(themes)}) — столько же тем оно и объявляет само. "
        "Сборное изменение не отревьюить, не откатить и не разобрать по частям (132). "
        "Если темы независимы — разделите; если тема одна и просто широкая, это законно "
        "и предупреждение можно пропустить.",
        file=sys.stderr,
    )


def marks_of(text: str) -> set[str]:
    """Отпечатки находок, снятых строкой «Разобрано:» в этом тексте.

    РАЗБОР ОДИН НА ВСЕХ ЧИТАТЕЛЕЙ СТРОКИ, и берётся он у `changerefs`. Здесь
    жил свой: строка находилась образцом, а отпечатки выбирались `[0-9a-f]{7}`
    по ВСЕЙ строке — то есть и по тексту причины. Ровно этот дефект `changerefs`
    уже чинил у себя, разведя отпечатки и причину, и второй разбор повторял его
    заново (нашёл внешний взгляд на #439).

    ДВА ДОВОДА, КОТОРЫМИ ДУБЛЬ ОПРАВДЫВАЛСЯ, ОКАЗАЛИСЬ НЕВЕРНЫ ОБА. Первый —
    «`changerefs` тянет за собой транспорт»: он импортирует только стандартную
    библиотеку, и проверить это стоило одного взгляда на его шапку. Второй —
    «разъехаться им не даёт `tests/test_journal.py`»: такого файла в дереве нет
    и не было, то есть сторожем был назначен адрес, которого не существует
    ([022](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/022-one-canonical-document.md),
    [090](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/090-shared-helpers-move-up-not-sideways.md)).

    ЗАМЕР 17.09.2026: по 660 строкам «Разобрано» в журнале и последних 400 телах
    коммитов два разбора совпали на ВСЕХ — дефект скрытый, а не сработавший.
    Предъявить его при этом можно одной строкой: «Разобрано: abc1234 — премиса
    опровергнута заходом deadbee» свой разбор читает как ДВА снятия.
    """
    return set(changerefs.resolved_in(text))


#: Как площадка говорит «такого пути там не было». Отличать это от прочих
#: отказов обязательно: «файла не существовало» — законный исход, а «git не
#: смог» — третий, и сваливать второй в первый значит зеленеть на своей
#: поломке
#: ([039](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/039-three-outcomes-not-two.md)).
#: Прежняя редакция глушила ЛЮБОЙ отказ `git show`, и битая ссылка, обрезанный
#: чекаут или сломанный репозиторий читались как «фрагмент здесь родился» —
#: то есть заход требовал увезти все отметки и не говорил, почему.
#: Нашёл внешний взгляд на #441.
#:
#: ФОРМ ДВЕ, И ВТОРУЮ НАШЁЛ ПРОГОН, А НЕ ПАМЯТЬ. Первая редакция знала одну —
#: «does not exist in», — и живой набор покраснел на второй: у пути, который
#: ЕСТЬ в рабочем дереве и отсутствует в том коммите, git говорит иначе. Это
#: сработала строгая сторона: неузнанный отказ ушёл наверх третьим исходом и
#: назвался, вместо того чтобы молча прочитаться как «файла не было» (045).
#: Список закрытый и растёт правкой: новая форма — это правка здесь, а не
#: догадка образца (068).
#:
#: Обе сняты с живого вызова 17.09.2026, `git show <ссылка>:<путь>` по пути,
#: которого у этой ссылки нет:
#:   fatal: path '<путь>' does not exist in '<ссылка>'      — пути там не было;
#:   fatal: path '<путь>' exists on disk, but not in '<sha>' — путь есть в
#:                                                             рабочем дереве.
NO_SUCH_PATH: Final = ("does not exist in", "exists on disk, but not in")


def at_base(ancestor: str, name: str) -> str:
    """Каким файл был у ОБЩЕГО ПРЕДКА: пусто, если его там не было вовсе.

    Отсутствие — законный исход, а не отказ: фрагмент, ЗАВЕДЁННЫЙ этой работой,
    у предка не существует, и все его отметки новые.

    ЧИТАЕТСЯ ПРЕДОК, А НЕ ВЕРШИНА БАЗЫ. Вершина движется, пока изменение
    открыто: соседи сливаются, а выпуск переносит фрагменты журнала в
    `released/` — и тогда `main:changelog.d/<фрагмент>` не существует вовсе,
    все его отметки становятся «новыми», и заход требует увезти уже уехавшее.
    Список файлов берётся от предка тем же `journal.common_ancestor`, и
    содержимое обязано браться оттуда же (нашёл внешний взгляд на #441).
    """
    try:
        return journal.git(["git", "show", f"{ancestor}:{name}"])
    except NotRun as exc:
        if any(said in str(exc) for said in NO_SUCH_PATH):
            return ""
        raise


def travelled(base: str, ancestor: str | None = None) -> list[str]:
    """Отметки снятия, объявленные фрагментом и НЕ уехавшие с работой.

    ``ancestor`` — уже спрошенная точка сравнения: зовущему, которому она нужна
    и самому, незачем спрашивать её вторым вызовом. Тем же словом и по той же
    причине её принимает `journal.changed_files`; там оно объяснено прозой, а
    здесь молчало (нашёл внешний взгляд на #454).

    СНЯТИЕ ЕДЕТ ТЕЛОМ КОММИТА, А НЕ ФРАГМЕНТОМ ЖУРНАЛА. Уборка реестра читает
    тело слитого ИЗМЕНЕНИЯ, а тело изменения собирает `scripts/agent_pr.py` из
    тел коммитов. Фрагмент журнала в эту цепочку не входит вовсе: отметка,
    написанная только в нём, адресату не доезжает — работа сделана, находка в
    реестре осталась, и снять её больше нечем.

    ЗАМЕР 17.09.2026: так потерялись ДВАДЦАТЬ ТРИ снятия за одну смену. Семь
    изменений подряд объявляли находки разобранными во фрагменте и ни одного
    отпечатка не положили в коммит. Реестр всё это время рос: к концу смены он
    держал 33 записи, из которых 23 были починены.

    ПОЧЕМУ ЭТО СЛУЧИЛОСЬ, А НЕ «КТО ЗАБЫЛ». Навык разбора находки говорил «снять
    строкой в ТЕЛЕ ИЗМЕНЕНИЯ» — а тело изменения окно писать не вправе вовсе
    ([131](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/131-no-writes-from-a-cloud-session.md)):
    его собирает конвейер. Адрес был назван тот, которого у окна нет, и окно
    выбрало похожий.
    """
    ancestor = ancestor or journal.common_ancestor(base)
    fragments = [
        name
        for name in journal.changed_files(base, alive_only=True, ancestor=ancestor)
        if FRAGMENT_RE.match(name)
    ]
    claimed: set[str] = set()
    for name in fragments:
        try:
            now = marks_of(Path(name).read_text(encoding="utf-8"))
        except OSError:
            continue
        # СПРАШИВАЕТСЯ ТО, ЧТО ОБЪЯВИЛО ЭТО ИЗМЕНЕНИЕ, А НЕ ВСЁ, ЧТО СТОИТ ВО
        # ФРАГМЕНТЕ. Первая редакция брала текущий текст целиком — и требовала
        # повезти отметки, которые фрагмент нёс ЕЩЁ ДО этой работы: изменение,
        # правящее в нём одну фразу, обязано было заново положить в тело ДЕВЯТЬ
        # чужих отпечатков. Поймано на #438: правка прозы в уже слитом фрагменте
        # покраснела отметками, уехавшими с тем изменением, которое их и
        # объявило. Отметку везёт тот, кто её поставил, и везёт один раз (045).
        claimed |= now - marks_of(at_base(ancestor, name))
    if not claimed:
        return []
    carried = marks_of(journal.git(["git", "log", "--format=%B", f"{base}..HEAD"]))
    return sorted(claimed - carried)


def main(argv: list[str] | None = None) -> int:
    """Точка входа: печатает исход и возвращает его код."""
    parser = argparse.ArgumentParser(description=__doc__)
    # Площадка отдаёт базу коротким именем («main»), а в дереве прогона она
    # существует как `origin/main`, поэтому приставка нужна. Но ставится она
    # ТОЛЬКО к умолчанию из окружения: переданное ключом имя — это то, что
    # имел в виду зовущий, и молча переписывать его нельзя. Ровно на этом гейт
    # и упал в первом же прогоне на площадке — локально переменной нет, и
    # расхождение не воспроизводилось.
    parser.add_argument("--base", default=journal.base_from_env(), help="ветка сравнения")
    args = parser.parse_args(argv)

    # ТОЧКА СРАВНЕНИЯ СПРАШИВАЕТСЯ ОДИН РАЗ НА ЗАХОД, И СПРАШИВАЕТСЯ ЗДЕСЬ.
    # Прежде её брали трижды: дважды внутри `changed_files` и ещё раз внутри
    # `travelled`. Заявление «спрашивается однажды» было сделано, когда убрали
    # ОДИН из трёх — то есть оказалось шире починки (нашёл внешний взгляд на
    # #451, и назвал дважды).
    #
    # Цена трёх вопросов не в трёх вызовах git: общая ветка движется, пока
    # изменение открыто, и три читателя одного захода могут получить РАЗНЫЕ
    # точки — список путей от одной, выжившие от другой, содержимое от третьей.
    try:
        ancestor = journal.common_ancestor(args.base)
        files = journal.changed_files(args.base, ancestor=ancestor)
    except NotRun as exc:
        print(f"проверка не отработала: {exc}", file=sys.stderr)
        return EXIT_BROKEN

    # Охват называется до вердикта: проверка, читающая список путей, без числа
    # неотличима от чистого результата (165).
    exempt = [name for name in files if name.startswith(EXEMPT_PREFIXES)]
    print(f"тронутых путей прочитано: {len(files)}, из них журнальных: {len(exempt)}")

    # ФРАГМЕНТОМ СЧИТАЕТСЯ ТОЛЬКО ВЫЖИВШИЙ ПУТЬ. Удалённого файла в голове нет:
    # засчитывать его за принесённую запись значит зеленеть на изменении,
    # которое запись УНЕСЛО, а своей не оставило. Ровно так уборка старого
    # фрагмента пронесла бы мимо гейта любую правку кода.
    try:
        alive = set(journal.changed_files(args.base, alive_only=True, ancestor=ancestor))
    except journal.NotRun as exc:
        print(f"проверка не отработала: {exc}", file=sys.stderr)
        return EXIT_BROKEN
    fragments = [name for name in alive if FRAGMENT_RE.match(name)]

    # СНЯТИЕ, ОСТАВШЕЕСЯ В ЖУРНАЛЕ, НЕ ЕДЕТ НИКУДА. Отметка «Разобрано:» из
    # фрагмента адресату не доходит: уборка читает тело изменения, а его
    # собирает конвейер из тел КОММИТОВ. Замер 17.09.2026 — так потерялись
    # двадцать три снятия за смену.
    try:
        stranded = travelled(args.base, ancestor)
    except NotRun as exc:
        print(f"проверка не отработала: {exc}", file=sys.stderr)
        return EXIT_BROKEN
    if stranded:
        print(
            "снятие находки объявлено фрагментом журнала и не уехало с работой: "
            + ", ".join(stranded)
            + "\n  Отметка «Разобрано: <отпечаток>» обязана стоять в ТЕЛЕ КОММИТА — "
            "оттуда её переносит scripts/agent_pr.py. Во фрагменте она остаётся "
            "рассказом о снятии, а реестр держит находку дальше",
            file=sys.stderr,
        )
        return EXIT_REJECTED

    # ИМЯ ФРАГМЕНТА ГОВОРИТ, ЧТО ИЗМЕНИЛОСЬ, А НЕ КАКАЯ ЗАДАЧА. Одна задача
    # живёт дольше одного изменения, и два захода целятся в одно имя: конфликта
    # это не даёт — побеждает последний, и первая запись исчезает без следа и
    # без выпуска. Так была потеряна запись об исправлении атрибуции (#12).
    # Судится тот же выживший список: у удалённого имени спрашивать нечего.
    by_number = [name for name in fragments if numbered(name)]
    if by_number:
        print(
            "отвергнуто: фрагмент назван номером задачи, а не смыслом: "
            f"{', '.join(by_number)}\n\n"
            "Одна задача живёт дольше одного изменения, и второй заход перезапишет\n"
            "первый молча — конфликта тут не бывает. Имя берётся от того, ЧТО\n"
            "изменилось: changelog.d/README.md.",
            file=sys.stderr,
        )
        return EXIT_REJECTED

    # ПОЧИНКА ПРИНОСИТ ПРОВЕРКУ, ИНАЧЕ ОНА УБИРАЕТ ПОВЕДЕНИЕ, А НЕ ДЕФЕКТ.
    # Правило 014 требует: сначала замер на входе, где гейт зелен, а быть
    # должен красным, потом починка. Доказать дереву САМ замер нечем — гейт
    # видит зелёный набор и не видит, краснел ли он до правки, — и это названо
    # пробелом, а не выровнено (046). Проверяется половина, которая проверяема:
    # починка механизма без единой тронутой проверки не проходит.
    #
    # Замер 09.09.2026 по сорока последним коммитам общей ветки: починок,
    # тронувших механизм, — 15, и все пятнадцать принесли проверку. Гейт
    # закрепляет то, что уже соблюдается, а не вводит новое требование.
    fixing = [name for name in fragments if name.endswith(f".{FIXED}.md")]
    touches_code = [name for name in alive if name.startswith(CODE_PREFIXES)]
    touches_tests = any(name.startswith(TESTS_PREFIX) for name in alive)
    if fixing and touches_code and not touches_tests:
        print(
            "отвергнуто: починка не принесла ни одной проверки.\n\n"
            f"Род записи — «{FIXED}», тронуты механизмы: "
            f"{', '.join(touches_code[:5])}\n\n"
            "Починка доказывается входом, на котором гейт краснел до неё (014): без\n"
            "проверки убирается поведение, а не дефект, и вернуться он может молча.\n"
            "Если проверять нечем — род записи другой, и причина называется в ней.",
            file=sys.stderr,
        )
        return EXIT_REJECTED

    if BUILT_JOURNAL in files:
        print(
            f"отвергнуто: изменение трогает {BUILT_JOURNAL}.\n\n"
            "Собранный журнал — производный файл, и собирает его ВЫПУСК: "
            "`scripts/release.py` уносит фрагменты в `changelog.d/released/` и "
            "пересобирает журнал сам.\n"
            "На изменении его не трогают (030): общий файл, который правит каждая "
            "ветка, даёт конфликт на каждом втором изменении — ровно тот инцидент, "
            "из-за которого фрагменты и заведены.\n\n"
            f"Уберите {BUILT_JOURNAL} из состава: `git checkout origin/<база> -- "
            f"{BUILT_JOURNAL}`. Фрагмент в `changelog.d/` остаётся — он и есть запись.",
            file=sys.stderr,
        )
        return EXIT_REJECTED

    if fragments:
        print(f"фрагмент журнала есть: {', '.join(fragments)}")
        say_if_compound(fragments)
        return EXIT_OK

    substantive = [name for name in files if not name.startswith(EXEMPT_PREFIXES)]
    if not substantive:
        print("изменение тронуло только журнал и производные файлы — фрагмент не нужен")
        return EXIT_OK

    print(
        "отвергнуто: изменение не несёт фрагмента журнала.\n\n"
        "Тронуто файлов вне журнала: "
        f"{len(substantive)}, первые — {', '.join(substantive[:5])}\n\n"
        "Положите changelog.d/<что-изменилось>.<род>.md. Если потребителю это\n"
        "безразлично — род `internal`, и ПЕРВОЙ строкой идёт причина в форме\n"
        "«> **Потребителю безразлично:** …»: молчание состоянием не является\n"
        "(154). Формат — changelog.d/README.md.",
        file=sys.stderr,
    )
    return EXIT_REJECTED


if __name__ == "__main__":
    raise SystemExit(main())
