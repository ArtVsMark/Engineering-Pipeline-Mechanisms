#!/usr/bin/env python3
"""Виды механизмов из выгрузки каталога — один набор на всех, кто их считает.

Ответ проекта каталогу называет ВИД механизма: `gate`, `pipeline` —
исполняемое, и `document` — текст. Разница между ними не косметическая: на ней
стоят разрез приоритета, сводка фактов, дрейф сводки семьи и карта для внешнего
взгляда. Четыре механизма считали её ЧЕТЫРЬМЯ своими копиями одного и того же
множества, причём один под другим именем (`family.KINDS`).

РАСХОЖДЕНИЕ БЫЛО БЫ МОЛЧАЛИВЫМ, и это главное. Каталог добавит пятый вид — и
правка в трёх местах из четырёх выглядит полной: ни один набор не сверяется с
остальными, а числа, которые они печатают, разъедутся без единого красного
([022](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/022-one-canonical-document.md),
[090](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/090-shared-helpers-move-up-not-sideways.md)).
Нашёл внешний взгляд на #120 — и назвал прямо: коммит, заведший четвёртую
копию, сам обосновывал отказ от рукописных списков ссылкой на 090.

ПЯТЫЙ ВИД ПРИШЁЛ 17.09.2026: контракт ответа 1.4 завёл `skill`. Опасение
сбылось буквально — и обошлось дёшево ровно потому, что набор к тому дню лежал
в ОДНОМ месте: правка здесь дошла до всех четверых читателей разом, а не до
трёх из четырёх.
"""

from typing import Final

#: ВИДЫ ДОГОВОРА ОТВЕТА КАТАЛОГА — ЦИТАТА С НАЗВАННОГО ТЕГА (#1566). Виды
#: определяет издатель договора: `answer_form.MECHANISMS` и
#: `answer_form.МАШИННЫЕ` каталога. Снимка его кода в дереве нет, а набор в
#: прогоне в сеть не ходит, поэтому набор процитирован здесь вместе с тегом, на
#: котором снят. Тег сверяется с прибивкой действия каталога в `ci.yml`
#: (`tests/test_kinds.py`): поднял прибивку — перечитай цитату, иначе красное.
CONTRACT_AT: Final = "v2.1.0"
#: Все виды поля `mechanism`; `process-step` — устаревший, но принимаемый.
CONTRACT_KINDS: Final = frozenset({"gate", "pipeline", "skill", "document", "none", "process-step"})
#: Виды, которые договор считает КРАСНЕЮЩИМИ.
CONTRACT_MACHINE: Final = frozenset({"gate", "pipeline"})

#: Виды, которые считаются МЕХАНИЗМОМ, — ровно машинные виды договора.
#: Документ сюда не входит намеренно: его не вынести и не запустить, а
#: «правило держится документом» — это ровно то состояние, которое разрез
#: приоритета и ищет.
#:
#: ВИДА `code` ЗДЕСЬ БОЛЬШЕ НЕТ (#1566). Договор его не знает: у каталога
#: слово `code` — область правил («код»), а не вид механизма, и сюда оно
#: попало при сведении наборов (#120). Числа это не меняло — у нас им не
#: держится ни одно правило (замер 22.10.2026: gate 195, pipeline 17, code 0),
#: — но расхождение с издателем не краснело бы, проявись оно.
MACHINE: Final = CONTRACT_MACHINE

#: УСТАРЕВШИЙ ВИД, КОТОРЫЙ ДОГОВОР ЕЩЁ ПРИНИМАЕТ. «Шаг процесса» называл три
#: разные вещи — проверку конвейера, абзац документа и намерение, — и по замеру
#: каталога 27 из 44 таких ответов не держались ничем. Машинным он не считается:
#: договор не относит его к краснеющим, и у нас им не отвечено ни одно правило.
PROCESS_STEP: Final = "process-step"

#: Вид, который механизмом НЕ является. Назван отдельно, а не выведен
#: вычитанием: список видов у каталога открыт, и «всё, что не машина» завтра
#: включит в себя вид, о котором мы ещё не знаем (068 — перечисляем, а не
#: исключаем).
DOCUMENT: Final = "document"

#: ПЯТЫЙ ВИД, КОТОРОГО МОДУЛЬ И ЖДАЛ. Контракт ответа 1.4 завёл `skill` —
#: навык агента. В `MACHINE` он не входит, и это решение, а не пропуск: навык
#: НЕ КРАСНЕЕТ. Он ничему не отказывает, а срабатывание его есть суждение
#: модели по описанию, а не машинное совпадение, — поэтому место ему между
#: `pipeline` и `document`, а не рядом с гейтом. Доля «машинного соблюдения»,
#: посчитанная с навыком внутри, обещала бы отказ там, где его нет.
#:
#: Сильнее документа он при этом ровно тем, чего у документа нет, — МОМЕНТОМ:
#: свод читается один раз, при старте окна, а навык — в минуту вызова.
#: Порядок «gate → pipeline → skill → document → none» держит каталог, и
#: перечисляем мы его, а не выводим вычитанием (068).
SKILL: Final = "skill"
