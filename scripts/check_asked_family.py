#!/usr/bin/env python3
"""Новый механизм называет, у кого из семьи спросили и что нашли (162, #1440).

ВТОРАЯ ПОЛОВИНА 162. Первую держит ночной прогон «входящих»: по правилу, которое
у нас не держится ничем, он называет соседа и адрес его механизма. Но механизм
строят и по другим поводам — по находке взгляда, разбору чужого проекта, вопросу
владельца, — и тогда вопрос «а у семьи?» не задаёт никто. 16.10.2026 каталог так
прошёл мимо готового трижды за смену: свой прогон подъёма закреплений рядом с
нашим перехватом, гейт интерпретатора хуков, дедлайн подпроцесса у Token.

СПЕРВА СПРОСИЛИ СЕМЬЮ (162). Приём взят у каталога — его гейт
`ArtVsMark/Engineering-Incidents-Playbook:scripts/check_asked_family.py` и навык
`ask-the-family-first`, — ссылкой, а не копией (153). Каталог потом перейдёт на
этот шаг вместо своей копии (решение владельца 17.10.2026, #1440). Своё здесь —
две вещи. Запись судится абзацем, а не строкой: у нас она обычно занимает
абзац, где номер правила стоит в одной строке, а ответ — в следующей. И запись
обязана назвать, что нашли, а не только кого спросили: номер правила рядом со
словом «сосед» — ещё не ответ.

ЧТО СЧИТАЕТСЯ ЗАПИСЬЮ. Абзац текста механизма, в котором есть:

* номер правила 162;
* у кого спрашивали — семья, сосед, каталог или «спросили»;
* что нашли — один из исходов навыка каталога `ask-the-family-first`, и в
  одном предложении с тем, у кого нашли: взяли приём или идею у соседа, у
  соседа только для себя, ни у кого нет, подключили готовое.

ИСХОД СУДИТСЯ СВЯЗЬЮ, А НЕ СЛОВОМ (210). Заходы взгляда на #1490 находили
слово исхода, стоящее в абзаце о семье без всякой связи с соседом: «для себя»
в «шаг пишет отчёт для себя», хвосты «взятие» и «идейный» у открытых корней.
Каждая прежняя починка добавляла словоформу, то есть чинила ту же форму, —
и вторая находка по одному месту стала поводом сменить форму. Теперь взятое и
«только для себя» засчитываются, только когда в том же предложении назван
источник — «у кого»: «приём взят у каталога», «у Token есть, но только для
себя». «Ни у кого» источник несёт в себе, а «подключили» — глагол о готовом
механизме соседа, которого называет уже «у кого спросили». Голые «приём» и
«идея» исходом больше не считаются: «приём у Token свой» не говорит, взяли его
или нет.

ОТВЕТ — РУССКИМИ СЛОВАМИ, И ЭТО СТРОГОЕ ПРАВИЛО, А НЕ ВКУС (навык
`build-a-gate`, шаг 3а). Три захода взгляда на #1490 и #1496 находили, что
английское слово из адреса правила — «neighbours» в ссылке, пути, якоре, слаге —
засчитывалось ответом, и каждая починка разбора адреса рождала следующую форму.
Круг оборван словарём: «у кого» и «что нашли» узнаются только русскими
словоформами, а латиница — адреса, имена, слаги — ответом не бывает вовсе.
Словоформы перечислены, а не открыты корнем: «приёмка», «соседний», «взятие» и
«подключение» ответом не считаются.

ЦЕНУ ЛАТИНИЦЫ ЗАМЕРИЛИ И У СЕМЬИ, А НЕ ТОЛЬКО У СЕБЯ. Шаг отдаётся наружу
(`step-journal.yml`), и каталог перейдёт на него. Замер 18.10.2026 — `recorded`
этого гейта по механизмам их общих веток (`git ls-tree origin/main` выкачки):
у каталога (911bd4b) из 89 механизмов
запись признана у 6, и абзацев с номером 162 по-английски нет ни одного —
латиница рядом с ним стоит только в регулярном выражении его же гейта. У
Usage-Token (52efb3a, 17 механизмов) и грейдера (3b97998, 67) абзацев о 162 нет
вовсе, а `step-journal` не зовёт пока ни один из троих. Английские формы
`family|neighbou?rs?` гейт каталога принимает, но записей ими у него нет.

ПРЕДМЕТ — ТОЛЬКО ДОБАВЛЕННЫЙ МЕХАНИЗМ. Механизм — файл на местах из
`MECHANISMS`, тех же, что у гейта каталога. Прежние механизмы задним числом не
спрашиваются: судить их значило бы краснеть на чужой работе (051).

ГРАНИЦЫ, И ОНИ НАЗВАНЫ.

* Гейт видит, что ответ ЗАПИСАН, а не что он ВЕРЕН: «ни у кого нет» при живом
  механизме соседа он пропустит. Верность судит взгляд.
* Расширение прежнего механизма не видно: путь есть на базе. Переименованный
  механизм тоже не новый. Это держит шаг «Сначала — спросить семью» нашего
  навыка `build-a-gate`; своего навыка о семье у нас нет, и шаг отсылает к
  навыку каталога. Но файл, переехавший на место механизма с другого пути
  (`scripts/foo.py` → `scripts/check_foo.py`), — новый механизм: на базе
  механизмом он не был, и о семье его не спрашивал никто.
* Механизм вне названных мест (скрипт без приставки `check_`) не виден.
* «Каталог» — и каталог правил, и папка дерева, и словом их не различить:
  абзац с номером 162, папкой и найденным ответом пройдёт как запись.
* Связь исхода с источником — предлог «у» в том же предложении, а не разбор
  предложения: «у шага отчёт для себя» пройдёт, хотя шаг — не сосед. Исход без
  глагола — «идея у Token» — не виден: нужно «идею взяли у Token». Предложение
  кончается точкой, «!», «?» или «;» перед пробелом; сокращение «т. е.» его
  тоже кончает.
* Запись по-английски не засчитывается — это цена строгого правила. Замер
  18.10.2026 тем же `recorded` по `MECHANISMS`: из 99 механизмов дерева запись о семье признана у
  11, и все одиннадцать — русские. Прежняя форма признавала те же 11, а у
  каталога — те же 6: смена формы не потеряла ни одной живой записи.

Исходы (правило 039): ``0`` новых механизмов нет или каждый называет семью ·
``1`` новый механизм без записи · ``2`` не отработал — база не разобрана или
файл механизма не прочитан.
"""

import argparse
import re
import sys
from pathlib import Path, PurePosixPath
from typing import Final

import check_new_is_tested as neighbour

EXIT_OK: Final = 0
EXIT_FOUND: Final = 1
EXIT_BROKEN: Final = 2

#: Что считается механизмом — те же места, что у гейта каталога и мета-гейтов
#: (220): гейты, хуки окна, прогоны, действия и навыки.
MECHANISMS: Final = (
    "scripts/check_*.py",
    ".claude/hooks/*.py",
    ".claude/hooks/*.sh",
    ".github/workflows/*.yml",
    ".github/workflows/*.yaml",
    ".github/actions/*/action.yml",
    ".github/actions/*/action.yaml",
    ".claude/skills/*/SKILL.md",
)
#: Номер правила — отдельным числом, а не частью другого. Ищется во всём абзаце,
#: адреса ссылок включительно: голая ссылка на правило — тоже ссылка на 162.
RULE_RE: Final = re.compile(r"(?<!\d)162(?!\d)")
#: У кого спрашивали — ТОЛЬКО РУССКИМИ СЛОВАМИ (строгое правило выше): английское
#: слово из адреса правила ответом не становится ни в какой форме адреса.
#: Словоформы перечислены, а не открыты хвостом `\w*` (правило 210): «соседний»
#: значит «рядом», а не «сосед по семье». Границы слов: «семь» и «семи» —
#: числительные.
ASKED_RE: Final = re.compile(
    r"\b(?:семь[яеюи]|семей|семейств\w*|сосед(?:а|у|ом|е|и|ей|ям|ями|ях)?"
    r"|спросил\w*|спрашивал\w*|каталог\w*)\b",
    re.IGNORECASE,
)
#: Что нашли — исходы навыка каталога `ask-the-family-first`, которым источник
#: нужен рядом: взятое и «для себя». Словоформы перечислены, хвоста нет:
#: «взятие» и «взятка» — не взятое у соседа.
SOURCED_RE: Final = re.compile(
    r"\b(?:взял[аио]?|взяли|взят[аоы]?|для себя)\b",
    re.IGNORECASE,
)
#: Исходы, несущие источник в себе: «ни у кого» и подключённое готовое соседа.
#: «Подключение» — документ потребителя, а не ответ семьи.
WHOLE_RE: Final = re.compile(
    r"\b(?:ни у кого|подключил[аио]?|подключили|подключ[её]н[аоы]?)\b",
    re.IGNORECASE,
)
#: Источник находки — предлог «у» отдельным словом: «взят у каталога».
SOURCE_RE: Final = re.compile(r"\bу\b", re.IGNORECASE)
#: Конец предложения: связь исхода с источником судится внутри него.
SENTENCE_END_RE: Final = re.compile(r"(?<=[.!?;])\s+")
#: Навык каталога о том, как спросить семью, — полным адресом: гейт уезжает к
#: потребителям шагом `step-journal`, и путь в нашем дереве у них не разрешится.
ASK_SKILL: Final = (
    "https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/"
    ".claude/skills/ask-the-family-first/SKILL.md"
)
#: Знаки комментария в начале строки: абзац комментария делится такой же
#: «пустой» строкой, что и абзац прозы.
COMMENT_MARKS: Final = "#/;"


def paragraphs(text: str) -> list[str]:
    """Абзацы текста; строка из одних знаков комментария их делит, как пустая."""
    found: list[str] = []
    current: list[str] = []
    for line in text.splitlines():
        bare = line.strip().lstrip(COMMENT_MARKS).strip()
        if bare:
            current.append(bare)
        elif current:
            found.append(" ".join(current))
            current = []
    if current:
        found.append(" ".join(current))
    return found


def found(paragraph: str) -> bool:
    """В одном предложении абзаца назван исход вместе с тем, у кого его нашли."""
    return any(
        WHOLE_RE.search(one) or (SOURCED_RE.search(one) and SOURCE_RE.search(one))
        for one in SENTENCE_END_RE.split(paragraph)
    )


def recorded(text: str) -> bool:
    """Есть абзац, где названы правило 162, у кого спросили и что нашли."""
    return any(
        RULE_RE.search(one) and ASKED_RE.search(one) and found(one) for one in paragraphs(text)
    )


def is_mechanism(path: str) -> bool:
    """Путь лежит на одном из мест механизма."""
    return any(PurePosixPath(path).full_match(one) for one in MECHANISMS)


def added_mechanisms(base: str) -> list[str]:
    """Механизмы, которые изменение ДОБАВИЛО, — и пришедшие на место механизма переездом.

    Переименованный механизм и правленый — не новые. Файл, переехавший с
    немеханизменного пути, механизмом на базе не был — он новый (взгляд на #1490).
    """
    return sorted(
        path
        for state, path, was in neighbour.changes(base)
        if is_mechanism(path) and (state == "A" or (state == "R" and not is_mechanism(was)))
    )


def silent(paths: list[str], root: Path) -> list[str]:
    """Добавленные механизмы, в тексте которых записи о семье нет."""
    quiet: list[str] = []
    for one in paths:
        try:
            text = (root / one).read_text(encoding="utf-8")
        except (OSError, UnicodeDecodeError) as exc:
            raise neighbour.NotRun(f"механизм {one} не прочитан: {exc}") from exc
        if not recorded(text):
            quiet.append(one)
    return quiet


def main(argv: list[str] | None = None) -> int:
    """Точка входа: судит механизмы, добавленные изменением."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--base", default="", help="общая ветка; по умолчанию — origin/main")
    args = parser.parse_args(argv)
    try:
        added = added_mechanisms(args.base or neighbour.base_ref())
        quiet = silent(added, Path())
    except neighbour.NotRun as exc:
        print(f"проверка не отработала: {exc}", file=sys.stderr)
        return EXIT_BROKEN
    if not added:
        print("новых механизмов в изменении нет — спрашивать семью не о чем")
        return EXIT_OK
    if quiet:
        print("новый механизм не называет, у кого из семьи спросили и что нашли (162):")
        for one in quiet:
            print(f"  {one}")
        print(
            "\nЗапишите в описании механизма абзац с номером 162 — русскими словами: "
            "латиница (адрес, путь, слаг) ответом не считается. В абзаце — у кого "
            "спросили (семья, сосед или каталог) и что нашли, в одном предложении с "
            "тем, у кого: «приём взят у каталога», «у соседа только для себя», "
            "«ни у кого нет» или «подключили готовое». Как спросить — навык каталога "
            f"ask-the-family-first: {ASK_SKILL}"
        )
        return EXIT_FOUND
    print(f"новые механизмы называют семью: {len(added)}")
    return EXIT_OK


if __name__ == "__main__":
    raise SystemExit(main())
