"""Форма документов проверяется там, где её читает не только человек.

Документы этого проекта читает окно — целиком, текстом, без интерфейса
площадки. Всё, что в интерфейсе разворачивается кликом, для такого читателя
остаётся заголовком без содержимого, и пропажа выглядит как пустой раздел, а не
как скрытый (008).
"""

from __future__ import annotations

import re
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parent.parent
DOCS = sorted(
    [
        *ROOT.glob("*.md"),
        *(ROOT / "docs").rglob("*.md"),
        *(ROOT / ".github").rglob("*.md"),
        *(ROOT / "changelog.d").rglob("*.md"),
    ]
)

#: Сворачиваемый блок: содержимое видит только тот, кто кликнул.
COLLAPSED_RE = re.compile(r"<details\b|<summary\b", re.I)


def test_there_are_documents_to_check() -> None:
    """Предмет проверки найден: иначе гейт зелен на пустом списке (075)."""
    assert DOCS, "в дереве не нашлось ни одного документа — проверять нечего"


@pytest.mark.parametrize("path", DOCS, ids=lambda p: p.as_posix())
def test_no_collapsed_blocks(path: Path) -> None:
    """Сворачиваемых блоков в документах нет: раскрывайте или не пишите (008)."""
    text = path.read_text(encoding="utf-8")
    hits = [
        f"{number}: {line.strip()}"
        for number, line in enumerate(text.splitlines(), start=1)
        if COLLAPSED_RE.search(line)
    ]
    assert not hits, f"{path.as_posix()}: сворачиваемый блок читается как обрубок: {hits}"


#: Числительные, которыми в договоре записан размер скелета. Прозой, а не
#: цифрой: заголовок читает человек. Отсюда и гейт — число прописью устаревает
#: ровно так же молча, как цифрой (005).
SPELLED = {
    10: "десяти",
    11: "одиннадцати",
    12: "двенадцати",
    13: "тринадцати",
    14: "четырнадцати",
    15: "пятнадцати",
    16: "шестнадцати",
    17: "семнадцати",
    18: "восемнадцати",
}
SPELLED_STEPS = {
    12: "двенадцать",
    13: "тринадцать",
    14: "четырнадцать",
    15: "пятнадцать",
    16: "шестнадцать",
    17: "семнадцать",
    18: "восемнадцать",
    19: "девятнадцать",
    20: "двадцать",
}
STEP_ROW_RE = re.compile(r"^\|\s*(?P<step>\d+)[a-zа-я]?\s*\|")
STEP_FILE_RE = re.compile(r"`(?P<file>[\w.-]+\.yml)`")


def test_the_skeleton_heading_matches_its_own_table() -> None:
    """Заголовок договора называет столько шагов, сколько в таблице под ним.

    Замер 10.09.2026: заголовок говорил «четырнадцать шагов в десяти файлах»,
    когда в таблице было шестнадцать в тринадцати. Число, вписанное в прозу
    руками, устаревает молча (005) — поэтому его сверяет гейт, а не читатель.
    """
    text = (ROOT / "docs" / "pipeline.md").read_text(encoding="utf-8")
    steps: set[int] = set()
    files: set[str] = set()
    for line in text.splitlines():
        row = STEP_ROW_RE.match(line)
        if not row:
            continue
        steps.add(int(row.group("step")))
        cells = [cell.strip() for cell in line.strip("|").split("|")]
        files.update(found.group("file") for found in STEP_FILE_RE.finditer(cells[2]))
    assert steps and files, "таблица шагов не разобралась — гейту не с чем сверять"
    heading = next(line for line in text.splitlines() if line.startswith("## Скелет:"))
    assert SPELLED_STEPS[len(steps)] in heading.lower(), f"{heading}: шагов в таблице {len(steps)}"
    assert SPELLED[len(files)] in heading.lower(), f"{heading}: файлов в таблице {len(files)}"


#: Строка таблицы без номера шага: `| — | выпуск | release.yml | … |`. Такая в
#: счёт заголовка не входит, и читатель, считающий строки глазами, получит на
#: единицу больше.
UNNUMBERED_ROW_RE = re.compile(r"^\|\s*[—-]\s*\|")


def test_an_unnumbered_row_is_named_under_the_heading() -> None:
    """Строка без номера названа прозой, иначе счёт заголовка спорит с глазами.

    Заголовок считает НОМЕРОВАННЫЕ строки; читатель считает все. Расхождение
    на единицу выглядит устаревшим числом, и внешний взгляд прочёл его именно
    так на #199 — «четырнадцать не совпадает с пятнадцатью файлами дерева».
    Разницу называет проза под заголовком, а не догадка (046).
    """
    text = (ROOT / "docs" / "pipeline.md").read_text(encoding="utf-8")
    lines = text.splitlines()
    place = next(n for n, line in enumerate(lines) if line.startswith("## Скелет:"))
    table = lines[place:]
    unnumbered = [line for line in table if UNNUMBERED_ROW_RE.match(line)]
    if not unnumbered:
        return
    said = "\n".join(lines[place : place + 8])
    assert "без номера" in said, (
        f"в таблице {len(unnumbered)} строк без номера, а проза под заголовком о них молчит"
    )


#: Сколько первых строк документа читается в поисках читателя. Не весь файл:
#: объявление, стоящее в середине, читателю не поможет — он до него не дойдёт.
READER_HEAD = 12
#: Строка объявления. Форма взята у соседей по семье, где правило уже держится
#: машиной: расходящиеся формы стоили бы переноса гейта (162, 090).
READER_MARK = "Читатель:"
#: Документы, у которых читателя нет по построению: их читает механизм, а не
#: человек. Список закрытый и каждый назван с причиной — иначе он станет местом,
#: куда сваливают всё, что лень объявить (154).
WITHOUT_READER = {
    "CHANGELOG.md": "производное: собирается из фрагментов сборкой",
}


@pytest.mark.parametrize(
    "path",
    sorted(p for p in DOCS if "changelog.d" not in p.parts and p.name not in WITHOUT_READER),
    ids=lambda p: str(p.relative_to(ROOT)),
)
def test_every_document_declares_its_reader(path: Path) -> None:
    """У документа объявлен читатель, и объявлен в его начале.

    Документ без названного читателя пишется «вообще» и потому не годится
    никому: свод агента и витрина посетителя отвечают на разные вопросы, и
    смешавшись, перестают отвечать на оба.

    Правило держалось вниманием: все тринадцать документов проекта читателя уже
    называли, но ничто не мешало четырнадцатому его не назвать. Гейт перенесён
    от соседей — у троих из пяти он уже стоит машиной (162).
    """
    head = "\n".join(path.read_text(encoding="utf-8").splitlines()[:READER_HEAD])
    assert READER_MARK in head, (
        f"{path.relative_to(ROOT)}: читатель не объявлен в первых {READER_HEAD} строках"
    )


def test_the_reader_gate_found_its_subject() -> None:
    """Гейт читателя проверяет не пустоту: документы в дереве есть (075)."""
    subject = [p for p in DOCS if "changelog.d" not in p.parts and p.name not in WITHOUT_READER]
    assert len(subject) > 5, "предмет проверки не найден — гейт проходит вхолостую"


#: Витрина: документ, который читает пришедший и ещё не решивший.
STOREFRONT = ROOT / "README.md"

#: Предел витрины в СЛОВАХ ПРОЗЫ, а не в строках и не в знаках. Строка — это
#: перенос, то есть форматирование: гейт по строкам краснел бы от переливки
#: абзацев, не изменившей ни слова, и приучил бы обходить себя переносами (051).
#:
#: ЧИСЛО ПЕРЕВЕДЕНО ИЗ САМОГО ПРАВИЛА, А НЕ ВЗЯТО ИЗ ДОСТИГНУТОГО. «Первые пять
#: минут» при 200 словах в минуту — тысяча слов. Храповика «не выше, чем
#: сегодня» здесь нет намеренно: витрине законно расти, пока она остаётся
#: витриной, и порог, приколоченный к текущему замеру, отвергал бы законное.
STOREFRONT_WORDS = 1000

#: Адрес ссылки словами не считается: его не читают. Убирается ВМЕСТЕ с
#: разделителем — иначе «текст](адрес)» слипается в одно слово, и витрина
#: кажется короче, чем она есть.
ADDRESS_RE = re.compile(r"\]\([^)]*\)")
BARE_LINK_RE = re.compile(r"https?://\S+")


def prose_words(text: str) -> int:
    """Сколько слов в документе читает человек: без адресов ссылок."""
    return len(BARE_LINK_RE.sub(" ", ADDRESS_RE.sub("] ", text)).split())


#: Свод агента: документ, который окно читает ЦЕЛИКОМ и при каждом старте.
MAIN_FILE = ROOT / "AGENTS.md"

#: Предел свода в словах прозы. Объём главного файла — НАЛОГ НА ЛЮБУЮ РАБОТУ:
#: он платится каждым окном при старте, а используется по частям и редко
#: ([029](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/029-triggers-and-canon.md)).
#:
#: ЧИСЛО ВЗЯТО ИЗ РЯДА, А НЕ ИЗ ПРАВИЛА — в отличие от витрины, которой правило
#: само назначает пять минут. Замер 13.09.2026 по 47 правкам свода: 985 → 1068
#: → 1237 → 1519 → 1808 → 2185 слов за четыре дня, то есть рост вдвое и ни
#: одного отката. Сам себя он не остановит, и предел здесь — потолок налога, а
#: не оценка качества текста.
#:
#: ЗАПАС НАМЕРЕННО МАЛ: около абзаца. Добавка крупнее требует вынести
#: равнозначное в канон — ровно того разговора, который правило и просит.
#: Двигать предел вверх можно, но это решение с ценой, а не правка числа (050).
MAIN_FILE_WORDS = 2300


def test_the_main_file_stays_a_trigger() -> None:
    """Свод не перерастает своего назначения: триггер, а не канон.

    РЕГРЕСС ЗДЕСЬ НЕИЗБЕЖЕН И НАЗВАН САМИМ ПРАВИЛОМ: «разрастание входного
    файла — повод переспросить, триггер это или канон». Каждая правка кажется
    уместной по отдельности, а вместе они удваивают налог на старт.

    ЧТО ГЕЙТ НЕ СУДИТ: что именно вынести. Критерий деления — «нужно, чтобы не
    сделать ошибку прямо сейчас» против «нужно, когда уже занимаешься
    предметно» — это суждение о читателе, и оно остаётся автору
    ([195](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/195-a-narrowed-predicate-names-its-neighbour.md)).
    """
    said = prose_words(MAIN_FILE.read_text(encoding="utf-8"))
    assert said <= MAIN_FILE_WORDS, (
        f"свод вырос до {said} слов при пределе {MAIN_FILE_WORDS}: его читают целиком и при "
        "каждом старте, и объём здесь — налог на любую работу. Вынесите подробности в канон "
        "(docs/) и оставьте триггер — то, что нужно знать, чтобы не сделать ошибку прямо "
        "сейчас (029)"
    )


def test_the_main_file_sends_the_reader_to_the_canon() -> None:
    """У свода есть врезка, отсылающая к канону, и она не пуста.

    Приписка «детали не дублировать здесь» — не вежливость, а защита от
    регресса: без неё следующий автор вернёт подробность обратно из лучших
    побуждений. Проверяется наличие отсылки, а не её формулировка: судить
    слова значило бы судить стиль.
    """
    text = MAIN_FILE.read_text(encoding="utf-8")
    ведёт = [line for line in text.splitlines() if "docs/" in line and "](" in line]
    assert len(ведёт) >= 3, (
        f"свод ссылается на канон {len(ведёт)} раз: главный файл отвечает «надо ли мне туда "
        "идти», а «как именно» живёт в специальном документе (029)"
    )


#: Свод окна: второй документ, который читают ЦЕЛИКОМ и при каждом старте.
#: `CLAUDE.md` сам называет порядок — «первое, что читает новое окно, —
#: AGENTS.md, затем этот файл», — то есть налог на старт платится дважды, а
#: потолок стоял только у одной половины.
WINDOW_FILE = ROOT / "CLAUDE.md"

#: Предел свода окна в словах прозы. Довод тот же, что у главного файла (029),
#: и сложение — тоже: 2300 + 900 = 3200 слов, которые окно читает, ещё не начав
#: работу. Число взято из РЯДА: замер 14.09.2026 по истории общей ветки дал
#: 756 → 756 → 756 → 756 → 756 → 828 слов за шесть дней — рост медленнее, чем у
#: главного файла, но без единого отката, как и у всех документов проекта.
#: Запас, как и там, около абзаца: добавка крупнее требует вынести равнозначное
#: в ядро или канон, а не растить налог молча. Двигать предел вверх можно, но
#: это решение с ценой, а не правка числа (050).
WINDOW_FILE_WORDS = 900

#: ГДЕ ПРЕДЕЛА НЕТ НАМЕРЕННО, И ЭТО НЕ ЗАБЫТО. Потолок стоит у того, что читают
#: ЦЕЛИКОМ И ВСЕГДА: витрина, ядро, свод окна. У канона (`docs/`) его нет —
#: канон читают по надобности и частями, рост там не означает поломки, а гейт,
#: краснеющий на законном, учат обходить
#: ([051](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/051-warn-on-likely-block-on-certain.md)).
#: Регресс канона держит другое: деление по читателю (021) и один канонический
#: документ на вопрос (022). У записей решений предела нет по прямому запрету:
#: запись — датированный факт, и сокращать её нельзя вовсе (043). Замер
#: 14.09.2026 называет цену этой границы: `docs/pipeline.md` 2062 → 3178 слов за
#: шесть дней, `docs/release.md` 855 → 2290, и ни один документ проекта ни разу
#: не убыл. То есть граница названа, а не выдана за отсутствие предмета (046).
UNCAPPED = ("docs/", "docs/decisions/")


def test_the_window_file_stays_a_trigger() -> None:
    """Свод окна не перерастает своего назначения — по тому же доводу (029).

    НАЛОГ НА СТАРТ ПЛАТИТСЯ ДВАЖДЫ, а потолок стоял у одной половины: окно
    читает ядро, затем свод окна, и до этого гейта вторая половина могла расти
    сколько угодно. Предмет здесь не «длинный документ», а НАЛОГ: он платится
    каждым окном и до всякой работы.

    ЧТО ГЕЙТ НЕ СУДИТ — что именно вынести: критерий деления есть суждение о
    читателе и остаётся автору (195).
    """
    said = prose_words(WINDOW_FILE.read_text(encoding="utf-8"))
    assert said <= WINDOW_FILE_WORDS, (
        f"свод окна вырос до {said} слов при пределе {WINDOW_FILE_WORDS}: его читают целиком "
        "и при каждом старте, сразу после ядра. Вынесите подробности в ядро (AGENTS.md) или "
        "канон (docs/) и оставьте то, что верно ТОЛЬКО для этого окна (029, 021)"
    )


#: ПОТОЛОК НАЛОГА НА СТАРТ — СВОЙ, А НЕ СУММА ЧАСТЕЙ. Первая редакция ставила
#: сюда 2300 + 900 и покраснеть не могла: превысить сумму, не превысив ни одной
#: части, арифметически невозможно, и «защита суммы» существовала только на
#: словах. Нашёл внешний взгляд на #351 (`18823c0`); гейт, который не может
#: найти ничего, обязан считаться поломкой, а не зеленью
#: ([075](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/075-a-guard-that-finds-nothing-must-fail.md)).
#:
#: ЧИСЛО МЕНЬШЕ СУММЫ — И ЭТО СМЫСЛ, А НЕ ПРИЁМ. Налог платит читатель, а не
#: файл: ему всё равно, в каком из двух документов лежат слова. Потолок ниже
#: суммы частей означает, что запас у них ОБЩИЙ: одна половина вправе занять
#: свободное у другой, но обе разом — нет. Пределы частей при этом остаются:
#: они держат перекос, когда один документ съедает весь общий запас.
#:
#: Замер 15.09.2026: ядро 2231 слова, свод окна 828 — налог 3059 при потолке
#: 3150, запас около абзаца, как и у частей. Двигать вверх можно, но это
#: решение с ценой, а не правка числа (050).
START_TAX_WORDS = 3150


def over_tax(core: int, window: int) -> bool:
    """Превышен ли налог на старт такими объёмами половин.

    Предикат один на живой замер и на прогон отказа: две записи того же
    сравнения разошлись бы молча, и отказ проверял бы не тот вопрос (090).
    """
    return core + window > START_TAX_WORDS


def start_tax() -> tuple[int, int]:
    """Объёмы половин налога: ядро и свод окна, в словах прозы."""
    return (
        prose_words(MAIN_FILE.read_text(encoding="utf-8")),
        prose_words(WINDOW_FILE.read_text(encoding="utf-8")),
    )


def test_the_start_tax_is_held_as_a_whole() -> None:
    """У налога на старт свой потолок, ниже суммы частей.

    Порознь каждый предел выглядит скромным, а читают оба подряд: без общего
    потолка «поднять на сотню» дважды звучит одинаково дёшево, а платит за это
    каждое окно.
    """
    core, window = start_tax()
    assert not over_tax(core, window), (
        f"налог на старт вырос до {core + window} слов при потолке {START_TAX_WORDS}: это ядро"
        " и свод окна вместе, и читает их каждое окно до всякой работы. Общий запас кончился —"
        " выносите равнозначное в канон (029), а не поднимайте потолок"
    )


def test_the_start_tax_can_go_red_on_its_own() -> None:
    """Потолок налога отвергает то, что части по отдельности пропускают (140).

    Это и есть предмет находки `18823c0`: пока потолок равнялся сумме частей,
    покраснеть он не мог НИ ПРИ КАКОМ входе — превысить сумму, не превысив ни
    одной части, арифметически невозможно. Зелёное такого гейта означало лишь,
    что предикат не умеет краснеть (075).
    """
    красный = (MAIN_FILE_WORDS, WINDOW_FILE_WORDS)
    assert красный[0] <= MAIN_FILE_WORDS and красный[1] <= WINDOW_FILE_WORDS, (
        "обе половины на своих пределах, то есть по частям такой вход зелен"
    )
    assert over_tax(*красный), "а по сумме он красен — иначе общего запаса не существует"
    assert not over_tax(*start_tax()), "сегодняшний замер при этом зелен"


def test_the_window_file_limit_rejects_what_it_must() -> None:
    """Предел свода окна отвергает переросший документ, а не оформление (140)."""
    assert prose_words("слово " * (WINDOW_FILE_WORDS + 1)) > WINDOW_FILE_WORDS
    один = "[правило](https://example.com/очень/длинный/адрес) и слово"
    assert prose_words(один) == 3, "адрес ссылки в налог не входит, её текст — входит"


