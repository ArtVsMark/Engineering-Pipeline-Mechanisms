#: Аннотация прогона: строка, которую площадка отдаёт по REST.
#:
#: МЕТКА `case` ПЕРЕД `echo` — ЧАСТЬ ФОРМЫ, А НЕ ИСКЛЮЧЕНИЕ. Первая редакция
#: требовала `echo` в начале строки и потому не видела `3) echo "::warning::…"`.
#: Дыра была не теоретической: под ней спокойно жила аннотация «см. вывод шага»
#: — ровно то, что этот гейт и запрещает. Нашлось, когда соседний разбор привёл
#: к тому же шагу (075).
ANNOTATES: Final = re.compile(
    r'^\s*(?:[^\s()]+\)\s*)?echo\s+"::(?:error|warning)::(?P<said>.*)"\s*(?:;;)?\s*$'
)

#: Тупик вместо причины. Строка названа дословно, потому что она и есть предмет:
#: «смотрите вывод» отправляет читателя туда, куда часть окон не смотрит вовсе.
DEAD_END: Final = ("смотрите вывод", "смотрите лог", "см. вывод")

#: Чем причина попадает в аннотацию: подстановкой оболочки.
CARRIES: Final = ("${reason}", "$(tr", "${said}")

#: Сколько текста обязано идти ПОСЛЕ кода. Мера именно такая, а не «длина
#: сообщения»: описание того, ЧТО упало, стоит в сообщении всегда — оно есть и у
#: негодного «Шаг разбора красноты не отработал (код 2).». Отличает годное от
#: негодного то, продолжается ли сообщение за кодом: там живёт следствие («взгляд
#: пойдёт без неё», «покрытие будет объявлено непрочитанным»). Первая редакция
#: мерила длину целиком, ничего не отвергала и была гейтом без предмета (075).
AFTER_THE_CODE: Final = 20

#: Сам код в сообщении — по нему и режут.
THE_CODE: Final = re.compile(r"\(код \$\{?rc\}?\)")


def annotated() -> list[tuple[str, int, str]]:
    """Все аннотации прогонов дерева: файл, строка, текст."""
    found: list[tuple[str, int, str]] = []
    for path in sorted((ROOT / ".github" / "workflows").glob("*.yml")):
        for number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
            said = ANNOTATES.match(line)
            if said:
                found.append((path.name, number, said["said"]))
    return found


#: Шаг вычислил причину: вывод шага, сложенный в одну строку.
COMPUTES: Final = re.compile(r'^\s*reason="\$\(tr\b')
#: …и подставил её куда-нибудь.
SUBSTITUTES: Final = "${reason}"


def blocks() -> list[tuple[str, int, list[str]]]:
    """Тела шагов `run:` прогонов дерева: файл, строка начала, строки тела.

    Границей взят отступ: тело блока идёт глубже строки `run:`, и первая
    строка с отступом не глубже — уже сосед. Разбирать YAML ради этого нечем:
    тело блока — текст оболочки, и именно как текст его и читают соседние
    проверки этого файла.
    """
    found: list[tuple[str, int, list[str]]] = []
    for path in sorted((ROOT / ".github" / "workflows").glob("*.yml")):
        lines = path.read_text(encoding="utf-8").splitlines()
        for number, line in enumerate(lines, 1):
            head = re.match(r"^(\s*)-?\s*run:\s*\|", line)
            if not head:
                continue
            deep = len(head.group(1))
            body: list[str] = []
            for below in lines[number:]:
                if below.strip() and len(below) - len(below.lstrip()) <= deep:
                    break
                body.append(below)
            found.append((path.name, number, body))
    return found


def test_the_tree_has_run_blocks_to_look_at() -> None:
    """Блоки найдены: без них проверка ниже — поверхность без предмета (075)."""
    assert len(blocks()) >= 20, f"блоков `run:` найдено {len(blocks())} — разбор их не видит"


@pytest.mark.parametrize(
    "block",
    blocks(),
    ids=lambda one: f"{one[0]}:{one[1]}" if isinstance(one, tuple) else str(one),
)
def test_a_computed_reason_is_substituted(block: tuple[str, int, list[str]]) -> None:
    """Шаг, вычисливший причину, обязан её подставить.

    ПОЧЕМУ ЭТО НЕ ПРИДИРКА К МЁРТВОЙ ПЕРЕМЕННОЙ. Рядом с вычислением стоит
    пояснение «причина едет в аннотацию, а не остаётся в логе», и пока
    подстановки нет, ПОЯСНЕНИЕ ЛЖЁТ: читатель верит, что причина доедет, и не
    ищет её в логе — которого из части окон не видно вовсе (142). Соседний
    гейт этого не берёт намеренно: он принимает и СЛЕДСТВИЕ словами, а
    следствие здесь как раз было написано.

    ЗАМЕР 16.09.2026 ПО ВСЕМУ ДЕРЕВУ, а не по найденному случаю: причину
    вычисляют одиннадцать шагов в девяти прогонах, и ровно один её не
    подставлял — `automerge.yml`, шаг записи слитого без взгляда. Нашёл
    внешний взгляд находкой `08d2f71` на #383.
    """
    name, number, body = block
    if not any(COMPUTES.match(line) for line in body):
        pytest.skip("шаг не вычисляет причину")
    assert any(SUBSTITUTES in line for line in body), (
        f"{name}:{number}: шаг сложил вывод в `reason`, но никуда его не подставил — "
        "пояснение обещает причину в аннотации, а её там нет (142)"
    )


#: Ветка «всё прочее» разбора кода возврата: она и есть отказ (068).
OTHERWISE: Final = re.compile(r"^\s*\*\)")


def otherwise_of(body: list[str]) -> list[str]:
    """Ветка отказа шага: от «*)» до конца случая. Пусто — ветки нет.

    ЗАКРЫТИЕ ПРОВЕРЯЕТСЯ И НА ПЕРВОЙ СТРОКЕ. Ветка обычно однострочная —
    `*) echo "…" ;;`, — и прежняя редакция пропускала `;;` ровно на той строке,
    где его находила: `continue` уносил разбор дальше, и ветка «дочитывалась» до
    следующего `;;`, то есть до СОСЕДА.

    ЗАМЕР 16.09.2026: из двенадцати ветвей семь однострочные, и каждая
    захватывала одну-две чужие строки. Гейт при этом был зелен — причина в
    первой строке и так стояла, — но зелен он был на РАСШИРЕННОМ отрезке: та же
    проверка приняла бы причину, подставленную у соседа. Нашёл внешний взгляд
    находкой `757c1a6` на #397
    ([075](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/075-a-guard-that-finds-nothing-must-fail.md)).
    """
    branch: list[str] = []
    for line in body:
        if not branch and not OTHERWISE.match(line):
            continue
        branch.append(line)
        if ";;" in line:
            break
    return branch


def test_a_one_line_branch_does_not_swallow_its_neighbour() -> None:
    """Однострочная ветка отказа кончается на своей строке, а не у соседа.

    Ветка обычно однострочная, и разбор пропускал `;;` ровно там, где его
    находил: ветка «дочитывалась» до следующего `;;` — то есть до соседней. Гейт
    при этом оставался зелёным по существу, но судил РАСШИРЕННЫЙ отрезок: он
    принял бы причину, подставленную у соседа, за свою. Замер 16.09.2026: из
    двенадцати ветвей семь однострочные, и каждая захватывала одну-две чужие
    строки. Нашёл внешний взгляд находкой `757c1a6`.

    Это риск, а не дефект: ложного зелёного в дереве не было — причина стояла в
    первой же строке каждой ветки. Проверяется он подделкой, потому что
    настоящего случая ещё нет (140).
    """
    body = [
        '            0) echo "чисто" ;;',
        '            *) echo "::warning::не отработал (код $rc)" ;;',
        '            3) echo "часть не прочитана: ${reason}" ;;',
        "          esac",
    ]
    branch = otherwise_of(body)
    assert len(branch) == 1, f"ветка прочитана длиной {len(branch)}: {branch}"
    assert SUBSTITUTES not in "\n".join(branch), "причина соседа принята за свою"


def test_a_multiline_branch_is_read_to_its_end() -> None:
    """Многострочная ветка читается целиком: обрыв на первой строке терял бы причину.

    Обе половины нужны разом. Первая редакция ошибалась в одну сторону, а
    починка «обрывать на первой строке» ошиблась бы в другую — и цена второй
    ошибки выше: причина уехала бы из-под гейта вместе с концом ветки.
    """
    body = [
        "            *)",
        '              echo "::warning::не отработал (код $rc): ${reason}"',
        "              exit 0",
        "              ;;",
        "          esac",
    ]
    branch = otherwise_of(body)
    assert len(branch) == 4, f"ветка прочитана длиной {len(branch)}: {branch}"
    assert any(SUBSTITUTES in line for line in branch), "причина потеряна вместе с концом ветки"


@pytest.mark.parametrize(
    "block",
    blocks(),
    ids=lambda one: f"{one[0]}:{one[1]}" if isinstance(one, tuple) else str(one),
)
def test_the_failing_branch_names_the_reason(block: tuple[str, int, list[str]]) -> None:
    """Ветка ОТКАЗА несёт причину, а не только объявленный исход.

    Соседний гейт требует, чтобы вычисленная причина была подставлена хоть
    куда-нибудь, — и этого мало. Причину подставляли в ветку объявленного
    третьего исхода, а ветка отказа выходила кодом, не сказав наружу ничего:
    шаг падал молча, хотя причина лежала вычисленной строкой выше.

    ОТКАЗ — ХУДШИЙ МОМЕНТ ДЛЯ МОЛЧАНИЯ. Объявленный исход читатель и так
    понимает по слову рядом; отказ — это ровно тот случай, когда нужно знать,
    ЧТО именно не получилось, и именно тогда лог из части окон не читается
    ([142](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/142-a-scheduled-red-needs-an-addressee.md)).

    ЗАМЕР 16.09.2026 ПО ВСЕМУ ДЕРЕВУ: причину вычисляют одиннадцать шагов, и
    ровно один ронял её в отказе — шаг остатка долга в `ci.yml`. В тот же день
    он и упал на голове `229fb95`: общая ветка встала красной, а почему —
    неизвестно до сих пор, разбирать нечего.
    """
    name, number, body = block
    if not any(COMPUTES.match(line) for line in body):
        pytest.skip("шаг не вычисляет причину")
    branch = otherwise_of(body)
    if not branch:
        pytest.skip("у шага нет ветки отказа — разбирать нечего")
    assert any(SUBSTITUTES in line for line in branch), (
        f"{name}:{number}: ветка отказа выходит, не назвав причину, — а причина "
        "вычислена строкой выше. Снаружи такой отказ неотличим от любого другого (142)"
    )


