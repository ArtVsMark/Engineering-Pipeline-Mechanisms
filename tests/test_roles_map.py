#: Слот после слова «профиль» отвечает на «ЧЕЙ» — и только. Предел, вход и
#: граница профиля живут в обосновании справа: слот на два вопроса читается как
#: слот на один, и машине различить их нечем. Нашёл внешний взгляд на #403.
#:
#: ОБРАЗЦА «ЧЕЙ» ЗДЕСЬ НЕТ, И ЭТО НАЗВАНО, А НЕ УМОЛЧАНО. Рядом жил
#: `WHOSE_PROFILE = r"^профиль(?:\s+[\w\s]+)?$"`, объявленный и НЕ ЗВАННЫЙ
#: ниоткуда; проверку нёс один список ниже. Хуже, чем мёртвый код: образец и не
#: решал бы задачу — прогнанный по живым строкам, он признаёт «чьим» и «профиль
#: каталога», и «профиль с названным пределом», потому что `[\w\s]+` покрывает
#: оба. Объявление обещало разбор, которого не было ни в вызовах, ни в самом
#: образце (нашёл внешний взгляд на #437).
#:
#: «Чей» отличается от «какой» СМЫСЛОМ хвоста, а не его формой, и признака по
#: форме тут нет. Поэтому механизм — перечень того, что уже пробовали вписать:
#: он не решает вопрос вообще, а отвергает известные промахи, и граница его
#: названа здесь (068, 154).
#: Слова, которыми хвост отвечает НЕ на «чей». Список разрешительный наоборот —
#: он перечисляет ровно то, что уже пробовали вписать.
NOT_A_WHOSE: Final = ("с названным", "с объявленным", "с оговоркой", "но ", "при ")


def test_a_profile_tail_says_whose_and_nothing_else() -> None:
    """Хвост у «профиля» отвечает на «чей», а не на «с какой оговоркой».

    Слот один, а вопросов в него вписывали два: «профиль каталога» — чей, и
    «профиль с названным пределом» — какой. Второе не даёт сравнить строки между
    собой и делает исход непроверяемым: список исходов закрытый ровно затем,
    чтобы по нему можно было считать (068).
    """
    wrong = [
        f"{direction}: «{outcome}»"
        for direction, (outcome, _) in rows().items()
        if outcome.startswith("профиль") and any(one in outcome for one in NOT_A_WHOSE)
    ]
    assert not wrong, (
        "хвост профиля отвечает не на «чей»: " + "; ".join(wrong) + " — предел и "
        "граница профиля живут в обосновании, а не в слоте исхода"
    )


def test_the_known_misses_are_actually_refused() -> None:
    """Перечень промахов прогнан тем, что обязан отвергать, — и тем, что нет.

    Список — единственное, чем держится слот: признака «чей» по ФОРМЕ хвоста не
    существует. Значит проверять надо сам список, иначе он неотличим от
    объявления намерения — как и снятый отсюда образец, который не звали ниоткуда
    и который признал бы «чьим» всё подряд (075, 139).
    """
    refused = [
        "профиль с названным пределом",
        "профиль с объявленным входом",
        "профиль с оговоркой",
        "профиль каталога, но без границы",
        "профиль при условии",
    ]
    for said in refused:
        assert any(one in said for one in NOT_A_WHOSE), f"промах не отвергнут: «{said}»"
    for said in ("профиль каталога", "профиль внешнего взгляда", "профиль владельца"):
        assert not any(one in said for one in NOT_A_WHOSE), f"законный хвост отвергнут: «{said}»"


# --- состав ролей выводится из карты, а не живёт рядом (#595) -----------------

#: Заголовок таблицы состава: по нему она и находится.
ROSTER_HEAD: Final = "| Роль | Вход | Возражает |"
#: Исход, называющий владельца профиля. Голое «профиль» означает «владелец с
#: окном» — то есть кто-нибудь из двоих, а вопрос, который задаёт кто-нибудь,
#: не задаёт никто в тот день, когда оба заняты другим.
NAMED_RE: Final = re.compile(r"^профиль (?P<owner>.+)$")


def roster() -> set[str]:
    """Имена ролей из таблицы состава — как они в ней написаны."""
    said = MAP.read_text(encoding="utf-8")
    after = said.partition(ROSTER_HEAD)[2]
    found: set[str] = set()
    for line in after.splitlines():
        if not line.strip():
            # Пустая строка сразу после заголовка — это его собственный перевод
            # строки, а не конец таблицы. Обрыв на ней давал НОЛЬ ролей, и гейт
            # зеленел бы на пустом предмете, если бы не проверка непустоты (075).
            continue
        if not line.startswith("|"):
            break
        cells = [one.strip() for one in line.strip("|").split("|")]
        if len(cells) != 3 or set(cells[0]) <= set("- "):
            continue
        name = re.sub(r"[^\w\s-]", "", cells[0]).replace("**", "").strip()
        if name:
            found.add(name)
    return found


def test_the_roster_has_roles_to_judge() -> None:
    """Предмет найден: состав ролей в карте есть и не пуст (075)."""
    assert len(roster()) >= 10, f"ролей разобрано {len(roster())} — таблицы состава не видно"


def test_every_profile_names_its_owner() -> None:
    """У профиля назван ВЛАДЕЛЕЦ, а не «владелец с окном» по умолчанию.

    ЗАМЕР, РАДИ КОТОРОГО ГЕЙТ ЗАВЕДЁН (21.09.2026, #595). Из двадцати шести
    профилей карты владелец был назван у СЕМИ. У девятнадцати стояло голое
    «профиль» — и карта честно говорила, что вопрос задаётся, не говоря кем.
    Владелец подвёл итог точно: «вывод есть, а самих ролей нет».

    Это дыра, которая НЕ помечена «роли нет»: вопрос задаётся, спрашивающий не
    назван
    ([046](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/046-name-the-gaps-do-not-level-them.md)).
    """
    bare = [name for name, (outcome, _) in rows().items() if outcome == "профиль"]
    assert not bare, (
        "исход «профиль» не называет владельца у: "
        + ", ".join(sorted(bare))
        + " — вопрос задаётся, а спрашивающий не назван"
    )


def test_a_named_owner_is_a_role_that_exists() -> None:
    """Названный владелец — это роль из состава, внешний исполнитель или человек.

    Вторая половина: без неё «профиль Кого-Угодно» проходил бы первую проверку,
    и состав разошёлся бы с картой молча — ровно то, ради чего он из неё и
    выводится (049).
    """
    outside = {"внешнего взгляда", "окна", "владельца", "каталога"}
    known = {name.split()[-1] for name in roster()} | roster()
    unknown: list[str] = []
    for name, (outcome, _) in rows().items():
        said = NAMED_RE.match(outcome)
        if not said:
            continue
        owner = said["owner"]
        if owner in outside:
            continue
        # СВЕРЯЕТСЯ ИМЯ ЦЕЛИКОМ, А НЕ ПЕРВОЕ СЛОВО (#602). Прежде брался корень
        # ПЕРВОГО слова, и остаток многословного имени не проверялся вовсе:
        # «профиль Инженера чего-угодно» проходил, потому что в составе есть
        # «Инженер площадки». Предикат был шире предмета ровно на хвост имени
        # ([195](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/195-a-narrowed-predicate-names-its-neighbour.md)).
        # Нашёл внешний взгляд, и дважды — находками `50c1a49` и `3dc69fa`.
        #
        # Падеж снимается по СЛОВАМ: каждое слово имени сверяется корнем без
        # последней буквы, и совпасть обязаны ВСЕ. Морфологии здесь нет и не
        # нужно — имена ролей короткие и заданы самим составом.
        said_words = [one[:-1] for one in owner.split() if len(one) > 2]
        if not said_words or not any(all(word in role for word in said_words) for role in known):
            unknown.append(f"{name} → «{owner}»")
    assert not unknown, (
        "исход называет владельца, которого нет ни в составе, ни снаружи: " + ", ".join(unknown)
    )


# --- у роли есть профиль, а не только строка (#599) ---------------------------

#: Поля профиля, без которых роль неотличима от строки таблицы. «Вопрос» —
#: зачем она есть, «Запрещено» — чем она не становится, «Предел» — чего не
#: видит по построению. Последнее важнее прочего: роль, чей предел не назван,
#: кажется всесильной, и её молчание читают как «там чисто»
#: ([046](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/046-name-the-gaps-do-not-level-them.md)).
PROFILE_FIELDS: Final = ("**Вопрос:**", "**Запрещено:**")
#: Предел называется одним из двух: просто названный или ИЗМЕРЕННЫЙ.
LIMIT_FIELDS: Final = ("**Предел:**", "**Предел ИЗМЕРЕН:**")


def profiles() -> dict[str, str]:
    """Профиль каждой роли: заголовок третьего уровня → тело."""
    said = MAP.read_text(encoding="utf-8")
    after = said.partition("## Профили")[2]
    found: dict[str, str] = {}
    for part in re.split(r"^### ", after, flags=re.M)[1:]:
        head = part.splitlines()[0]
        name = re.sub(r"[^\w\s-]", "", head).strip()
        found[name] = part.split("\n## ", 1)[0]
    return found


def test_there_are_profiles_to_judge() -> None:
    """Предмет найден: профили в карте есть (075)."""
    assert len(profiles()) >= 10, f"профилей разобрано {len(profiles())} — раздела не видно"


def test_every_role_of_the_roster_has_a_profile() -> None:
    """У каждой роли состава есть профиль, а не только строка таблицы.

    ЗАМЕР, РАДИ КОТОРОГО ПРОВЕРКА ЗАВЕДЕНА (21.09.2026, #599). Состав был
    написан таблицей — имя, вход, возражение, — и владелец назвал это
    неполным: «не увидел описание и взаимодействие ролей». Строка отвечает
    «кто спрашивает», профиль — «как он спрашивает», а это и есть то, ради
    чего роль существует.
    """
    missing = sorted(roster() - set(profiles()))
    assert not missing, "роль в составе есть, а профиля у неё нет: " + ", ".join(missing)


@pytest.mark.parametrize("name", sorted(profiles()), ids=lambda one: str(one))
def test_a_profile_names_its_limit_and_its_ban(name: str) -> None:
    """Профиль называет запрет и предел, а не только достоинства.

    Роль, которой можно всё, поглощает соседнюю, и вход перестаёт их
    различать. Роль, чей предел не назван, кажется всесильной — и тогда её
    молчание читают как «там чисто», а не как «она туда не смотрит» (046).
    """
    body = profiles()[name]
    for field in PROFILE_FIELDS:
        assert field in body, f"{name}: в профиле нет поля {field}"
    assert any(one in body for one in LIMIT_FIELDS), (
        f"{name}: предел не назван — роль выглядит всесильной, "
        "и её молчание прочтут как «там чисто»"
    )
