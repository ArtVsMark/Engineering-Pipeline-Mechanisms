"""Раздел «чего ещё нет» — утверждение о действительности, а не оборот речи.

Проза целиком непроверяема, и гейт её трогать не должен. Но у неё есть
подкласс, который рассыхается молча и выглядит при этом осознанным решением, —
СЧЁТ. Число в строке «ответа по N записям каталога» стареет каждой пачкой
разбора, и заметить это нечем: раздел никто не пересчитывает.

ВТОРАЯ ПОЛОВИНА ТРЕБОВАНИЯ — ВЫХОД, А НЕ ТОЛЬКО ПРИЧИНА. Правило 046 просит у
пробела двух вещей: «почему он оставлен» И «что было бы правильным решением».
Вторая половина у нас выражена адресом — задачей или путём к механизму, — и до
18.09.2026 не держалась ничем: замер того дня дал десять строк, адрес несли все
десять, то есть требование исполнялось и проверялось внимательностью. Пробел без
выхода перестаёт быть пробелом и становится обстоятельством: его никто не
закроет, потому что закрывать некуда
([046](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/046-name-the-gaps-do-not-level-them.md),
[142](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/142-a-scheduled-red-needs-an-addressee.md)).

Правила каталога: 175 (утверждение «предмета нет», опровергаемое одной
командой, обязано быть гейтом), 005 и 127 (число в прозе без маркера и сборки
рассыхается).
"""

from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
#: ТАБЛИЦА ПРОБЕЛОВ ПЕРЕЕХАЛА 21.09.2026 (#597). Она жила в ядре и занимала
#: 748 слов из 2204 — треть документа, который отвечает на «как работать», а не
#: «что не доделано». Ядро сохранило врезку со ссылкой, список получил свой
#: документ и своего читателя (021, 029).
#: Документ пробелов и ЯДРО — теперь разные файлы, и читателя у них два.
#: Таблица секретов осталась в ядре: она отвечает на «как работать» (чем
#: держится доступ и когда истекает), а список пробелов — на «чего нет» (021).
CHARTER = ROOT / "docs" / "dev" / "gaps.md"
CORE = ROOT / "AGENTS.md"
BINDINGS = ROOT / ".rules" / "bindings.json"
HEADING = "## Пробелы"
SECRETS_HEADING = "## 🔑 Секреты"
# Имя секрета в прозе: заглавные латиницей с подчёркиваниями, в обратных кавычках.
SECRET_RE = re.compile(r"`([A-Z][A-Z0-9_]{5,})`")


def gaps_rows() -> list[str]:
    """Строки таблицы пробелов — без шапки и разделителя."""
    text = CHARTER.read_text(encoding="utf-8")
    start = text.index(HEADING)
    section = text[start:]
    rows = [line for line in section.splitlines() if line.startswith("|")]
    return rows[2:]


def test_the_section_has_a_subject() -> None:
    """Таблица пробелов не пуста: иначе гейт зелен на отсутствии предмета (075)."""
    assert gaps_rows(), f"в {CHARTER.name} не нашлось таблицы пробелов — предмет проверки не найден"


def test_no_row_carries_a_count() -> None:
    """Ни один пробел не называется числом: счёт двигает механизм, а не рука.

    Число живёт там, где считается, — шаг `debt` печатает его на каждом
    изменении, `facts.json` в ветке `badges` публикует наружу. Вписанное сюда,
    оно расходится с деревом на первой же разобранной записи и продолжает
    выглядеть решением.
    """
    with_counts = [row for row in gaps_rows() if re.search(r"\d", row.split("|")[1])]
    assert not with_counts, f"число вписано в пробел прозой: {with_counts}"


def unreviewed() -> int:
    """Сколько записей каталога ещё без ответа — по дереву, а не по памяти."""
    rules = json.loads(BINDINGS.read_text(encoding="utf-8"))["rules"]
    return sum(1 for answer in rules.values() if answer["status"] == "unreviewed")


def test_the_catalogue_gap_matches_the_answer() -> None:
    """Пробел «ответа по записям каталога нет» опровергается одной командой (175).

    Ровно тот подкласс прозы, который сводится к наличию объекта: очередь либо
    есть в `.rules/bindings.json`, либо её нет. Пока строка стояла на памяти,
    она успела разойтись с деревом на 71 запись и продолжала выглядеть решением.
    """
    claims = [
        row
        for row in gaps_rows()
        if "каталог" in row.split("|")[1] and "ответа" in row.split("|")[1]
    ]
    if unreviewed():
        assert claims, "очередь без ответа есть, а пробел в своде не назван (046)"
    else:
        assert not claims, f"ответ каталогу полон, а свод всё ещё называет это пробелом: {claims}"


def secrets_rows() -> list[str]:
    """Строки таблицы секретов — того, что у проекта ЕСТЬ и кем продлевается."""
    text = CORE.read_text(encoding="utf-8")
    start = text.index(SECRETS_HEADING)
    section = text[start:]
    rows = [line for line in section.splitlines() if line.startswith("|")]
    return rows[2:]


def test_the_two_tables_do_not_contradict_each_other() -> None:
    """Секрет не может числиться и заведённым, и отсутствующим разом.

    Две таблицы одного файла: одна называет, чем механизм держится и кто
    продлевает секрет, другая — чего у проекта нет. Секрет, попавший в обе,
    означает, что одна из них не обновлена, — и снаружи это неотличимо от
    осознанного решения
    ([175](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/175-an-absence-claim-that-a-command-can-refute-must-be-a-gate.md)).

    Замер, из-за которого проверка написана: `CLAUDE_CODE_OAUTH_TOKEN` стоял в
    таблице секретов с продлевающим и одновременно в пробелах как «секрета
    нет». Ревью при этом работало на каждом изменении.
    """
    declared = {name for row in secrets_rows() for name in SECRET_RE.findall(row)}
    assert declared, "таблица секретов пуста — предмет сверки не найден (075)"
    claimed_missing = {
        name
        for row in gaps_rows()
        if "секрет" in row.split("|")[1].lower()
        for name in SECRET_RE.findall(row.split("|")[1])
    }
    both = sorted(declared & claimed_missing)
    assert not both, f"секрет объявлен заведённым и отсутствующим сразу: {both}"


#: Разделитель ячеек: труба, НЕ закрытая обратной косой. Внутри текста ячейки
#: труба пишется как `\|` — так её и разбирает Markdown.
CELL_EDGE = re.compile(r"(?<!\\)\|")


def cells(row: str) -> list[str]:
    r"""Поля строки таблицы без пустых краёв, которые даёт разрез по трубе.

    ОБРАМЛЯЮЩИЕ ТРУБЫ ДАЮТ ПУСТЫЕ КРАЯ, и первая редакция этой проверки взяла
    `split("|")[-1]` — то есть пустоту за последней трубой. Гейт покраснел на
    ЗДОРОВОМ дереве, все десять строк; предикат, который отвергает верное, не
    держит ничего и только учит себя обходить
    ([140](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/140-a-gate-is-tested-by-what-it-must-reject.md)).

    ВТОРАЯ РЕДАКЦИЯ РЕЗАЛА ПО КАЖДОЙ ТРУБЕ, включая экранированную внутри
    текста ячейки: строка с `` `a\|b` `` в первом столбце давала ЧЕТЫРЕ поля, и
    проверка объяснения мерила длину не того текста — на замере четыре знака
    вместо пятидесяти, то есть ложный отказ. Нашёл внешний взгляд.
    """
    return [cell.strip() for cell in CELL_EDGE.split(row.strip().strip("|"))]


#: Выход из пробела: задача площадки либо путь к механизму в дереве.
WAY_OUT_RE = re.compile(r"#\d+|issues/\d+|(?:docs|scripts|tests|packages)/[\w./-]+")
#: Ниже какой длины объяснение пробела перестаёт объяснять. Взято ПОТОЛКОМ снизу:
#: замер 18.09.2026 по десяти живым строкам дал минимум 129 знаков, медиану 480.
#: Предел поставлен вдвое ниже минимума — он ловит пустое и односложное, а не
#: короткое: ограничивать надо УСЫХАНИЕ, а не стиль (050).
EXPLAINED_AT_LEAST = 64


def test_every_gap_names_its_way_out() -> None:
    """У каждого пробела назван ВЫХОД, а не только причина.

    Пробел без адреса перестаёт быть пробелом и становится обстоятельством: его
    никто не закроет, потому что закрывать некуда. Адрес разрешимый — задача либо
    путь к механизму, — и проза рядом законна, вместо адреса — нет: то же
    требование, что `.pipeline.yml` предъявляет совещательной проверке.
    """
    без_выхода = [cells(row)[0] for row in gaps_rows() if not WAY_OUT_RE.search(cells(row)[-1])]
    assert not без_выхода, (
        "пробел не назвал выхода — ни задачи, ни пути к механизму (046, 142):\n  "
        + "\n  ".join(без_выхода)
    )


def test_every_gap_explains_itself() -> None:
    """У каждого пробела есть объяснение, а не одна отметка о существовании.

    Правило просит двух половин, и первая — «почему он оставлен». Пустой или
    односложный столбец оставляет пробел неотличимым от «не сделали»: разница
    между отложенным намеренно и забытым живёт ровно здесь.
    """
    невнятные = [
        f"{cells(row)[0]!r} — объяснение {len(cells(row)[1])} знаков"
        for row in gaps_rows()
        if len(cells(row)[1]) < EXPLAINED_AT_LEAST
    ]
    assert not невнятные, (
        f"пробел объяснён короче {EXPLAINED_AT_LEAST} знаков — это отметка, а не"
        " причина (046):\n  " + "\n  ".join(невнятные)
    )


def test_a_pipe_inside_a_cell_does_not_split_it() -> None:
    """Экранированная труба внутри ячейки полем не считается.

    Вторая редакция разбора резала по КАЖДОЙ трубе: строка с `` `a\\|b` `` в
    первом столбце давала четыре поля, и проверка объяснения мерила длину не
    того текста — четыре знака вместо полусотни, то есть ложный отказ. Нашёл
    внешний взгляд.
    """
    row = "| **чего нет `a\\|b`** | причина, объясняющая пробел достаточно подробно | #243 |"
    said = cells(row)
    assert len(said) == 3, f"строка разрезана не по столбцам: {said}"
    assert said[0] == "**чего нет `a\\|b`**", said[0]
    assert said[1].startswith("причина"), said[1]
    assert said[-1] == "#243", said[-1]
