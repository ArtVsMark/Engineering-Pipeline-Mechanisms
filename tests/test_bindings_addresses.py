"""Ответ каталогу называет адреса, которые ЕСТЬ в дереве.

Каталог требует от поля `where` разрешимый адрес, а не прозу, и проверяет это у
себя — но у потребителя проверить не может: файл чужой, и красное оттуда
приучало бы читать красное как фон. Значит проверять обязан сам потребитель
([174](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/174-facts-about-a-project-are-published-by-it.md)).

ЧТО ЭТО ЛОВИТ. Механизм переименовали или он переехал, а ответ остался прежним:
снаружи такой ответ выглядит живым, и расхождение молчит до тех пор, пока
кто-нибудь не пойдёт по адресу руками. ЗАМЕР 10.09.2026, найдено ревизией по
просьбе владельца, а не механизмом: ответ на правило 075 называл
`gates_complete.py` — имя, под которым сводный гейт не живёт с самого
переименования.

ЧЕГО ГЕЙТ НЕ ТРЕБУЕТ. Чужих адресов — механизм соседа законно называется в
ответе и в нашем дереве не лежит. Такие имена перечислены списком с причиной, а
не пропускаются молча
([068](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/068-allowlist-not-denylist.md)).
"""

from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any, Final

import pytest

from tests.conftest import walk_deep

ROOT = Path(__file__).resolve().parent.parent
BINDINGS = ROOT / ".rules" / "bindings.json"

#: Имя файла механизма внутри ответа: то, по чему читатель пойдёт искать.
#: Ведущая точка входит в имя: `.pipeline.yml` — файл ответа проекта, и без неё
#: гейт искал бы в дереве несуществующий `pipeline.yml`.
#: Имя файла, названного ответом. ВИДОВ ШЕСТЬ, А НЕ ДВА, и это замер, а не вкус:
#: до 18.09.2026 сверялись только `.py` и `.yml`, то есть записи `.rules/*.json`
#: и разборы `docs/decisions/*.md` не проверялись ВОВСЕ — переименуй хранилище
#: или разбор, и ответ рассохся бы молча.
#:
#: ШЕСТОЙ ВИД НАЗВАН ВСЛУХ, А НЕ ДОПИСАН МОЛЧА. Прежде тут стояло «видов пять»,
#: а образец уже нёс `toml` — то есть замер и предикат расходились в одном
#: абзаце, и расходились в сторону непроверенного (005). Замер 19.09.2026,
#: командой ниже: `py` — 511, `yml` — 99, `md` — 96, `json` — 55, `toml` — 1,
#: `txt` — 1. Ни один вид не пуст, то есть ни один не стоит впрок (068)::
#:
#:     python -c "import re,collections;\
#:     s=open('.rules/bindings.json',encoding='utf-8').read();\
#:     print(collections.Counter(m.rsplit('.',1)[1] for m in NAME_RE.findall(s)))"
NAME_RE: Final = re.compile(r"(?<![\w./-])(\.?[\w./-]+\.(?:py|yml|yaml|json|md|txt|toml))\b")

#: Имена, которых в этом дереве нет и быть не должно. Список разрешительный:
#: каждое названо с причиной, и молчаливого пропуска здесь нет.
FOREIGN: Final = {
    "onboard_consumer.py": "механизм каталога: им собран наш ответ, у нас его нет",
    "check_untrusted_prompt.py": (
        "механизм каталога: у него вторая половина 085, "
        "и наш гейт взял у него образец пометки (090)"
    ),
}


#: Имена, которые в ответе стоят НЕ адресом: образец записи, пример имени с
#: точкой. Отличить адрес от примера в прозе машина не может — это суждение о
#: смысле, — поэтому список закрытый и с причиной у каждого (068, 154).
IN_PROSE: Final = {
    "NNN-slug.md": (
        "ОБРАЗЕЦ адреса, а не адрес: так выглядит ссылка на правило каталога, "
        "и `NNN` здесь место для номера"
    ),
    "SECURITY.md": (
        "ПРИМЕР имени, внутри которого стоит точка, — им ответ показывает, что "
        "разбор прозы не режет по точке. Такого файла у нас нет и не требуется"
    ),
}
#: Наше, но ОПУБЛИКОВАННОЕ: в дереве этого файла нет и быть не должно — он
#: собирается прогоном и живёт в ветке значков. Ответ обязан называть именно его:
#: путь к сборщику требовал бы от читателя считать число самому (174).
PUBLISHED: Final = {
    "facts.json": (
        "собирается scripts/build_facts.py и публикуется в ветку badges; "
        "витрина и ответы ссылаются на опубликованный файл, а не на дерево"
    ),
}


def answers() -> dict[str, dict[str, str]]:
    """Ответы проекта по правилам каталога."""
    document = json.loads(BINDINGS.read_text(encoding="utf-8"))
    rules: dict[str, dict[str, str]] = document["rules"]
    return rules


def tree_names() -> set[str]:
    """Имена файлов дерева — по ним и ищет читатель ответа."""
    return {path.name for path in walk_deep(ROOT, "*") if path.is_file()}


def named_files() -> list[tuple[str, str]]:
    """Пары «правило, имя файла», названные в ответах."""
    found: list[tuple[str, str]] = []
    for rule, answer in sorted(answers().items()):
        for field in ("where", "why"):
            for name in NAME_RE.findall(str(answer.get(field) or "")):
                found.append((rule, name.rsplit("/", 1)[-1]))
    return found


def test_the_gate_found_its_subject() -> None:
    """Предмет проверки найден: ответы есть и адреса в них называются (075)."""
    assert answers(), "ответов каталогу нет — проверять нечего"
    assert named_files(), "ни один ответ не называет файла — предмет не найден"


@pytest.mark.parametrize(
    ("rule", "name"), named_files(), ids=lambda item: item if isinstance(item, str) else ""
)
def test_a_named_mechanism_exists_in_the_tree(rule: str, name: str) -> None:
    """Файл, названный в ответе, лежит в дереве — или объявлен чужим.

    Ответ, называющий несуществующий механизм, врёт каталогу и читателю
    одинаково правдоподобно: снаружи он ничем не отличается от живого.
    """
    if name in FOREIGN or name in IN_PROSE or name in PUBLISHED:
        return
    assert name in tree_names(), (
        f"ответ на правило {rule} называет «{name}», которого в дереве нет. "
        "Механизм переименован или переехал — поправьте ответ либо объявите имя "
        "с причиной в одном из трёх списков: FOREIGN (механизм каталога), "
        "PUBLISHED (наше, но собираемое прогоном), IN_PROSE (образец или пример, "
        "а не адрес).\n  Объявлено сейчас: "
        f"FOREIGN={sorted(FOREIGN)}, PUBLISHED={sorted(PUBLISHED)}, IN_PROSE={sorted(IN_PROSE)}"
    )


def test_every_foreign_name_is_explained() -> None:
    """У каждого имени вне дерева названа причина, а не просто пропуск (154)."""
    for what, said in (("чужое", FOREIGN), ("в прозе", IN_PROSE), ("публикуемое", PUBLISHED)):
        bare = sorted(name for name, why in said.items() if not str(why).strip())
        assert not bare, f"имя объявлено как «{what}» без причины: {bare}"


def test_the_foreign_list_is_not_a_graveyard() -> None:
    """В списке чужих нет имён, которые в дереве всё же есть.

    Такое имя означает, что исключение пережило свою причину: механизм появился
    у нас, а гейт продолжает его не проверять.
    """
    stray = sorted((set(FOREIGN) | set(IN_PROSE) | set(PUBLISHED)) & tree_names())
    assert not stray, f"эти имена есть в дереве и в исключении не нуждаются: {stray}"


def test_every_declared_exception_is_still_named_by_an_answer() -> None:
    """Исключение не переживает ответа, который его называл.

    Запись, чьё имя из ответов ушло, — разрешение, которого никто не просил: оно
    молча пропустит следующее имя с тем же написанием
    ([075](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/075-a-guard-that-finds-nothing-must-fail.md)).
    """
    alive = {name for _, name in named_files()}
    dead = sorted((set(IN_PROSE) | set(PUBLISHED)) - alive)
    assert not dead, f"исключение объявлено, а ответы это имя больше не называют: {dead}"


#: Любой адрес файла в ответе, включая документы: нужен, чтобы отличить
#: «назван документ» от «не названо ничего» — это разные находки (154).
ANY_FILE_RE: Final = re.compile(r"(?<![\w./-])(\.?[\w./-]+\.[a-z]{2,5})\b")
#: Что считается ИСПОЛНЯЕМЫМ адресом: то, что можно запустить и получить код
#: возврата. Список закрытый: «похоже на путь» приняло бы и документ, а весь
#: смысл правила в том, что документ механизмом не является.
RUNNABLE_SUFFIXES = (".py", ".yml", ".yaml")
#: Механизмы, у которых исполняемого адреса нет и быть не может, — с причиной.
#: Пустой список тут был бы честнее пустой отговорки: имя попадает сюда только
#: тогда, когда предмет действительно вне дерева (154).
RUNNABLE_ELSEWHERE: dict[str, str] = {}


@pytest.mark.parametrize(
    "answer",
    [(number, one) for number, one in sorted(answers().items()) if one.get("mechanism") == "gate"],
    ids=lambda pair: str(pair[0]),
)
def test_a_gate_names_something_runnable(answer: tuple[str, dict[str, Any]]) -> None:
    """Ответ «держится гейтом» называет адрес ИСПОЛНЯЕМОГО, а не документа.

    Правило 139: механизм считается работающим по прогону, а не по написанному.
    Документ прогоном не подтверждается вовсе — он не запускается; ответ,
    называющий гейтом абзац в `AGENTS.md`, обещает проверку, которой нет.

    Правило соблюдалось всеми ста пятью ответами и держалось при этом
    вниманием: сто шестому ничто не мешало назвать документ. Гейт перенесён от
    каталога, где список видов тоже закрытый (162).
    """
    number, one = answer
    if number in RUNNABLE_ELSEWHERE:
        return
    names = ANY_FILE_RE.findall(one.get("where") or "")
    runnable = [name for name in names if name.endswith(RUNNABLE_SUFFIXES)]
    assert runnable, (
        f"правило {number}: ответ «gate» не назвал исполняемого — {names or 'адресов нет'}. "
        "Механизм подтверждается прогоном, а документ не запускается (139)"
    )


#: Ссылка на ШАГ дорожной карты — с номером или без. Шагов в ней нет вовсе: она
#: ведётся этапами, а перечень отложенного живёт в задаче. Рукописная ссылка на
#: часть чужого документа — классическое протухание
#: ([005](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/005-hand-written-numbers-rot.md)).
#:
#: ПЕРВАЯ РЕДАКЦИЯ ОБРАЗЦА БЫЛА СОБРАНА ПО ТРЁМ НАЙДЕННЫМ СЛУЧАЯМ и потому
#: пропустила два лежавших рядом: «шаг 8 или 9 ИЗ docs/roadmap.md» (другой
#: предлог и два номера) и «шаги в docs/roadmap.md» (без номера вовсе). Гейт
#: заводился с заявлением «признак назван целиком» — и заявление было неверным.
#: Нашёл внешний взгляд, трижды об одном, на #380.
#:
#: Теперь предмет назван прямо: слово «шаг» рядом с адресом карты. Окно в
#: шестьдесят знаков держит границу — «шаг» и карта, упомянутые в разных
#: предложениях, ссылкой не являются (195).
ROADMAP_STEP: Final = re.compile(r"шаг\w*[^.\"]{0,60}?docs/roadmap")


def test_no_answer_points_at_a_roadmap_step() -> None:
    """Условие, названное шагом дорожной карты, протухает молча.

    ЗАМЕР 16.09.2026: так и вышло, и дважды. Сперва три ответа — 076, 112 и 194 —
    называли условием шаг дорожной карты; пакет появился 15.09.2026, то есть
    условие НАСТУПИЛО, а шага с таким номером в карте к тому времени не было
    вовсе. Нашёл владелец вопросом о неприменимых.

    Потом первая редакция этого гейта, собранная по трём найденным случаям,
    пропустила ещё ДВА, лежавших рядом: 184 («шаг 8 или 9 из docs/roadmap.md» —
    другой предлог и два номера) и 025 («шаги в docs/roadmap.md» — без номера).
    Заявление «признак назван целиком» было неверным, и нашёл это внешний взгляд.
    Урок дешевле правила: гейт меряется по ВСЕМУ дереву до того, как починены
    найденные случаи, — иначе он проверяет только их (075).

    Условие обязано называться СОБЫТИЕМ, которое видно в дереве («пакет
    опубликован в чужом реестре»), а не номером строки чужого документа.
    """
    rot = [
        rule
        for rule, one in sorted(answers().items())
        if ROADMAP_STEP.search(json.dumps(one, ensure_ascii=False))
    ]
    assert not rot, (
        f"ответы ссылаются на шаг дорожной карты: {rot}. Шагов в ней нет вовсе — "
        "она ведётся этапами. Условие надо назвать СОБЫТИЕМ, видимым в дереве"
    )


#: Формы, на которых образец уже спотыкался. Список не придуман: каждая строка
#: — случай из истории этого гейта, и рядом назван заход, который её нашёл.
#:
#: * «шаг N в» — три ответа (076, 112, 194), ради которых гейт и заводился;
#: * «шагом N по» — первая редакция образца его обходила; поймано ОТКАТОМ на
#:   #380, а не чтением;
#: * «шаг N из» (184) и «шаги в» без номера (025) — пропущены второй редакцией,
#:   собранной по трём найденным случаям; нашёл внешний взгляд на #386.
ROADMAP_SAID: Final = (
    "условие: шаг 9 в `docs/roadmap.md`",
    "условие: шагом 9 по `docs/roadmap.md`",
    "условие: шаг 8 или 9 из `docs/roadmap.md`",
    "условие: шаги в `docs/roadmap.md`",
)

#: Соседство, ссылкой НЕ являющееся: «шаг» и карта в разных предложениях или
#: просто далеко друг от друга. Без этой половины гейт нельзя отличить от
#: образца «упомянуты оба слова» (195).
ROADMAP_NEARBY: Final = (
    "шаг сделан. Порядок работ описан в `docs/roadmap.md`",
    "шаг механизма ждёт события, которое видно в дереве; порядок работ, этапы "
    "и их приёмка описаны отдельно — см. `docs/roadmap.md`",
)


@pytest.mark.parametrize("said", ROADMAP_SAID)
def test_the_roadmap_gate_catches_every_form_it_met(said: str) -> None:
    """Гейт прогнан тем, что обязан отвергать, — всеми четырьмя формами (140).

    ЗАЧЕМ ОТДЕЛЬНЫЕ СТРОКИ, РАЗ ЕСТЬ ОБХОД ДЕРЕВА. Обход судит сегодняшние
    ответы, и когда все они починены, он зелен при ЛЮБОМ образце — включая
    пустой. Гейт, у которого нет прогона на отказе, подтверждается только тем,
    что ему нечего ловить
    ([075](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/075-a-guard-that-finds-nothing-must-fail.md)).

    ЗАЯВЛЕНИЕ БЫЛО, А ПРОГОНА НЕ БЫЛО. Фрагмент #386 писал «проверено на всех
    четырёх известных формах», и проверкой была рука автора: в дереве не стояло
    ни одной строки, которая бы это держала. Нашёл внешний взгляд находкой
    `3787d06` — он же заметил, что одна из форм пришла из соседнего захода
    (139).
    """
    assert ROADMAP_STEP.search(said), f"форма прошла мимо гейта: {said}"


@pytest.mark.parametrize("said", ROADMAP_NEARBY)
def test_the_roadmap_gate_leaves_the_neighbour_alone(said: str) -> None:
    """Соседство — не ссылка: иначе гейт запрещает упоминать карту вовсе (195).

    Предикат, который краснеет на всяком соседстве двух слов, дороже пропуска:
    его начинают обходить формулировкой, и тогда он не ловит уже ничего (051).
    """
    assert not ROADMAP_STEP.search(said), f"гейт покраснел на соседстве: {said}"
