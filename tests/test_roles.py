"""Роли, задающие вопросы карты: у каждой роли состава есть профиль с запретом и пределом.

Карта направлений (`docs/dev/directions.md`) называет вопрос и его владельца; файл
ролей (`docs/agent/roles.md`) — кто этот владелец и как он спрашивает. Разведено по
решению владельца 24.09.2026 (#767): у них разный повод правки и разный
читатель. Полноту карты и стык «исход называет роль из состава» держит
`tests/test_directions_map.py`, и второй копии той проверки здесь нет (022).
"""

import re
from typing import Final

import pytest

from tests.conftest import ROOT, load_script
from tests.test_directions_map import role_name, roster, roster_rows

paths = load_script("paths.py")

ROLES: Final = ROOT / paths.ROLES


# --- у роли есть профиль, а не только строка (#599) ---------------------------

#: Поля профиля, без которых роль неотличима от строки таблицы. «Вопрос» —
#: зачем она есть, «Запрещено» — чем она не становится, «Предел» — чего не
#: видит по построению. Последнее важнее прочего: роль, чей предел не назван,
#: кажется всесильной, и её молчание читают как «там чисто»
#: ([046](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/046-name-the-gaps-do-not-level-them.md)).
PROFILE_FIELDS: Final = ("**Вопрос:**", "**Запрещено:**")
#: Предел называется одним из двух: просто названный или ИЗМЕРЕННЫЙ.
LIMIT_FIELDS: Final = ("**Предел:**", "**Предел ИЗМЕРЕН:**")


def profiles() -> dict[str, str]:
    """Профиль каждой роли: заголовок третьего уровня → тело."""
    said = ROLES.read_text(encoding="utf-8")
    after = said.partition("## Профили")[2]
    found: dict[str, str] = {}
    for part in re.split(r"^### ", after, flags=re.M)[1:]:
        head = part.splitlines()[0]
        name = re.sub(r"[^\w\s-]", "", head).strip()
        found[name] = part.split("\n## ", 1)[0]
    return found


def test_there_are_profiles_to_judge() -> None:
    """Предмет найден: профили в карте есть (075)."""
    assert len(profiles()) >= 10, f"профилей разобрано {len(profiles())} — раздела не видно"


def test_every_role_of_the_roster_has_a_profile() -> None:
    """У каждой роли состава есть профиль, а не только строка таблицы.

    ЗАМЕР, РАДИ КОТОРОГО ПРОВЕРКА ЗАВЕДЕНА (21.09.2026, #599). Состав был
    написан таблицей — имя, вход, возражение, — и владелец назвал это
    неполным: «не увидел описание и взаимодействие ролей». Строка отвечает
    «кто спрашивает», профиль — «как он спрашивает», а это и есть то, ради
    чего роль существует.
    """
    missing = sorted(roster() - set(profiles()))
    assert not missing, "роль в составе есть, а профиля у неё нет: " + ", ".join(missing)


@pytest.mark.parametrize("name", sorted(profiles()), ids=lambda one: str(one))
def test_a_profile_names_its_limit_and_its_ban(name: str) -> None:
    """Профиль называет запрет и предел, а не только достоинства.

    Роль, которой можно всё, поглощает соседнюю, и вход перестаёт их
    различать. Роль, чей предел не назван, кажется всесильной — и тогда её
    молчание читают как «там чисто», а не как «она туда не смотрит» (046).
    """
    body = profiles()[name]
    for field in PROFILE_FIELDS:
        assert field in body, f"{name}: в профиле нет поля {field}"
    assert any(one in body for one in LIMIT_FIELDS), (
        f"{name}: предел не назван — роль выглядит всесильной, "
        "и её молчание прочтут как «там чисто»"
    )


# --- возражение адресовано роли из состава (#1053, 062) -----------------------

#: Адресат, который ролью не является и всё же законен. Окно — АВТОР
#: изменения и выбора работы, а не роль состава: Аудитор возражает ему «вот
#: чего вы о себе не спросили», Диспетчер — «работа не та по источнику». Иного
#: исключения нет, и «всем» в их число не входит: возражение всем некому
#: принять, и роль с таким адресатом в состав не встроена (062).
NOT_A_ROLE: Final = {"окну": "окно — автор изменения и выбора работы, а не роль состава"}


def addressee(cell: str) -> str:
    """Адресат возражения: текст ячейки «Возражает» до двоеточия."""
    return cell.partition(":")[0].strip()


def names_a_role(said: str, names: set[str]) -> bool:
    """Адресат в дательном падеже называет роль из `names`.

    Склонение не разбирается, а снимается: у каждого слова отбрасывается
    последняя буква, и основа обязана совпасть со словом роли или с ним же без
    последней буквы («Архитектору» → «Архитектор», «Безопасности» →
    «Безопасность», «Техписателю» → «Техписатель»). Число слов — то же.
    """
    words = said.split()
    for name in names:
        parts = name.split()
        if len(parts) == len(words) and all(
            word[:-1] in {part, part[:-1]} for word, part in zip(words, parts, strict=True)
        ):
            return True
    return False


def strangers(said: str) -> list[str]:
    """Роли, чей адресат возражения — не роль из той же таблицы и не исключение."""
    rows = roster_rows(said)
    names = {role_name(cells[0]) for cells in rows}
    return [
        f"{role_name(cells[0])} → «{addressee(cells[2])}»"
        for cells in rows
        if addressee(cells[2]) not in NOT_A_ROLE and not names_a_role(addressee(cells[2]), names)
    ]


def test_an_objection_is_addressed_to_a_role_of_the_roster() -> None:
    """Столбец «Возражает» называет роль из состава — иначе возражение некому принять.

    ЗАМЕР, РАДИ КОТОРОГО ПРОВЕРКА ЗАВЕДЕНА (02.10.2026, #999 → #1053). Ответ
    на 062 считал приёмку роли машине недоступной, а перемер нашёл признак: из
    16 строк таблицы 3 называли адресатом не роль — Аудитор «окну», Ревизор и
    Диспетчер «всем». Ревизор возражает Техписателю: объявление — его
    документ; Аудитор и Диспетчер — окну, и это исключение `NOT_A_ROLE` с
    причиной, а не тихий пропуск (195).

    ПРЕДЕЛ. Проверяется, КОМУ роль возражает, а не О ЧЁМ: способна ли реплика
    возражения что-то оспорить, решает чтение (навык `role-profile`).
    """
    said = ROLES.read_text(encoding="utf-8")
    assert len(roster_rows(said)) >= 10, "строк состава не видно — предмет не найден (075)"
    found = strangers(said)
    assert not found, "возражение адресовано не роли состава: " + "; ".join(found)


def test_the_addressee_predicate_has_both_halves() -> None:
    """Склонённое имя роли проходит, «всем» и чужое имя — нет (140)."""
    table = "\n".join(
        (
            "| Роль | Вход | Возражает |",
            "|---|---|---|",
            "| **Инженер площадки** | x | Механику: «а» |",
            "| **Механик** | x | Инженеру площадки: «б» |",
            "| **Ревизор** | x | всем: «в» |",
            "| **Аудитор** | x | окну: «г» |",
            "| **Редактор** | x | Корректору: «д» |",
        )
    )
    assert strangers(table) == ["Ревизор → «всем»", "Редактор → «Корректору»"]
