"""Число, названное записью, сверяется с деревом — а не с памятью автора.

Строка «Правил на документах: X → Y» стоит в каждом фрагменте о переносе
правила с документа на механизм. Замер 10.09.2026: из восьми таких строк
**четыре** расходились с деревом — счёт брался из головы, пока работа шла, и
устаревал к слиянию. Ни один прогон об этом не говорил.

Правило 005 запрещает рукописные числа не потому, что они выдуманы, а потому,
что они **не пересчитываются**: верное в момент написания, число молчит, когда
дерево уходит вперёд. Здесь оно пересчитывается — по тому же источнику, из
которого его брал автор.

Проверяется ТОЛЬКО голова: у слитых фрагментов замер относится к их коммиту, и
сверять их с сегодняшним деревом значило бы требовать, чтобы прошлое совпало с
настоящим (114).
"""

from __future__ import annotations

import json
import re
from collections import Counter
from pathlib import Path
from typing import Final

from tests.conftest import ROOT

#: Строка счёта в записи. Дата обязательна: без неё это число в прозе,
#: которое устареет молча (005, 127).
COUNT_RE: Final = re.compile(r"Правил на документах \(замер ([\d.]+)\): \*\*(\d+) → (\d+)\*\*")
#: Та же строка без даты — прежняя форма, которая и разошлась.
BARE_RE: Final = re.compile(r"Правил на документах[^(:]*:\s*\**\d+\**\s*→")


def documents_now() -> int:
    """Сколько правил каталога держится документом по ответу проекта."""
    answer = json.loads((ROOT / ".rules" / "bindings.json").read_text(encoding="utf-8"))
    rules = answer["rules"]
    items = rules if isinstance(rules, list) else list(rules.values())
    return Counter(one.get("mechanism") for one in items if one.get("status") == "active")[
        "document"
    ]


def fragments() -> list[Path]:
    """Фрагменты журнала, лежащие в дереве сейчас."""
    return sorted((ROOT / "changelog.d").glob("*.md"))


def prose(path: Path) -> str:
    """Текст записи одной строкой: проза переносится, а число — нет.

    Искать по сырому тексту значило бы требовать, чтобы автор не переносил
    строку посреди фразы, — то есть проверять оформление вместо предмета.
    """
    return " ".join(path.read_text(encoding="utf-8").split())


def test_every_count_names_its_measurement_date() -> None:
    """У числа в записи есть дата замера — иначе оно врёт молча.

    Замер с названной датой числом в прозе не считается: он говорит о том дне,
    а не обо всех временах (127).
    """
    bare = [
        path.name
        for path in fragments()
        if BARE_RE.search(prose(path)) and not COUNT_RE.search(prose(path))
    ]
    assert not bare, "счёт без даты замера: " + ", ".join(bare)


def test_the_last_move_is_written_down() -> None:
    """Нынешнее число объявлено хотя бы одной записью.

    Перенос правила с документа на механизм — это работа, и она обязана
    оставить след. Запись, чьё «стало» равно нынешнему счёту, и есть тот след;
    её отсутствие означает, что перенос случился, а сказать о нём забыли —
    ровно так счёт и разошёлся с деревом: замер 10.09.2026 нашёл перенос
    28 → 27, о котором не сказала ни одна запись.

    Прежние записи говорят о своих днях, и требовать от них сегодняшнего числа
    значило бы требовать, чтобы прошлое совпало с настоящим (114). Поэтому
    спрашивается наличие, а не совпадение всех.
    """
    now = documents_now()
    counted = [
        (path.name, int(found.group(2)), int(found.group(3)))
        for path in fragments()
        if (found := COUNT_RE.search(prose(path)))
    ]
    assert counted, "ни одной записи со счётом — предмет проверки не найден (075)"
    assert any(said_to == now for _, _, said_to in counted), (
        f"в дереве сейчас {now} правил на документах, и ни одна запись этого не называет. "
        "Последний перенос случился, а след о нём не оставлен: "
        + ", ".join(f"{name} ({was} → {became})" for name, was, became in counted)
    )
