"""Как механизмы говорят с человеком: обрезка вывода и признак режима.

Длинный вывод обрезают четверо: шаг открытия, гейт журнала, транспорт и сборка
тела уплотнения. Обрезали молча — `[:300]`, — и это ровно то, что запрещает
[016](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/016-no-silent-truncation.md):
урезанный результат выглядит как полный. Читатель ищет причину в первых
трёхстах знаках, когда она в четырёхсот первом.

Копий было четыре, и разошлись бы они молча — как уже расходились состав меток,
связь с задачей и роды журнала. Здесь она одна.

ПРИЗНАК ПРОБНОГО ЗАХОДА ЖИВЁТ ЗДЕСЬ ЖЕ, И ПО ТОЙ ЖЕ ПРИЧИНЕ. Правило
[045](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/045-no-silent-fallback.md)
называет признак нарушения прямо: «в логе нет строки, по которой видно, в каком
режиме прошёл КОНКРЕТНЫЙ запуск». Замер 18.09.2026: пробный режим есть у
пятнадцати механизмов, приставку несли шесть — и все шесть вписывали её строкой
у себя. Семь букв в семи местах разъехались бы молча, а гейт, ищущий их по
дереву, искал бы подстроку вместо признака
([022](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/022-one-canonical-document.md),
[090](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/090-shared-helpers-move-up-not-sideways.md)).
"""

from __future__ import annotations

import sys
from typing import Final

LIMIT: Final = 300

#: Признак пробного захода в выводе. Боевой заход себя не называет намеренно:
#: умолчание механизма — делать, и отдельного слова требует ОТСТУПЛЕНИЕ от него,
#: а не следование ему (045).
DRY: Final = "(пробный заход)"


def cut(text: str, limit: int = LIMIT) -> str:
    """Обрезает длинный вывод, сказав, насколько он обрезан."""
    text = text.strip()
    if len(text) <= limit:
        return text
    return f"{text[:limit]}… (обрезано, всего {len(text)} знаков)"


def announce(dry_run: bool) -> None:
    """Называет пробный заход строкой захода: по ней режим виден в логе.

    Боевой заход себя не называет намеренно: приставка отмечает ОТСТУПЛЕНИЕ от
    умолчания, а не следование ему, и строка, стоящая всегда, ничего не
    различает.

    ИДЁТ В ПОТОК ДИАГНОСТИКИ, А НЕ В ОТВЕТ. Это пояснение о РЕЖИМЕ, а не
    ответ механизма, и делить с ответом один поток ему нельзя: у части
    механизмов ответ на `stdout` читает не человек, а оболочка.

    ЗАМЕР 20.09.2026, ИЗ-ЗА КОТОРОГО ПОТОК И РАЗВЕДЁН. Шаг прогона брал ответ
    механизма подстановкой — ``ответ=$(python … --queue)`` — и клал его в
    ``$GITHUB_OUTPUT``. На `stdout` приходили ДВЕ строки: приставка режима и
    сам ответ. Вторая уезжала туда же без ``ключ=``, площадка отвечала
    ``Invalid format`` и роняла джоб — два захода подряд, 18 и 19.09.2026.
    Краснело это на вкладке прогонов, которая адресатом не является
    ([045](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/045-no-silent-fallback.md)).
    """
    if dry_run:
        print(f"{DRY} — ничего не применяется, показано только намерение", file=sys.stderr)
