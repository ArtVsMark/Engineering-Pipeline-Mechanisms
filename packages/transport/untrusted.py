"""Чужой текст в теле, которое механизм публикует от своего имени (правило 230).

Ввод соседа, автора изменения или другого репозитория, положенный в тело задачи
или комментария сырым, действует от имени механизма: `@имя` уведомляет,
`#N` и адреса ссылаются, строки складываются в заголовки, пункты и служебные
метки. Форм у этих действий много, и разбор по формам дважды оставлял соседнюю
(210). Поэтому чужой текст встаёт в код строки: одной строкой, с разорванным
началом метки и с ограждением длиннее любой серии обратных кавычек внутри.

Невидимые символы этот модуль не судит: что невидимо, решает гейт текста для
агента у механизмов (`check_invisible`), и его данные Unicode в пакет не едут.
Зовущий, которому это нужно, делает текст видимым до вызова.
"""

import re
from typing import Final

#: Начало служебной метки `<!-- … -->` и его видимый разрыв в чужом тексте.
MARK_OPEN: Final = "<!--"
MARK_BROKEN: Final = "<! --"


def quoted(text: object) -> str:
    """Чужой текст — кодом строки: без упоминаний, ссылок, разметки и меток (230).

    Одна строка не начнёт ни заголовка, ни пункта; начало метки рвётся видимым
    пробелом, чтобы поиск метки подстрокой по телу её не нашёл. Ограждение длиннее
    любой серии обратных кавычек внутри, кавычка у края отделена пробелом
    (CommonMark, «Code spans»). Пустой текст — пустая строка.
    """
    flat = " ".join(str(text).split()).replace(MARK_OPEN, MARK_BROKEN)
    if not flat:
        return ""
    fence = "`" * (max(map(len, re.findall("`+", flat)), default=0) + 1)
    pad = " " if flat.startswith("`") or flat.endswith("`") else ""
    return f"{fence}{pad}{flat}{pad}{fence}"
