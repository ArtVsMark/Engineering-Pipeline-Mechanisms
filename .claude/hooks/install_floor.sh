# Интерпретатор планки `want` — ОДНА установка на оба хука старта (#1554, 214).
#
# Его читают точкой хук старта этого дерева и заготовка хука старта, которую
# заход подключения кладёт потребителю (`kit/data/.claude/hooks/session-start.sh`).
# Стражу толчка и журналу навыков нужен `python$want`, у кого бы они ни стояли;
# пока установка жила в одном хуке, заготовке пришлось бы повторить её второй
# копией, и смена установщика правила бы одну из двух.
#
# Ждёт от зовущего `want` (из `floor.sh`) и функцию `warn`. Сам не выходит:
# отказ — предупреждение зовущего, а решать, идти ли дальше, ему.
#
# ПОЧЕМУ uv ИЗ PyPI. Образ окна несёт 3.10–3.13, встроенный uv знает лишь
# 3.14.0rc2, сайт установщика uv закрыт сетевой политикой, PyPI открыт (замер
# каталога 01.10.2026: uv 0.12.21 ставит 3.14.7 за ~2 с). Сам uv ставится
# системным 3.12 — тем, что в образе окна есть всегда.
#
# СПЕРВА СПРОСИЛИ СЕМЬЮ (162): приём взят у каталога — его хук старта ставит
# интерпретатор планки тем же путём, uv из PyPI. Общего файла установки на два
# хука у каталога нет: вынос сделан только для себя, ради заготовки потребителя.
#
# Файл не исполняется сам и потому без `#!` и без права на исполнение, как `floor.sh`.
if ! command -v "python$want" >/dev/null 2>&1; then
  { python3.12 -m venv /opt/uv \
      && /opt/uv/bin/pip install -q -U uv \
      && /opt/uv/bin/uv python install "$want" \
      && ln -sf "$(/opt/uv/bin/uv python find "$want")" "/usr/local/bin/python$want"; } \
    || warn "Python $want не поставлен"
fi
