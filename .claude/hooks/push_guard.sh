#!/bin/sh
# Обёртка стража толчка: зовёт `push_guard.py` ИНТЕРПРЕТАТОРОМ ПЛАНКИ (217, #1058).
#
# ПОЧЕМУ НЕ `python3` НАПРЯМУЮ. Хук исполняется в окружении самого процесса
# окна, а не в PATH, который хук старта выставил командам: CLAUDE_ENV_FILE
# действует только на них. Голый `python3` там — системный интерпретатор
# образа (3.11 в облачном окне), и страж в стиле планки падал бы на нём
# `SyntaxError`ом. Ненулевой код, кроме 2, площадка считает НЕблокирующей
# ошибкой: толчок прошёл бы без проверки, молча.
#
# ЧИСЛО ПЛАНКИ — ИЗ `floor.sh`, общего с хуком старта, а не своим разбором
# `pyproject.toml`: разборщик планки один — `check_env` (214), а `want` с ним
# сверяет набор. Нет `floor.sh` — `want` пуст, и обёртка идёт той же веткой, что
# и без интерпретатора. Проверка `-r` ДО точки не украшение: неудачная `.` в
# `sh` обрывает его кодом 2, а 2 здесь — отказ КАЖДОЙ команде окна.
#
# НЕТ ИНТЕРПРЕТАТОРА ПЛАНКИ — ТОЛЧОК ЗАКРЫТ, ОСТАЛЬНОЕ ОТКРЫТО. Хук стоит на
# каждой команде оболочки; закрыть всё значило бы обездвижить окно из-за сбоя
# сети при старте. Закрывается только то, что страж и сторожит.
#
# ПРИЗНАК ТОЛЧКА ЗДЕСЬ — ТЕКСТ, И ОН ШИРЕ РАЗБОРА СТРАЖА, А НЕ УЖЕ. Разобрать
# команду по словам без Python нечем, а подстрока каталога `git push` пропустила
# бы формы, которые страж ловит: `git -C путь push`, `git -c k=v push`. Поэтому
# отвергается всякая команда, где после `git` где-то стоит `push`: и
# `/usr/bin/git push`, и `bash -c "git push"`, и `env git push`. Цена названа и
# идёт в безопасную сторону (068): без стража отказ получат и данные — `echo git
# push`, тело записываемого документа, `git log --grep=push`. Предел тоже назван:
# толчок, где `git` или `push` собраны из частей (`g"i"t`, `$x`), текстом не
# виден — его не ловит и сам страж, разбирающий слова без подстановки.
#
# ЛОКАЛЬНОЕ ОКНО ИНТЕРПРЕТАТОРА ПЛАНКИ ИЗ ХУКА СТАРТА НЕ ПОЛУЧАЕТ: хук старта
# ставит его только в облачном (`CLAUDE_CODE_REMOTE=true`). Поэтому вторым
# берётся `python3`, если он сам не ниже планки, — у человека это обычно и
# есть установленный 3.14 (`08446b4`). Ниже планки он стража не исполнит.
here=$(cd "$(dirname "$0")" && pwd)
unset want  # не из окружения окна: число только из floor.sh
[ -r "$here/floor.sh" ] && . "$here/floor.sh"
if [ -n "$want" ] && command -v "python$want" >/dev/null 2>&1; then
  exec "python$want" "$here/push_guard.py"
fi
if [ -n "$want" ] && command -v python3 >/dev/null 2>&1 \
  && python3 -c "import sys; sys.exit(sys.version_info[:2] < tuple(map(int, '$want'.split('.'))))" 2>/dev/null; then
  exec python3 "$here/push_guard.py"
fi
input=$(cat)
# Смотрится команда, а не всё событие: путь к расшифровке сессии или имя
# каталога с `git` в нём не должны делать толчком всякое слово `push` дальше.
command=${input#*\"command\"}
case "$command" in
  *git*push*)
    echo "страж толчка не запущен: нет ни python${want:-?}, ни python3 не ниже ${want:-?}. Толчок отвергнут до починки: без стража он ушёл бы непроверенным. В облачном окне интерпретатор ставит хук старта — перезапустите окно; в локальном поставьте python${want:-?} сами." >&2
    exit 2 ;;
esac
exit 0
