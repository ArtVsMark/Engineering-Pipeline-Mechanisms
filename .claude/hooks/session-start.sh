#!/bin/bash
# Старт облачной сессии: окружение проверки — на планке проекта, Python 3.14 — на месте.
#
# ТОЛЬКО В ОБЛАКЕ. На машине владельца окружение его, и ставить туда
# интерпретатор без спроса хук не вправе: признак облака — CLAUDE_CODE_REMOTE.
#
# ЗАЧЕМ .venv НА ПЛАНКЕ. Системный python3 облачного окна — 3.11, а
# предполётная (`scripts/preflight.py`) обещает «площадка скажет то же» и
# потому сверяет окружение с объявленным (`scripts/check_env.py`). Окружение
# собирается на версии из `requires-python` — той же, на которой гоняет
# конвейер, — с инструментами ровно в тех границах, что стоят в строках
# установки прогонов. Ни планка, ни список не разбираются здесь второй раз
# (214): их читают `check_env.python_floor`, `check_env.needs` и
# `check_env.local_packages`. Сдвинется граница — хук сам соберёт окружение
# заново. Сдвинется планка — правится одна строка `want` ниже: интерпретатор
# планки нужен, чтобы прочитать саму планку, и вычислить его до чтения нечем.
# Расхождение `want` с планкой хук называет предупреждением, а не молчит
# (взгляд на #1049, 005).
#
# ЗАЧЕМ 3.14. Это планка семьи (решение владельца 01.10.2026, #1018), а образ
# окна несёт 3.10–3.13, и встроенный uv знает лишь 3.14.0rc2. Сайт установщика
# uv закрыт сетевой политикой, PyPI открыт, поэтому свежий uv ставится из PyPI
# (замер каталога 01.10.2026: uv 0.12.21 ставит 3.14.7 за ~2 с). С #1025 3.14
# и есть планка: окружение собирается на нём. Сам uv ставится системным 3.12 —
# тем, что в образе окна есть всегда.
#
# СБОЙ СЕТИ НЕ РОНЯЕТ СТАРТ. Всякий отказ — предупреждение с названным шагом
# и выход 0: окно открывается всегда, а не готово только то, что названо.
# `.venv` попадает в PATH, только если собран целиком — или уже годен.
set -uo pipefail

warn() {
  echo "старт окна: $1 — окно работает без этого; предполётную запускайте интерпретатором не ниже планки вручную" >&2
}

if [ "${CLAUDE_CODE_REMOTE:-}" != "true" ]; then
  exit 0
fi
cd "$CLAUDE_PROJECT_DIR" || { warn "нет каталога проекта"; exit 0; }

# ЕДИНСТВЕННОЕ МЕСТО ЧИСЛА ПЛАНКИ В ХУКЕ. Его сверяет с `requires-python`
# `tests/test_session_start.py`, а на старте — сам хук, прочитав планку.
want=3.14

if ! command -v "python$want" >/dev/null 2>&1; then
  { python3.12 -m venv /opt/uv \
      && /opt/uv/bin/pip install -q -U uv \
      && /opt/uv/bin/uv python install "$want" \
      && ln -sf "$(/opt/uv/bin/uv python find "$want")" "/usr/local/bin/python$want"; } \
    || warn "Python $want не поставлен"
fi

# Планку и список читает код, который уже их читает для предполётной. Без
# планки окружение не собирается вовсе: собранное наугад обещало бы то, чего
# площадка не скажет.
#
# ЧИТАЕТ ИНТЕРПРЕТАТОР ПЛАНКИ, А НЕ СИСТЕМНЫЙ python3 (взгляд на #1036). Код
# дерева пишется под планку — с #1036 и без `from __future__ import
# annotations`, — и системный 3.11 окна его исполнять не обязан: синтаксис
# 3.14 в `check_env` или `paths` увёл бы хук в предупреждение молча. Набор
# исполняет этот разбор своим интерпретатором, то есть планкой, — и тогда он
# проверяет ровно то, что исполнит хук. Ставится этот интерпретатор строкой
# выше, а без него окружение на планке не собрать всё равно.
read_tree() {
  "python$want" -c "
import sys
sys.path[:0] = ['scripts', 'packages/transport']
import check_env as c
if sys.argv[1] == 'floor':
    major, minor = c.python_floor()
    print(f'{major}.{minor}')
elif sys.argv[1] == 'local':
    print(' '.join(str(p) for _, p in c.local_packages()))
else:
    print(' '.join(f'{n.name}{n.bounds}' for n in c.needs().values()))
" "$1"
}
# Без интерпретатора планку не прочесть — и это его отсутствие, а не планки:
# предупреждение называет настоящую причину (взгляд на #1049).
command -v "python$want" >/dev/null 2>&1 || { warn "нет python$want — дерево читать нечем"; exit 0; }
floor=$(read_tree floor) || { warn "планка интерпретатора не прочитана"; exit 0; }
if [ "$floor" != "$want" ]; then
  warn "планка $floor, а хук ставит python$want — поправьте want в хуке"
  exit 0
fi
tools=$(read_tree needs) || { warn "строки установки прогонов не прочитаны"; exit 0; }
locals=$(read_tree local) || { warn "пакеты дерева не прочитаны"; exit 0; }

if [ ! -x .venv/bin/python ] || [ "$(.venv/bin/python -c 'import sys; print("%d.%d" % sys.version_info[:2])')" != "$floor" ]; then
  rm -rf .venv
  "python$floor" -m venv .venv || { warn "окружение на $floor не собрано"; exit 0; }
fi
# ГОДНОЕ ОКРУЖЕНИЕ НЕ ПЕРЕСТАВЛЯЕТСЯ. Сверку делает тот же `check_env`, что
# зовёт предполётная: совпало — установки нет, и окно без сети получает уже
# собранное окружение, а не предупреждение (взгляд на #1024).
if ! .venv/bin/python scripts/check_env.py >/dev/null 2>&1; then
  # Пакеты дерева — РЕДАКТИРУЕМОЙ установкой, как советует `check_env`: копия
  # прятала бы от тестов правку пакета до следующего старта окна (взгляд на
  # #1024).
  editable=()
  for local in $locals; do
    editable+=(-e "$local")
  done
  # shellcheck disable=SC2086  # список — отдельные аргументы pip, а не одна строка
  .venv/bin/pip install -q $tools "${editable[@]}" || { warn "инструменты проверки не поставлены"; exit 0; }
fi
# Установка из исходников оставляет в дереве `build/` пакета, и проверка
# типов видит модуль дважды: тот, что в пакете, и его копию в сборке. Сборка
# — след установки, а не дерево проекта, и убирается тем же заходом.
for local in $locals; do
  rm -rf "$local/build"
done

echo "export PATH=\"$CLAUDE_PROJECT_DIR/.venv/bin:\$PATH\"" >> "$CLAUDE_ENV_FILE"
exit 0
