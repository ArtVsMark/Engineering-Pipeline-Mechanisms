#!/bin/bash
# Старт облачной сессии: окружение проверки — на планке проекта, интерпретатор планки (`want`) — на месте.
#
# ТОЛЬКО В ОБЛАКЕ. На машине владельца окружение его, и ставить туда
# интерпретатор без спроса хук не вправе: признак облака — CLAUDE_CODE_REMOTE.
#
# ЗАЧЕМ .venv НА ПЛАНКЕ. Системный python3 облачного окна — 3.11, а
# предполётная (`scripts/preflight.py`) обещает «площадка скажет то же» и
# потому сверяет окружение с объявленным (`scripts/check_env.py`). Окружение
# собирается на версии из `requires-python` — той же, на которой гоняет
# конвейер, — с инструментами ровно в тех границах, что стоят в строках
# установки прогонов. Ни планка, ни список не разбираются здесь второй раз
# (214): их читают `check_env.python_floor`, `check_env.needs` и
# `check_env.local_packages`. Сдвинется граница — хук сам соберёт окружение
# заново. Сдвинется планка — правится одна строка `want` в `floor.sh` рядом:
# её же читает обёртка стража толчка (#1058). Вычислить `want` из
# `requires-python` вторым разбором (`sed` по `pyproject.toml`) хук мог бы, но
# не вправе: разборщик планки один — `check_env` (214), а второй разошёлся бы с
# ним на первой же непривычной записи. Расхождение `want` с планкой хук
# называет предупреждением, а не молчит (взгляд на #1049, 005).
#
# ЗАЧЕМ СТАВИТЬ `want` САМИМ. Планка семьи на 01.10.2026 — 3.14 (решение владельца, #1018), а образ
# окна несёт 3.10–3.13, и встроенный uv знает лишь 3.14.0rc2. Сайт установщика
# uv закрыт сетевой политикой, PyPI открыт, поэтому свежий uv ставится из PyPI
# (замер каталога 01.10.2026: uv 0.12.21 ставит 3.14.7 за ~2 с). С #1025 это
# и есть планка: окружение собирается на нём. Сам uv ставится системным 3.12 —
# тем, что в образе окна есть всегда.
#
# СБОЙ СЕТИ НЕ РОНЯЕТ СТАРТ. Всякий отказ — предупреждение с названным шагом
# и выход 0: окно открывается всегда, а не готово только то, что названо.
# `.venv` попадает в PATH, только если собран целиком — или уже годен.
set -uo pipefail

# Каталог хука — ДО `cd` и АБСОЛЮТНЫМ: хук зовут полным путём
# (`.claude/settings.json`), но при относительном `$0` строка `dirname` сама
# осталась бы относительной и после смены каталога указывала бы мимо
# `floor.sh`. Одного порядка «до cd» мало — нужен разрешённый путь (`9fda04b`).
here=$(cd "$(dirname "$0")" && pwd)

warn() {
  echo "старт окна: $1 — окно работает без этого; предполётную запускайте интерпретатором не ниже планки вручную" >&2
}

if [ "${CLAUDE_CODE_REMOTE:-}" != "true" ]; then
  exit 0
fi
cd "$CLAUDE_PROJECT_DIR" || { warn "нет каталога проекта"; exit 0; }

# ПОДПИСЬ КОММИТОВ КЛЮЧОМ ПЛАТФОРМЫ ВЫКЛЮЧЕНА — АВТОРСТВО НЕ ТРОНУТО (#1614).
# Образ окна включает `commit.gpgsign` глобально (`/root/.gitconfig`, ключ
# платформы), и стоп-хук платформы на каждом коммите требует переподписать его
# на `noreply@anthropic.com` со сбросом автора. Свод говорит обратное: автор —
# владелец, агент — соавтор трейлером (CLAUDE.md, «Подпись и открытие
# изменения»). Подпись ключом платформы на коммите владельца площадка всё равно
# зовёт Unverified, а в общую ветку уходит уплотнённый коммит очереди. Поэтому
# выключается только подпись и только в этом репозитории (`--local`): имя,
# почта и трейлеры не трогаются. Первым делом, до планки: её отказы выходят из
# хука раньше, а подпись от планки не зависит.
#
# ВЫКЛЮЧАТЕЛЬ — ПО ТЕКСТУ СТОП-ХУКА И ЗАМЕРУ, А НЕ ДОГАДКОЙ (107). Стоп-хук
# (`~/.claude/stop-hook-git-check.sh`) сверяет подпись только при
# `commit.gpgsign=true`; замер окна 23.10.2026: после `--local false` он
# перестал просить переподпись и спрашивал только неотправленное. Хук платформы
# вправе смениться — тогда совет вернётся, и это видно сразу.
#
# ГРАНИЦА НАЗВАНА (195): выключено в клоне проекта и его рабочих копиях
# (`git worktree` делит настройку). Другие клоны окна — каталог правил, соседи —
# своей настройки не получают: там подпись включена, пока их хук старта её не
# выключит.
if git config --local commit.gpgsign false 2>/dev/null; then
  echo "старт окна: подпись коммитов ключом платформы выключена — автор коммита владелец, агент соавтор трейлером (#1614)"
else
  # Свой отказ, не `warn`: совет про интерпретатор планки к подписи не относится.
  echo "старт окна: подпись коммитов не выключена — стоп-хук платформы попросит переподписать коммиты на noreply@anthropic.com, и совет не исполняется (#1614)" >&2
fi

# ЧИСЛА ПЛАНКИ В ХУКЕ НЕТ: `want` приходит из `floor.sh`, общего с обёрткой
# стража толчка (#1058). Его сверяет с `requires-python`
# `tests/test_session_start.py`, а на старте — сам хук, прочитав планку. Нет
# файла — предупреждение и выход 0, как у всякого сбоя старта.
unset want  # не из окружения окна: число только из floor.sh
[ -r "$here/floor.sh" ] || { warn "нет $here/floor.sh — число планки взять неоткуда"; exit 0; }
. "$here/floor.sh"
# ПУСТАЯ ПЛАНКА — СВОЯ ПРИЧИНА, КАК У ОБЁРТОК (взгляд на #1518, 195). Файл есть,
# но `want` не задаёт: под `set -u` хук падал бы ошибкой разбора, а без него
# ставил бы `uv python install ""` и винил интерпретатор.
[ -n "${want:-}" ] || { warn "$here/floor.sh не задаёт want — число планки взять неоткуда"; exit 0; }

if ! command -v "python$want" >/dev/null 2>&1; then
  { python3.12 -m venv /opt/uv \
      && /opt/uv/bin/pip install -q -U uv \
      && /opt/uv/bin/uv python install "$want" \
      && ln -sf "$(/opt/uv/bin/uv python find "$want")" "/usr/local/bin/python$want"; } \
    || warn "Python $want не поставлен"
fi

# Планку и список читает код, который уже их читает для предполётной. Без
# планки окружение не собирается вовсе: собранное наугад обещало бы то, чего
# площадка не скажет.
#
# ЧИТАЕТ ИНТЕРПРЕТАТОР ПЛАНКИ, А НЕ СИСТЕМНЫЙ python3 (взгляд на #1036). Код
# дерева пишется под планку — с #1036 и без `from __future__ import
# annotations`, — и системный 3.11 окна его исполнять не обязан: синтаксис
# планки в `check_env` или `paths` увёл бы хук в предупреждение молча. Набор
# исполняет этот разбор тем же `python<планка>`, что и хук, а не своим
# интерпретатором: набор вправе идти и выше планки, и синтаксис новее неё он
# пропустил бы, а хук упал бы (взгляд на #1049, 107). Ставится этот
# интерпретатор строкой выше, а без него окружение на планке не собрать всё
# равно.
read_tree() {
  "python$want" -c "
import sys
sys.path[:0] = ['scripts', 'packages/transport']
import check_env as c
if sys.argv[1] == 'floor':
    major, minor = c.python_floor()
    print(f'{major}.{minor}')
elif sys.argv[1] == 'local':
    print(' '.join(str(p) for _, p in c.local_packages()))
else:
    print(' '.join(f'{n.name}{n.bounds}' for n in c.needs().values()))
" "$1"
}
# Без интерпретатора планку не прочесть — и это его отсутствие, а не планки:
# предупреждение называет настоящую причину (взгляд на #1049).
command -v "python$want" >/dev/null 2>&1 || { warn "нет python$want — дерево читать нечем"; exit 0; }
# Отказ чтения называет и `want`: подняли планку, и код дерева уже на её
# синтаксисе — `python$want` его не прочтёт, и сверка ниже до расхождения не
# дойдёт. Тогда причина — именно `want`, а не сама планка (взгляд на #1057).
floor=$(read_tree floor) || { warn "планка не прочитана интерпретатором python$want — если планку подняли выше $want, поправьте want в .claude/hooks/floor.sh"; exit 0; }
if [ "$floor" != "$want" ]; then
  warn "планка $floor, а хук ставит python$want — поправьте want в .claude/hooks/floor.sh"
  exit 0
fi
tools=$(read_tree needs) || { warn "строки установки прогонов не прочитаны"; exit 0; }
locals=$(read_tree local) || { warn "пакеты дерева не прочитаны"; exit 0; }

if [ ! -x .venv/bin/python ] || [ "$(.venv/bin/python -c 'import sys; print("%d.%d" % sys.version_info[:2])')" != "$floor" ]; then
  rm -rf .venv
  "python$floor" -m venv .venv || { warn "окружение на $floor не собрано"; exit 0; }
fi
# ГОДНОЕ ОКРУЖЕНИЕ НЕ ПЕРЕСТАВЛЯЕТСЯ. Сверку делает тот же `check_env`, что
# зовёт предполётная: совпало — установки нет, и окно без сети получает уже
# собранное окружение, а не предупреждение (взгляд на #1024).
if ! .venv/bin/python scripts/check_env.py >/dev/null 2>&1; then
  # Пакеты дерева — РЕДАКТИРУЕМОЙ установкой, как советует `check_env`: копия
  # прятала бы от тестов правку пакета до следующего старта окна (взгляд на
  # #1024).
  editable=()
  for local in $locals; do
    editable+=(-e "$local")
  done
  # shellcheck disable=SC2086  # список — отдельные аргументы pip, а не одна строка
  .venv/bin/pip install -q $tools ${editable[@]+"${editable[@]}"} || { warn "инструменты проверки не поставлены"; exit 0; }
fi
# Установка из исходников оставляет в дереве `build/` пакета, и проверка
# типов видит модуль дважды: тот, что в пакете, и его копию в сборке. Сборка
# — след установки, а не дерево проекта, и убирается тем же заходом.
for local in $locals; do
  rm -rf "$local/build"
done

echo "export PATH=\"$CLAUDE_PROJECT_DIR/.venv/bin:\$PATH\"" >> "$CLAUDE_ENV_FILE"
exit 0
