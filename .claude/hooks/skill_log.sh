#!/bin/sh
# Обёртка журнала навыков: зовёт `skill_log.py` ИНТЕРПРЕТАТОРОМ ПЛАНКИ (217, #1449).
#
# ПРИЁМ ТОТ ЖЕ, ЧТО У СТРАЖА ТОЛЧКА (`push_guard.sh`). Хук исполняется в
# окружении процесса окна, где голый `python3` — системный интерпретатор образа,
# а не планки. Число планки — из `floor.sh`, общего с хуком старта (214). В
# локальном окне хук старта интерпретатор не ставит, поэтому вторым берётся
# `python3`, если он сам не ниже планки.
#
# СПЕРВА СПРОСИЛИ СЕМЬЮ (162): обёртка того же назначения есть у каталога —
# `ArtVsMark/Engineering-Incidents-Playbook:.claude/hooks/skill_log.sh`. Приём
# взят у неё, а не файл (153), и отличий два. Запасной `python3` здесь
# допускается, только если он сам не ниже планки, — каталог берёт одну
# `python<планка>`. Не записанный вызов выходит кодом 1, а не 0: почему —
# в докстроке `skill_log.py`.
#
# НЕТ ИНТЕРПРЕТАТОРА ПЛАНКИ — ВЫЗОВ НЕ ЗАПИСАН, НО ЭТО СКАЗАНО. Журнал —
# необязательный канал (084): в отличие от стража, он не закрывает работу окна
# кодом 2. Но и не молчит (045): код 1 площадка считает неблокирующей ошибкой и
# показывает причину человеку, а stderr при коде 0 он не увидел бы.
here=$(cd "$(dirname "$0")" && pwd)
unset want  # не из окружения окна: число только из floor.sh
[ -r "$here/floor.sh" ] && . "$here/floor.sh"
if [ -n "$want" ] && command -v "python$want" >/dev/null 2>&1; then
  exec "python$want" "$here/skill_log.py" "$@"
fi
if [ -n "$want" ] && command -v python3 >/dev/null 2>&1 \
  && python3 -c "import sys; sys.exit(sys.version_info[:2] < tuple(map(int, '$want'.split('.'))))" 2>/dev/null; then
  exec python3 "$here/skill_log.py" "$@"
fi
echo "журнал навыков: нет ни python${want:-?}, ни python3 не ниже ${want:-?} — вызов не записан. В облачном окне интерпретатор ставит хук старта — перезапустите окно; в локальном поставьте python${want:-?} сами (217)." >&2
exit 1
