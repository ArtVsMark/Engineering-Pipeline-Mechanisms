#!/bin/sh
# Обёртка совета о пачке: зовёт `bundle_hint.py` ИНТЕРПРЕТАТОРОМ ПЛАНКИ (217, #1708).
#
# ПРИЁМ ТОТ ЖЕ, ЧТО У ЖУРНАЛА НАВЫКОВ (`skill_log.sh`) и стража толчка: голый
# `python3` в окружении окна — системный интерпретатор образа, а не планки.
# Число планки — из `floor.sh`, общего с хуком старта (214).
#
# НЕТ ИНТЕРПРЕТАТОРА ПЛАНКИ — СОВЕТА НЕ БУДЕТ, НО ЭТО СКАЗАНО. Совет —
# необязательный канал (084): нарезку он не держит. Но и не молчит (045): код 1
# площадка считает неблокирующей ошибкой и показывает причину человеку.
here=$(cd "$(dirname "$0")" && pwd)
unset want  # не из окружения окна: число только из floor.sh
[ -r "$here/floor.sh" ] && . "$here/floor.sh"
if [ -z "$want" ]; then
  echo "совет о пачке: планка интерпретатора не прочитана — $here/floor.sh нет, он не читается или не задаёт want; совета не будет. Верните файл из общей ветки (214)." >&2
  exit 1
fi
if command -v "python$want" >/dev/null 2>&1; then
  exec "python$want" "$here/bundle_hint.py" "$@"
fi
if command -v python3 >/dev/null 2>&1 \
  && python3 -c "import sys; sys.exit(sys.version_info[:2] < tuple(map(int, '$want'.split('.'))))" 2>/dev/null; then
  exec python3 "$here/bundle_hint.py" "$@"
fi
echo "совет о пачке: нет ни python$want, ни python3 не ниже $want — совета не будет. В облачном окне интерпретатор ставит хук старта — перезапустите окно; в локальном поставьте python$want сами (217)." >&2
exit 1
